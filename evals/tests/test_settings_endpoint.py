#!/usr/bin/env python3
"""
Endpoint провайдера: поле не заполняется менеджером паролей и не роняет форму.

─── Как это нашлось ──────────────────────────────────────────────────────────
Владелец подвинул один ползунок температуры, нажал «Сохранить» и получил
«endpoint: ожидается http(s)-адрес либо пусто». Поля endpoint он не трогал, и
находится оно в другой секции экрана.

Разбор дал две независимые причины, и обе стоит держать закрытыми.

**Первая — форма подсказывает менеджеру паролей форму входа.** Поле endpoint
стоит вплотную к «Ключу провайдера» с `type="password"`. Безымянное текстовое
поле перед паролем — это ровно тот образец, по которому менеджеры паролей
подставляют логин. Подстановка приходит событием `change`, то есть попадает в
черновик молча: человек её не набирал и на экран в тот момент не смотрел.

Это не только про удобство. В поле оказывается чужое значение — вплоть до
почты или логина, — и оно уезжает на сервер при каждом сохранении, а оттуда в
логи. `autoComplete="off"` менеджеры паролей не соблюдают; помогает пара «имя
поля + признаки конкретных менеджеров», а для самого пароля — значение
`new-password`, которое браузеры как раз соблюдают.

**Вторая — адрес без схемы отвергался.** `foundation-models.api.cloud.ru/v1`
копируется из документации провайдера и из `.env` именно в таком виде. Человек
сообщил ровно то, что требовалось; форма записи — не повод для отказа.
Дописывание схемы ограничено похожим на хост: строка с `@` или с пробелом
отвергается по-прежнему, иначе `https://` превратил бы подставленный логин в
правдоподобный адрес.

**И третья, общая для обеих.** Претензия приходила ответом на сохранение и
печаталась общей строкой внизу экрана. Отказ был верным, а сообщение —
неадресным: связать его с полем в другой секции было не с чем. Поэтому проверка
теперь считается тем же кодом на клиенте и показывается у поля.

─── Уровни ───────────────────────────────────────────────────────────────────
Статический — по исходникам: атрибуты полей и общая функция разбора. Работает
где угодно.

Поведение самой нормализации проверяется рядом, в `apps/web/lib/settings.test.ts`
(`npm test -w apps/web`) — там оно исполняется, а не читается глазами.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
WEB = REPO / "apps" / "web"

PASS, FAIL = "OK", "FAIL"
results: list[tuple[str, str, str]] = []


def check(name: str, ok: bool, detail: str = "") -> None:
    results.append((name, PASS if ok else FAIL, detail))
    print(f"  {'OK  ' if ok else 'FAIL'}  {name}" + (f"  →  {detail}" if detail and not ok else ""))


def read(p: Path) -> str:
    return p.read_text("utf-8") if p.exists() else ""


print("== Статический уровень ==")

page = read(WEB / "app" / "settings" / "page.tsx")
lib = read(WEB / "lib" / "settings.ts")
spec = read(WEB / "lib" / "settings.test.ts")

check("экран настроек на месте", bool(page))
check("модуль настроек на месте", bool(lib))

# ─── Поле endpoint ───────────────────────────────────────────────────────────
#
# Блок берётся от метки поля до конца его <input>: искать атрибуты по всему
# файлу значило бы засчитать их от соседнего поля.
endpoint_block = ""
match = re.search(r'id="provider-endpoint".*?/>', page, re.S)
if match:
    endpoint_block = match.group(0)

check(
    "поле endpoint названо",
    'name="provider-endpoint"' in endpoint_block,
    "у поля нет атрибута name — менеджер паролей опознаёт такое поле эвристикой "
    "и подставляет в него логин от соседнего пароля",
)
check(
    "поле endpoint закрыто от менеджеров паролей",
    "data-1p-ignore" in endpoint_block and "data-lpignore" in endpoint_block,
    "нет признаков для менеджеров паролей; autoComplete='off' они не соблюдают",
)

# ─── Поле ключа ──────────────────────────────────────────────────────────────
key_block = ""
match = re.search(r'name="provider-api-key".*?/>', page, re.S)
if match:
    key_block = match.group(0)

check(
    "ключ провайдера просит новый пароль, а не «off»",
    'autoComplete="new-password"' in key_block,
    "autoComplete='off' у поля пароля игнорируется — и вместе с ним браузер "
    "предлагает заполнить соседнее поле логином",
)

# ─── Общая проверка на две стороны ───────────────────────────────────────────
check(
    "разбор endpoint вынесен в общую функцию",
    "export function normalizeEndpoint" in lib,
    "нет normalizeEndpoint — значит клиент и сервер проверяют адрес порознь и "
    "молча разойдутся: экран разрешит то, что роут отвергнет",
)
check(
    "экран показывает претензию у поля",
    "normalizeEndpoint" in page and "endpointError" in page,
    "экран не зовёт общую проверку — отказ снова придёт общей строкой снизу, "
    "без указания на поле",
)
# Текст ошибки — строковый литерал без подстановок. Шаблонная строка означала бы
# ровно одно: в сообщение попало само значение поля.
error_texts = re.findall(r"error:\s*(.+?),?\n", lib.split("normalizeEndpoint", 1)[-1])
check(
    "значение поля не попадает в текст ошибки",
    bool(error_texts) and all("${" not in t and "`" not in t for t in error_texts),
    "в сообщение об ошибке подставляется само значение — а там может оказаться "
    "подставленный менеджером логин, и он уедет в ответ и в логи (§7): "
    f"{error_texts}",
)
check(
    "поведение нормализации исполняется тестом, а не описано словами",
    "normalizeEndpoint" in spec and "user@example.com" in spec,
    "нет apps/web/lib/settings.test.ts с проверкой нормализации",
)

print()
n_fail = sum(1 for _, s, _ in results if s == FAIL)
print(f"Итог: OK={len(results) - n_fail} FAIL={n_fail}")
if n_fail:
    print("\nНевыполненные условия:")
    for name, status, detail in results:
        if status == FAIL:
            print(f"  · {name}" + (f" — {detail}" if detail else ""))
sys.exit(1 if n_fail else 0)
