#!/usr/bin/env bash
#
# Развёртывание AGORA на боевом сервере.
#
# ─── Зачем скрипт, если это одна команда docker compose ──────────────────────
# Потому что команда НЕ одна, и выбор между вариантами стоил рабочего экрана.
#
# 19.08.2026 я собрал web с оверлеем `docker-compose.managed.yml`. Оверлей
# написан для случая, когда ВСЕ хранилища managed, и выставляет
# `PGSSLROOTCERT=/certs/root.crt`. На этом сервере Postgres — локальный
# контейнер `agora-postgres-1`, у него `ssl = off`, а managed только Mongo,
# Valkey и S3.
#
# Дальше — самое неприятное. `apps/web/lib/server/db.ts` дописывает
# `sslrootcert=` в строку подключения, когда переменная задана, а `node-postgres`
# считает ЛЮБУЮ ssl-настройку требованием шифрования. Страницы начали падать
# с «The server does not support SSL connections», и на экране это выглядело как
# ошибка отрисовки серверного компонента с одним лишь digest — то есть указывало
# куда угодно, только не на развёртывание.
#
# Воркер при этом остался жив, и это сбивает с толку сильнее всего: `psycopg`
# идёт через libpq, где `sslmode` по умолчанию `prefer`, и молча откатывается на
# нешифрованное соединение. Один и тот же неверный оверлей ломает веб и не
# трогает воркера — выглядит как дефект веба, а не как ошибка развёртывания.
#
# Отсюда правило: на этом сервере оверлей `managed` НЕ применяется. Он остаётся
# в репозитории для развёртывания, где managed и Postgres тоже.
#
# ─── Что здесь есть ──────────────────────────────────────────────────────────
#   ./infra/deploy.sh            — пересобрать и поднять web и worker
#   ./infra/deploy.sh web        — только web
#   ./infra/deploy.sh worker     — только worker (сборка ~10 минут: torch)
#
# Миграции этот скрипт НЕ применяет: они идут отдельно и осознанно
# (CLAUDE.md §5), а «развернуть» и «поменять схему» — разные решения.

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

[ -f .env.local ] || { echo ".env.local не найден в $REPO" >&2; exit 1; }

# ─── Ворота: не пересобирать посреди работы ─────────────────────────────────
#
# Генерация аудитории живёт в persona_sets, а не в tasks; пересборка воркера
# посреди неё теряет модельную работу и оставляет набор в generating навсегда.
# Именно так 18.09.2026 погибли два набора по сорок персон.
#
# Запрос идёт через `docker exec` в контейнер базы, а не через preflight.py.
# Причина конкретная и стоила одного заблокированного развёртывания: адреса в
# .env.local — это имена докер-сети (`postgres:5432`), и с хоста они не
# резолвятся. preflight.py, поставленный сюда обязательными воротами, падал с
# «Temporary failure in name resolution» на каждом запуске, то есть развернуть
# нельзя было вообще ничего. Проверять инфраструктуру снаружи сети, которой она
# принадлежит, — не строгость, а неработающая проверка.
#
# preflight.py никуда не делся: он проверяет Mongo, S3 и Redis и запускается
# оттуда, где эти имена видны. Здесь нужны ровно две таблицы, и до них есть
# прямой путь.
busy=$(docker exec agora-postgres-1 psql -U agora -d agora -t -A -c \
  "SELECT (SELECT count(*) FROM tasks WHERE status IN ('RUNNING','QUEUED'))
        + (SELECT count(*) FROM persona_sets WHERE status = 'generating')")
if [ "${busy:-0}" != "0" ]; then
  echo "ОТКАЗ: идёт работа — прогонов RUNNING/QUEUED и генераций аудитории: $busy" >&2
  docker exec agora-postgres-1 psql -U agora -d agora -c \
    "SELECT 'tasks' AS где, status, count(*) FROM tasks
       WHERE status IN ('RUNNING','QUEUED') GROUP BY status
     UNION ALL
     SELECT 'persona_sets', status, count(*) FROM persona_sets
       WHERE status = 'generating' GROUP BY status" >&2
  echo "Пересборка убьёт эту работу посреди задачи. Дождитесь завершения." >&2
  exit 1
fi
echo "  OK  ворота: активных прогонов и генераций нет"

SERVICES=("$@")
# Умолчание перечисляет ВСЕ службы, которые собираются из этого репозитория.
#
# 16.09.2026 здесь стояло `(web worker)`, а чат живёт в `agent-api`: маршрут
# /api/chat/reply обслуживает именно он. Инструменты чата были влиты,
# развёрнуты этим скриптом с умолчанием — и не доехали. Контейнер
# `agora-agent-api-1` на момент «успешного» развёртывания показывал `Up 2
# weeks`, и ни одна проверка не пожаловалась: скрипт честно поднял ровно то,
# что ему назвали.
#
# §3-бис написан про такой случай: сделанная и неразвёрнутая работа выглядит
# готовой и в отчёте, и в main. Тогда правка не была развёрнута вовсе; здесь —
# наполовину, что заметить ещё труднее.
#
# Список, а не `up -d --build` без имён: в compose есть службы без своего кода
# (база и прочее), пересобирать их незачем. Соответствие списка и compose
# держит `apps/web/lib/deploy-services.test.ts`: служба с `build:` обязана быть
# здесь, иначе её правки будут уезжать в main и не доезжать до боевого.
[ ${#SERVICES[@]} -eq 0 ] && SERVICES=(web worker agent-api)

# ─── Что именно собирается ────────────────────────────────────────────────
# 11.09.2026 сервер потерял доступ к GitHub (репозиторий стал приватным, ключей
# на нём нет). `git pull` упал, но вызов был написан как `git pull | tail && ./deploy.sh`
# — конвейер отдаёт код возврата `tail`, то есть ноль, — и скрипт собрал ОБРАЗ
# ПО СТАРОМУ КОДУ, отрапортовав успехом.
#
# Заметить это можно было только сверив коммит. Поэтому скрипт печатает его сам
# и предупреждает, если рабочее дерево отстало от того, что знает origin.
#
# Не отказ, а предупреждение: `git fetch` может быть недоступен (ровно наш
# случай), и падать из-за этого значило бы запретить развёртывание там, где код
# уже доставлен другим способом. Но молчать нельзя — молчание и стоило прохода.
HEAD_SHA="$(git rev-parse --short HEAD)"
HEAD_SUBJ="$(git log -1 --format=%s)"
echo "── Собирается ────────────────────────────────────────────────────────"
echo "  коммит: $HEAD_SHA  $HEAD_SUBJ"
if git rev-parse --verify --quiet origin/main >/dev/null; then
    BEHIND="$(git rev-list --count "HEAD..origin/main" 2>/dev/null || echo 0)"
    if [ "$BEHIND" != "0" ]; then
        echo >&2
        echo "ВНИМАНИЕ: рабочее дерево отстаёт от origin/main на $BEHIND коммит(ов)." >&2
        echo "Собирается СТАРЫЙ код. Обновите дерево или подтвердите, что так и надо." >&2
        echo >&2
    fi
fi
echo

# Только базовый compose. Список сервисов — явно: `up -d` без имён поднял бы и
# профильные хранилища, то есть контейнерные Mongo и Valkey рядом с managed.
docker compose -f infra/docker-compose.yml --env-file .env.local \
    up -d --build "${SERVICES[@]}"

echo
echo "── Проверка ──────────────────────────────────────────────────────────"
# --env-file нужен и здесь: без него compose не подставит обязательные
# переменные и упадёт на интерполяции, а `|| echo '?'` превратит отказ в
# безобидный вопросительный знак. Проверка, которая молча не работает, хуже
# отсутствующей — она создаёт ощущение, что развёртывание проверено.
for s in "${SERVICES[@]}"; do
    status="$(docker compose -f infra/docker-compose.yml --env-file .env.local \
        ps --format '{{.Status}}' "$s" 2>&1)" || {
        echo >&2 "не удалось спросить состояние $s:"; echo "$status" >&2; exit 1; }
    printf '%-8s %s\n' "$s" "${status:-НЕ ЗАПУЩЕН}"
    [ -n "$status" ] || exit 1
done

# Ровно та ошибка, ради которой скрипт и появился. Если она вернётся, это
# должно быть видно сразу, а не через сообщение об ошибке отрисовки.
if docker logs --since 2m agora-web-1 2>&1 | grep -q "does not support SSL"; then
    echo >&2
    echo "ВНИМАНИЕ: web не подключается к Postgres по SSL." >&2
    echo "Скорее всего применён оверлей managed — смотрите шапку этого скрипта." >&2
    exit 1
fi
