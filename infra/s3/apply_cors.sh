#!/usr/bin/env bash
#
# AGORA · CORS-политика бакета
#
# ─── Зачем это файл, а не действие в панели провайдера ───────────────────────
# Причина та же, по которой схема БД меняется миграцией (CLAUDE.md §5):
# настройка, сделанная руками в кабинете, не видна в репозитории. Её нельзя
# отревьюировать, нельзя повторить на втором стенде и нельзя обнаружить, когда
# она пропадёт. Здесь она — файл рядом с кодом.
#
# ─── Что чинится ────────────────────────────────────────────────────────────
# Загрузка видео из браузера уходит PUT-запросом на presigned URL, то есть на
# ЧУЖОЙ для страницы домен. Без CORS браузер шлёт preflight OPTIONS, получает
# 403 без заголовков Access-Control-*, и XHR падает событием `error` — в
# интерфейсе это «соединение с хранилищем оборвалось».
#
# Сбивает с толку то, что серверные загрузки при этом работают: CORS —
# механизм браузера, и `evals/e2e_run.py` его не касается вовсе. Отсюда
# ощущение «хранилище живо, сломан интерфейс», хотя сломана политика бакета.
#
# ─── Как запускать ──────────────────────────────────────────────────────────
#   set -a; . ./.env.local; set +a
#   ./infra/s3/apply_cors.sh
#
# Идемпотентно: PutBucketCors заменяет политику целиком, повторный прогон даёт
# тот же результат.
set -euo pipefail

: "${S3_ENDPOINT:?S3_ENDPOINT не задан — см. .env.local}"
: "${S3_BUCKET:?S3_BUCKET не задан}"
: "${S3_ACCESS_KEY:?S3_ACCESS_KEY не задан}"
: "${S3_SECRET_KEY:?S3_SECRET_KEY не задан}"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# boto3 живёт в образе воркера — туда же едет и этот скрипт. Ставить aws-cli на
# хост ради одной операции значит завести вторую среду (CLAUDE.md §9).
CORS_JSON="$(cat "$HERE/cors.json")"
export CORS_JSON

docker exec -i \
  -e S3_ENDPOINT -e S3_BUCKET -e S3_ACCESS_KEY -e S3_SECRET_KEY -e S3_REGION -e CORS_JSON \
  "${WORKER_CONTAINER:-agora-worker-1}" python3 - < "$HERE/apply_cors.py"
