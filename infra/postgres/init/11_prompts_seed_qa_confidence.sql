-- AGORA · 11 · Засев QA-промптов: вердикт QA обязан нести confidence (задача #19)
--
-- Отдельный файл, а не правка 07_prompts_seed.sql: применённая миграция не
-- редактируется (§5 CLAUDE.md), а 07 к тому же генерируется скриптом
-- generate-prompts-seed.mjs — перегенерация переписала бы тексты всех
-- тринадцати промптов заодно, невидимо для ревью.
--
-- Почему UPDATE, а не INSERT ... ON CONFLICT DO NOTHING, как в 10. Там ключа
-- ещё не было; здесь три строки уже засеяны 07-й, и DO NOTHING не сделал бы
-- ничего. Правится ровно дефолт (tenant_id IS NULL): версии, отредактированные
-- командой в Промпт-студии, не трогаются — иначе правка задним числом изменила
-- бы инструкцию, по которой уже шли прогоны.
--
-- Шаблон кладётся ЦЕЛИКОМ, а не патчится по подстроке. Точечный replace оставил
-- бы в базе старый текст с дописанным полем, и файл prompts/qa.*.md перестал бы
-- совпадать с тем, что уходит в модель. Расхождение такого рода ничего не
-- ломает заметно: прогон идёт по инструкции, которой нет ни в одном файле.
--
-- Идемпотентность — по условию на template: строка, где confidence уже есть,
-- под UPDATE не попадает, и повторный migrate.sh не поднимает версию второй раз.
--
-- Зачем поле: PRD §14.1 и Decision Log #16. Эскалация на модель большего
-- размера идёт по низкому confidence судьи. Без числа в ответе эскалировать
-- нечего, и «эскалация только при низкой уверенности» вырождается либо в
-- «никогда», либо в «на каждом ответе» — то есть в разы стоимости прогона.

UPDATE prompts
SET template = '# qa.consistency (seed) — LLM-as-judge
Переменные: {{persona_dna}}, {{persona_answer}}. Судья не видит других ответов
и не видит прежних вердиктов QA — иначе он согласуется с ними, а не с материалом.
---
Оцени, согласуется ли ответ персоны с её профилем. Профиль: {{persona_dna}}
Ответ: {{persona_answer}}
Проверь: соответствуют ли баллы тексту-обоснованию; не противоречат ли оценка и эмоции
ценностям/характеру/сегменту персоны (напр. пацифист в восторге от сцены насилия = флаг).

Арифметические противоречия (баллы вне 1–10, оценка против готовности досмотреть)
уже проверены до тебя правилами. Здесь ищи то, что видно только по смыслу.

Верни JSON:
{"consistency_score": <0..10>, "flags": ["<противоречие>"], "verdict": "<ok|regenerate>",
 "confidence": <0.0..1.0>}.
Порог: consistency_score < 7 → regenerate.

`confidence` — твоя уверенность в СОБСТВЕННОМ вердикте, а не оценка ответа. Ставь низкую,
когда профиль скуп на детали или противоречие спорно: по низкой уверенности ответ уйдёт
на перепроверку моделью большего размера, и это дешевле ошибки в обе стороны.
Только JSON.
',
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'qa.consistency'
  AND template NOT LIKE '%confidence%';

UPDATE prompts
SET template = '# qa.grounding (seed) — LLM-as-judge
Переменные: {{persona_answer}}, {{video_understanding}}.
---
Проверь, что персона ссылается ТОЛЬКО на реально существующие в материале детали.
Материал (единственная правда): {{video_understanding}}
Ответ персоны и её grounding_refs: {{persona_answer}}
Найди выдуманные сцены/реплики/детали, которых в материале нет.

Таймкоды за пределами длительности ролика уже проверены до тебя правилами — это
арифметика. Твоя часть другая: таймкод попадает в ролик, а описанного в нём не было.

Верни JSON:
{"grounded": <true|false>, "hallucinations": ["<выдуманная деталь>"],
 "verdict": "<ok|regenerate>", "confidence": <0.0..1.0>}.

`confidence` — уверенность в СОБСТВЕННОМ вердикте, а не оценка ответа. Ставь низкую,
когда описание сцены в материале обобщённое и деталь могла в нём быть: по низкой
уверенности ответ уйдёт на перепроверку моделью большего размера.
Только JSON.
',
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'qa.grounding'
  AND template NOT LIKE '%confidence%';

UPDATE prompts
SET template = '# qa.diversity (seed)
Переменные: {{all_persona_answers}}, {{expected_variance}}.
---
Оцени разнообразие ответов выборки (защита от mode collapse). Ответы: {{all_persona_answers}}
Числовые метрики — доля уникальных биграмм и дисперсия баллов — уже посчитаны до тебя
и лежат в {{expected_variance}} вместе с порогами.

Твоя часть — то, чего числа не видят: разными словами об одном и том же. Двадцать
непохожих формулировок одной и той же мысли дают высокий distinct-2 и при этом означают
ровно то, от чего мы защищаемся. Смотри на позиции и аргументы, а не на лексику.

Верни JSON:
{"score_variance": {"<критерий>": <разброс>}, "text_diversity": <0.0..1.0>,
 "collapsed": <true|false>, "note": "<если схлопнулось — где именно>",
 "verdict": "<ok|regenerate>", "confidence": <0.0..1.0>}.

`confidence` — уверенность в СОБСТВЕННОМ вердикте, а не оценка выборки. На выборке меньше
пяти ответов она обязана быть низкой: по такому числу наблюдений разброс не измеряется.
Только JSON.
',
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'qa.diversity'
  AND template NOT LIKE '%confidence%';
