-- 36. Снятие переопределений промптов, которые не могут работать.
--
-- ─── Что произошло ──────────────────────────────────────────────────────────
-- У арендатора с 03.08.2026 действовало собственное переопределение
-- `analytics.report`. Целиком оно выглядело так:
--
--     test {{content}}
--
-- Стадия аналитики подставляет шесть переменных: {{aggregate}},
-- {{retention_risk_points}}, {{all_persona_answers}}, {{survey}},
-- {{content_title}}, {{qa_flags}}. Ни одна в шаблоне не названа, а {{content}}
-- не подставляет никто. Модель получала 64 токена и отвечала
-- `{"content": "test {{content}}"}`.
--
-- Итог виден в прогоне 0051 (19.08.2026): narrative, themes, disagreements,
-- strengths, weaknesses — пустые, rationales — пустой, degraded — тоже пустой.
-- Отчёт не сломался; он молча стал наполовину числовым.
--
-- ─── Почему это чинится миграцией ───────────────────────────────────────────
-- Проверка контракта при сохранении (apps/web/lib/prompt-contract.ts) закрывает
-- дверь на будущее, но не трогает то, что уже лежит в базе. Строка активна и
-- будет действовать на каждом следующем прогоне, пока её кто-нибудь не заметит,
-- — а заметить её можно только по пустому нарративу.
--
-- ─── Насколько узко ─────────────────────────────────────────────────────────
-- Удаляются ТОЛЬКО версии арендаторов, в тексте которых нет ни одной переменной
-- из дефолта того же ключа. Такой шаблон не может работать по построению: он не
-- получает данных стадии вообще. Переопределение, переписанное человеком и
-- сохранившее хотя бы одну переменную, не трогается — судить о его качестве
-- миграция не вправе.
--
-- Дефолты (tenant_id IS NULL) не трогаются никогда: они и есть то, на что
-- откатится резолвер.
--
-- Идемпотентно: повторный прогон не находит таких строк и ничего не делает.

BEGIN;

WITH default_vars AS (
    SELECT
        key,
        ARRAY(
            SELECT DISTINCT m[1]
            FROM regexp_matches(template, '\{\{\s*([a-zA-Z0-9_.]+)\s*\}\}', 'g') AS m
        ) AS names
    FROM prompts
    WHERE tenant_id IS NULL AND is_active = true
),
unusable AS (
    SELECT p.id
    FROM prompts p
    JOIN default_vars d ON d.key = p.key
    WHERE p.tenant_id IS NOT NULL
      AND cardinality(d.names) > 0
      -- Ни одна переменная стадии в шаблоне не встречается.
      AND NOT EXISTS (
          SELECT 1
          FROM unnest(d.names) AS name
          WHERE p.template LIKE '%{{' || name || '}}%'
             OR p.template ~ ('\{\{\s*' || name || '\s*\}\}')
      )
)
DELETE FROM prompts WHERE id IN (SELECT id FROM unusable);

COMMIT;
