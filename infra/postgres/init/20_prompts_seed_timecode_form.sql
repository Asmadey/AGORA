-- ─── Что нашёл чистый прогон на сценной сетке ───────────────────────────────
-- QA забраковал 8 ответов из 12, все по grounding, из них три — правилом, с
-- одинаковой причиной:
--
--     grounding_refs: таймкод 44:48 за пределами ролика (02:42)
--
-- 44:48 — не сорок четыре минуты. Это ячейка таймлайна «с 44-й по 48-ю секунду»:
-- персона получала {"start": 44.0, "end": 48.0} и на просьбу дать «таймкод»
-- склеивала числа через двоеточие. Правило читало результат как MM:SS и
-- справедливо видело выход за длительность.
--
-- Ответ при этом был ВЕРНЫМ — персона сослалась на реальный отрезок, — а
-- забраковали его за форму, которую подсказали мы сами.
--
-- Починка двойная и обе половины обязательны: ячейка пакета теперь несёт готовую
-- строку `time` («0:44–0:48»), а промпт требует брать её оттуда. Без первой
-- половины требовать нечего, без второй — персона продолжит собирать сама.
--
-- Идемпотентно по условию на template.

