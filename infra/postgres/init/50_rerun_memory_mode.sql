-- AGORA · 50 · Режим памяти при перезапуске исследования
--
-- Родительский прогон и режим памяти — разные решения. Наличие
-- `parent_task_id` говорит, с чем сравнивать результат, но не должно само по
-- себе заставлять персону видеть прошлые ответы: пользователь может выбрать
-- чистый прогон для того же материала и аудитории.

ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS carry_over_memory boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN tasks.carry_over_memory IS
  'true — режим «Допрос»: ответы этой персоны из parent_task_id передаются в контекст, '
  'false — «Чистый прогон»: анкета задаётся в изоляции без прежних ответов.';
