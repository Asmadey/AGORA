-- ─────────────────────────────────────────────────────────────────────────
-- 33. Словарь «досмотрит» приводится к словарю корпуса
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что чинится. Владелец увидел в списке персон разнобой: одни отвечали на
-- «досмотрит?» процентами, другие словами — «хотелось досмотреть», «скорее
-- досмотреть». Причина не в модели, а в том, что словарей для одного поля было
-- ТРИ:
--
--   корпус ВЦИОМ             3 закрытых значения (140 / 22 / 3 из 165 записей)
--   промпт персоны           4 подсказки, придуманных отдельно от корпуса
--   правило в том же промпте 2 («удержание → продолжить/остановиться»)
--
-- Корпус — единственный из трёх, который что-то значит: на нём заземлён
-- продукт, и только с ним ответы персон сравнимы с ответами живых людей.
--
-- Почему replace(), а не новая версия целиком. Промпт правился четырьмя
-- миграциями (07, 13, 20, 22), у арендатора может быть своя редакция из
-- Промпт-студии, и подмена шаблона целиком стёрла бы её. Точечная замена
-- трогает ровно ту строку, о которой идёт речь; если её нет — не меняет
-- ничего, и это верное поведение для чужой редакции.
--
-- Приведение уже полученного ответа делает воркер
-- (agent_core/schemas/answer.py): ограничить формулировку на входе нечем —
-- строгий режим для ответа персоны выключен по замеру (8 разобранных ответов
-- из 12 со схемой против 12 из 12 без неё). Промпт и приведение обязаны
-- называть один словарь, иначе приведение станет молчаливым переписыванием.

BEGIN;

UPDATE prompts
SET template = replace(
      replace(
        template,
        '"retention_intent": "<хотелось досмотреть | скорее досмотреть | скорее выключить | выключил бы>",',
        '"retention_intent": "<Скорее хотелось досмотреть до конца | Скорее хотелось остановить просмотр | Затрудняюсь ответить — ровно одна из трёх формулировок>",'
      ),
      -- Без «удержание → » впереди: миграция 22 переписала этот абзац, и там
      -- стрелка осталась на предыдущей строке. Замена, привязанная к тексту в
      -- одну строку, не нашла бы ничего и промолчала бы об этом.
      'продолжить/остановиться',
      'одна из трёх формулировок retention_intent'
    )
WHERE key = 'respondent.user'
  AND (template LIKE '%хотелось досмотреть | скорее досмотреть%'
       OR template LIKE '%продолжить/остановиться%');

COMMIT;
