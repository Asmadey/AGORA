-- ─────────────────────────────────────────────────────────────────────────
-- 31. Каталог моделей транскрипции: в схему добавляется parakeet
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что чинится. Настройки предлагают parakeet-tdt-0.6b-v3 и whisper large-v3 —
-- ровно то, что лежит в образе воркера. Схема же знала только whisper:
--
--     CHECK (whisper_model IN ('large-v3', 'large-v3-turbo'))   -- 02_schema.sql
--
-- Выбор parakeet в интерфейсе сохранялся запросом, который падал на 23514, и
-- владелец видел «внутреннюю ошибку». Симптом честный, но бесполезный: ошибка
-- приходила от базы, а причина лежала в третьем по счёту списке моделей — том,
-- о котором тест сверки каталогов не знал (теперь знает).
--
-- Почему turbo уходит. Его нет в образе, и его выбор уводил бы прогон качать
-- полтора гигабайта весов после того, как ролик залит, — а выглядело бы это
-- случайно долгой транскрипцией, а не нехваткой модели. Ограничение — это
-- последняя граница между интерфейсом и прогоном; оставлять в ней имя, которое
-- нельзя выполнить, значит держать дверь в состояние, из которого нет выхода.
--
-- Что со строками, где turbo уже стоит. Их надо перевести ДО пересоздания
-- ограничения, иначе ALTER не пройдёт валидацию существующих данных и миграция
-- упадёт на боевой базе — там такая строка есть (прогон № 0050).

BEGIN;

-- Сначала данные, потом ограничение: обратный порядок падает на валидации.
UPDATE settings
   SET whisper_model = 'large-v3'
 WHERE whisper_model NOT IN ('parakeet-tdt-0.6b-v3', 'large-v3');

ALTER TABLE settings DROP CONSTRAINT IF EXISTS settings_whisper_model_check;

ALTER TABLE settings
  ADD CONSTRAINT settings_whisper_model_check
  CHECK (whisper_model IN ('parakeet-tdt-0.6b-v3', 'large-v3'));

-- Умолчание схемы идёт следом за умолчанием интерфейса: строка настроек,
-- созданная в обход роута, иначе получала бы медленную модель молча.
ALTER TABLE settings ALTER COLUMN whisper_model SET DEFAULT 'parakeet-tdt-0.6b-v3';

COMMIT;
