-- AGORA · 23 · Автор набора персон и его наследование персонами
--
-- ─── Зачем ──────────────────────────────────────────────────────────────────
-- У прогона автор был с самого начала (`tasks.created_by`), у персон — нет. В
-- команде из нескольких человек реестр персон показывал сотни карточек, по
-- которым нельзя понять, чья это аудитория и к какому исследованию она
-- относилась. Удалять такие персоны страшно ровно потому, что непонятно, чужие
-- они или свои.
--
-- ─── Почему на наборе, а не только на персоне ───────────────────────────────
-- Персоны создаются пачкой, одним заданием, одним человеком. Автор — свойство
-- этого задания, и хранить его только на персонах значило бы повторить одно и
-- то же значение шестьдесят раз, а набор без персон (упавшая генерация) остался
-- бы вовсе без автора — то есть именно тот случай, когда спросить «чьё это»
-- нужнее всего.
--
-- На персоне он тоже нужен: реестр показывает персон вперемешку, без набора, и
-- джойн на каждую карточку ради одного поля — лишняя работа на списке из сотен
-- строк.
--
-- ─── ON DELETE SET NULL ─────────────────────────────────────────────────────
-- Тот же выбор, что у `tasks.created_by`: уход человека из команды не должен
-- уносить аудиторию, на которой построены отчёты. NULL читается как «автор
-- неизвестен» — честнее, чем удалённая строка.

BEGIN;

ALTER TABLE persona_sets
  ADD COLUMN IF NOT EXISTS created_by uuid REFERENCES users(id) ON DELETE SET NULL;

ALTER TABLE personas
  ADD COLUMN IF NOT EXISTS created_by uuid REFERENCES users(id) ON DELETE SET NULL;

COMMENT ON COLUMN persona_sets.created_by IS
  'Кто заказал генерацию. NULL — набор создан до появления колонки либо автор удалён.';
COMMENT ON COLUMN personas.created_by IS
  'Наследуется от набора при записи. Дублирование намеренное: реестр показывает '
  'персон вперемешку, и джойн ради одного поля на списке из сотен строк — лишняя работа.';

COMMIT;
