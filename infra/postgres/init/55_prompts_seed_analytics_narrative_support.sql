-- AGORA · 55 · analytics.report: опора наблюдается, но не режет нарратив
--
-- Решение владельца 18.09.2026: промпт по-прежнему просит таймкоды и цитаты,
-- но код больше не скрывает утверждения без них. Фильтр съедал связный синтез
-- на прогоне 0094, а запись об отсеве в `degraded` выглядела как поломка.
--
-- Правим только этот фрагмент уже засеянного шаблона. Так миграция остаётся
-- короткой, идемпотентной и не стирает пользовательскую редакцию целиком:
-- повторный запуск не найдёт старый текст, а версия увеличится только один раз.

BEGIN;

UPDATE prompts
SET template = replace(
  template,
  'Правило, по которому текст проверяется автоматически: КАЖДОЕ утверждение обязано нести
опору — таймкод вида 04:10 либо дословную цитату персоны в кавычках. Утверждения без
опоры отсеиваются кодом и в отчёт не попадают, поэтому абзац вида «аудитория в целом
настроена положительно» будет просто выброшен. Пиши так: «После 04:10 трое из пяти
заявили о желании выключить», «Персона 4: „Бросил бы на 04:30“».',
  'Требование к качеству синтеза: КАЖДОЕ утверждение сопровождай опорой - таймкодом
вида 04:10 либо дословной цитатой персоны в кавычках. Пиши так: «После 04:10
трое из пяти заявили о желании выключить», «Персона 4: „Бросил бы на 04:30“».'
),
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'analytics.report'
  AND version = 3
  AND template LIKE '%Правило, по которому текст проверяется автоматически%';

COMMIT;
