-- ─────────────────────────────────────────────────────────────────────────
-- 54. persona.enrich: портрет пишется про ту персону, которую так и назовут
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что меняется. В промпт добавлена переменная `{{name}}`: имя персоны названо
-- отдельной строкой и вынесено в требования к тексту. Файл
-- `prompts/persona.enrich.md` правится тем же изменением; миграция приводит к
-- нему копию в базе.
--
-- ─── Почему ──────────────────────────────────────────────────────────────
-- Персона «Наталья», seed 272743267, имела портрет «Анна, 41-летняя жительница
-- Санкт-Петербурга…». Замер по набору 170c318c:
--
--     персон в наборе                                    20
--     портретов, содержащих собственное имя персоны       0
--     портретов с ЧУЖИМ именем                            5
--
-- Пятнадцать выкрутились безымянно («Ей 30 лет…»), пять назвали — и все пять
-- назвали чужое имя. Своё не назвал никто, и это не невезение: имени у модели
-- не было вовсе.
--
-- `generate_named` возвращает пары «имя, DNA», но дальше по конвейеру ехала
-- только DNA; имена лежали отдельным списком и приклеивались к персонам при
-- записи в базу. Докстринг `generate_named` описывает, где это разошлось:
-- раньше имя «подставлялось в narrative и выбрасывалось», потом его сохранили
-- в колонку — а до генератора портрета оно так и не доехало.
--
-- Расхождение не косметическое: портрет уезжает в промпт опроса как описание
-- персоны самой себе (`respondent/run.py`, `{{verbatim_examples}}`), то есть
-- Наталья отвечала на анкету, читая про Анну.
--
-- Решение владельца 18.09.2026: передавать имя в промпт, а не приклеивать в
-- конце.
--
-- ─── Зачем миграция, если код читает файл ────────────────────────────────
-- `persona/enrich.py` берёт шаблон с диска, из базы его не запрашивает никто.
-- На поведение генерации миграция не влияет. Нужна она затем же, зачем 45 и 47:
-- шаблон виден в Промпт-студии и читается как действующая инструкция, а
-- расхождение файла и засева ловит `evals/tests/test_task26_prompt_studio.py`.
--
-- Идемпотентно: повторный прогон присваивает то же значение. Сравнения текста
-- в WHERE нет — у `prompts` нет ни триггеров, ни `updated_at`.

