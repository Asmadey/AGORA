-- AGORA · 21 · Валидация персоны: вердикт на строке + промпт persona.validate
--
-- ─── Зачем эта фаза ─────────────────────────────────────────────────────────
-- Персона собирается в два шага: атрибуты сэмплируются из долей корпуса
-- (`random.Random(seed)`, модель не участвует), затем модель переписывает по
-- ним связный портрет. Второй шаг идёт при температуре 0.9 — так задумано, без
-- разброса формулировок двадцать персон с похожей DNA дают почти совпадающий
-- текст, и mode collapse становится свойством настройки.
--
-- У этого разброса есть цена: текст может разойтись с атрибутами, из которых
-- он собран, или досочинить биографию. Такая персона потом отвечает на анкету,
-- и её выдумка приезжает в отчёт как данные исследования.
--
-- ─── Почему проверяется СВЯЗНОСТЬ, а не соответствие датасету ───────────────
-- Спрашивать модель «соответствует ли персона датасету» бессмысленно: персона
-- ПО ПОСТРОЕНИЮ собрана из долей этого датасета, и ответ всегда будет «да».
-- Такая проверка зелена всегда и не ловит ничего — худший вид проверки, потому
-- что создаёт уверенность, не создавая гарантии.
--
-- Статистическое соответствие корпусу уже меряет метрика persona_grounding
-- (evals/check.py) — по распределениям, а не вызовом модели.
--
-- ─── Форма хранения ─────────────────────────────────────────────────────────
-- Вердикт лежит на строке персоны, а не сводкой по набору: пересоздаётся
-- конкретная персона, и знать, какая именно и почему, нужно поимённо. Пустой
-- объект — «не проверялась»: так выглядят все наборы, созданные до этой
-- миграции, и отличать их от «проверена, претензий нет» обязательно, иначе
-- старый набор выглядел бы прошедшим проверку, которой не было.

BEGIN;

ALTER TABLE personas
  ADD COLUMN IF NOT EXISTS validation jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMENT ON COLUMN personas.validation IS
  'Вердикт фазы валидации: {checked, consistent, issues[], attempts, confidence}. '
  'Пустой объект — не проверялась (набор создан до появления фазы).';

-- ─── Промпт ─────────────────────────────────────────────────────────────────
-- Идемпотентно: повторный прогон миграции не заводит второй строки и не
-- сбрасывает правки, сделанные командой в Промпт-студии (у них tenant_id NOT
-- NULL, а здесь трогается только дефолтная строка).

INSERT INTO prompts (tenant_id, key, stage, template, variables, version, is_active, is_default)
SELECT
  NULL,
  'persona.validate',
  'Персоны',
  '# persona.validate (seed)
Проверка связности созданной персоны. Переменные: {{skeleton_json}}, {{narrative}}, {{verbatim_pool}}.
---
Ты — проверяющий. Тебе дана персона, собранная в два шага: сначала атрибуты
сэмплированы из долей реального корпуса респондентов, затем модель переписала по
ним связный текст-портрет.

Твоя задача — найти расхождения ВНУТРИ персоны. Не оценивай, хороша ли она,
типична ли, приятна ли. Оценивай только одно: не противоречит ли текст своим же
атрибутам и не появилось ли в тексте того, чего в атрибутах нет.

## Атрибуты (источник истины)
{{skeleton_json}}

## Текст портрета (проверяемое)
{{narrative}}

## Реплики корпуса, из которого собрана персона
{{verbatim_pool}}

## Что считается расхождением
1. Противоречие атрибуту: в тексте сказано обратное тому, что стоит в атрибутах —
   возраст, город, занятость, семейное положение, частота просмотра, ценности,
   любой балл. «Не смотрю сериалы» при ежедневном просмотре — расхождение.
2. Досочинённый факт: биографическая подробность, которой нет ни в атрибутах, ни
   в репликах корпуса — профессия, диагноз, развод, переезд, имя супруга,
   конкретное место работы. Персона — розыгрыш из распределений, а не человек с
   историей; выдуманная подробность попадёт в её ответы и будет выглядеть
   данными исследования.
3. Обезличенность: текст не описывает никого конкретного, набор общих фраз,
   которые подошли бы любой персоне набора.

## Что расхождением НЕ считается
- Пересказ атрибута другими словами, синонимы, порядок изложения.
- Бытовые детали, вытекающие из атрибутов.
- Стилистика, тон, длина.
- Отличие от других персон набора. Персоны обязаны быть разными.

## Формат ответа
Только JSON, без пояснений вокруг:
{
  "consistent": true,
  "issues": [],
  "confidence": 0.0
}

consistent — false, если найдено хотя бы одно расхождение из списка выше.
issues — список строк, по одной на расхождение: что в атрибутах, что в тексте.
confidence — насколько уверен в вердикте, 0.0–1.0.

Сомневаешься — ставь consistent: true и низкий confidence. Забракованная персона
пересоздаётся заново, и ложное срабатывание стоит оплаченной генерации;
пропущенное расхождение стоит одного странного ответа в отчёте, который видно
глазами.',
  '["skeleton_json", "narrative", "verbatim_pool"]'::jsonb,
  1,
  true,
  true
WHERE NOT EXISTS (
  SELECT 1 FROM prompts WHERE key = 'persona.validate' AND is_default
);

COMMIT;
