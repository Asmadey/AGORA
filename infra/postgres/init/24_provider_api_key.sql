-- AGORA · 24 · Ключ провайдера, задаваемый из интерфейса
--
-- ─── Почему шифрование, а не просто колонка ─────────────────────────────────
-- Ключ в открытой колонке уезжает в каждую резервную копию базы и виден всем,
-- у кого есть доступ к базе, — включая того, кому дали доступ «только
-- посмотреть отчёты». Отозвать его оттуда нечем: копии уже сделаны.
--
-- Шифрование этого не отменяет, но меняет условие: чтобы воспользоваться копией
-- базы, нужен ещё и ключ шифрования, а он живёт в окружении сервисов и в
-- копию базы не попадает.
--
-- ─── Почему ключ шифрования в окружении, а не в базе ────────────────────────
-- Иначе всё это бессмысленно: замок и ключ от него в одном ящике. Переменная
-- `SETTINGS_SECRET` задаётся обоим сервисам — веб шифрует, воркер расшифровывает.
-- Без неё интерфейс отказывается принимать ключ и честно говорит почему, а не
-- сохраняет его открытым.
--
-- ─── Почему подсказка отдельной колонкой ────────────────────────────────────
-- Интерфейс обязан показать, КАКОЙ ключ действует, не расшифровывая его на
-- каждый заход в настройки. Маска (`sk-1a…9f`) хранится рядом: по ней ключ не
-- восстановить, а отличить один от другого можно.
--
-- ─── Чего здесь нет ─────────────────────────────────────────────────────────
-- Ключ НЕ попадает в `tasks.settings_snapshot`. Снимок живёт столько же,
-- сколько отчёт, и копия секрета в каждой строке `tasks` — это тот же секрет,
-- размноженный без единого способа его отозвать. Воркер читает ключ из
-- `settings` в момент прогона; состав снимка закреплён тестом.

BEGIN;

ALTER TABLE settings
  ADD COLUMN IF NOT EXISTS provider_api_key bytea,
  ADD COLUMN IF NOT EXISTS provider_api_key_hint text;

COMMENT ON COLUMN settings.provider_api_key IS
  'Ключ провайдера, зашифрованный AES-256-GCM ключом из SETTINGS_SECRET. '
  'NULL — ключ берётся из окружения сервера (прежнее поведение).';
COMMENT ON COLUMN settings.provider_api_key_hint IS
  'Маска вида «sk-1a…9f» для показа в интерфейсе. По ней ключ не восстановить.';

COMMIT;
