-- AGORA · 25 · qa.grounding: мнение — не выдумка
--
-- ─── Что нашлось ────────────────────────────────────────────────────────────
-- Golden-сет 17.08.2026, три прогона после починки покрытия анкеты и подписей
-- сцен. Весь остаток отбраковок — `grounding`, по три-шесть на прогон. Разбор
-- претензий судьи по фактическому материалу показал: из тринадцати претензий
-- ОДНА была справедливой (деталь привязана к чужому таймкоду), остальные
-- двенадцать — придирки к языку, а не к фактам:
--
--   · «просчитался наперёд» — ироничная формулировка того, что в материале
--     названо «как будто бы видел, куда идёт рынок»;
--   · «цифры выглядят как маркетинг» — МНЕНИЕ о названной в ролике сумме;
--   · «склейка стоковых кадров» — оценка монтажа;
--   · «стоят у доски и считают деньги» — пересказ «работы в финансах»;
--   · «отказался от DJI» вместо «отказался от предложения основателя DJI».
--
-- По трём из них судья прямо пишет в тексте претензии «это не явная выдумка»,
-- «допустимое упрощение», «это мнение» — и всё равно возвращает `regenerate`.
-- Он различает мнение и выдумку; ему просто нигде не сказано, что мнение
-- законно.
--
-- ─── Почему это дефект, а не строгость ──────────────────────────────────────
-- Продукт производит МНЕНИЯ синтетической аудитории. Вербатимы «почему такое
-- впечатление», «что запомнилось», «мнение о героях» субъективны по своему
-- назначению — в этом весь смысл фокус-группы. Правило, которое бракует
-- оценочную речь, требует от персоны пересказывать транскрипт, и тогда продукт
-- не производит ничего.
--
-- Проверка на выдумку нужна и остаётся: персона не должна ссылаться на сцены и
-- реплики, которых не было, и на таймкод, где было другое. Меняется граница, а
-- не наличие проверки — и меняется она в сторону назначения самой проверки,
-- сформулированного в первой же строке промпта: «ссылается ТОЛЬКО на реально
-- существующие в материале детали». Оценка детали — не деталь.
--
-- Честно: эта правка ПОДНИМЕТ долю выживших ответов, то есть сдвинет метрику,
-- по которой нас же и меряют. Поэтому граница описана перечнем случаев с обеих
-- сторон, а не словом «будь мягче»: мягкость нечего проверить, а перечень видно
-- в дифференциале и можно оспорить построчно.
--
-- ─── Идемпотентность ────────────────────────────────────────────────────────
-- По маркеру в тексте. Уже применённый файл не редактируется — заводится
-- следующий по номеру.

UPDATE prompts
SET template = template || '

# Где проходит граница: выдумка против мнения

Ты ищешь ВЫДУМАННЫЕ ФАКТЫ, а не неудачные формулировки. Персона — зритель, и
её вербатимы обязаны быть субъективными: продукт производит мнения аудитории,
а не пересказ транскрипта.

`regenerate` — только если персона:
- называет сцену, реплику или деталь, которых в материале нет вовсе;
- привязывает реальную деталь к таймкоду, где её нет (деталь из 1:17 названа
  как происходившая в 0:22);
- приписывает материалу число, имя или событие, отличное от названного в нём.

`ok` — во всех этих случаях, даже если формулировка тебе не нравится:
- оценка и мнение о материале: «выглядит как маркетинг», «затянуто»,
  «склейка стоковых кадров», «типичный инфобизнес» — это ответ зрителя, а не
  утверждение о содержании;
- пересказ своими словами и метафора: «стоят у доски и считают деньги» вместо
  «работает в финансах»;
- упрощение без искажения сути: «отказался от DJI» вместо «отказался от
  предложения основателя DJI»;
- ирония и эмоциональная окраска: «просчитался наперёд» о том, что в материале
  названо предвидением;
- вывод, который зритель делает из показанного, даже если прямо он не сказан.

Если ты обнаруживаешь, что пишешь «это не явная выдумка», «допустимое
упрощение», «это интерпретация» или «это мнение» — вердикт `ok`. Сомнение
здесь толкуется в пользу персоны: цена ложной отбраковки выше цены пропущенной
неточности. Забракованный ответ выпадает из агрегата целиком, и отчёт молча
считается по остатку.

В `hallucinations` перечисляй ТОЛЬКО выдуманные факты. Не клади туда
рассуждение о том, как ты выбирал вердикт: это поле читает человек в отчёте.'
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'qa.grounding'
  AND template NOT LIKE '%Где проходит граница%';
