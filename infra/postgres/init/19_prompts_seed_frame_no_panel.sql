-- AGORA · 19 · content.frame_analysis: описывать сцену, а не панель
--
-- ─── Что нашёл первый прогон на сценной сетке ───────────────────────────────
-- Семь описаний из двадцати четырёх начинались словами «Сцена представляет собой
-- монтаж из четырёх кадров…». Модель описывала НАШ способ подачи: панель 2×2,
-- в которую кадры склеены ради экономии вызовов.
--
-- Это не косметика. Персона видит не ролик, а его разбор; прочитав про монтаж,
-- она перескажет монтаж, которого в материале нет. QA-судья сверяет ответ с тем
-- же описанием и признает пересказ заземлённым — то есть артефакт нашей
-- предобработки доедет до отчёта как факт о материале, и опровергнуть его будет
-- нечем: к моменту разбора отчёта видео удалено по политике хранения.
--
-- Прежняя редакция промпта (миграция 16) говорила «кадры идут по порядку… это
-- последовательные моменты одной сцены» — этого оказалось мало. Теперь сказано
-- прямо: это НЕ монтаж и НЕ коллаж, и перечислены слова, которых в описании
-- быть не должно.
--
-- Идемпотентно по условию на template: строка, где запрет уже есть, под UPDATE
-- не попадает.

UPDATE prompts
SET template = '# content.frame_analysis (seed)
VLM-разбор сцены по панели кадров. Переменные: {{frames}}, {{scene_start}}, {{scene_end}}, {{panel_size}}, {{frame_times}}, {{timestamp}}.
---
На вход — {{panel_size}} кадра ОДНОЙ сцены видео, снятых подряд и склеенных в одну
картинку только ради экономии: слева направо, сверху вниз — это последовательные
моменты одного отрезка с {{scene_start}} по {{scene_end}} секунду (кадры сняты в
моменты: {{frame_times}}).

Это НЕ монтаж, НЕ коллаж и НЕ подборка разных сцен. Сравни кадры между собой:
что изменилось от первого к последнему и есть ли движение — именно из этого
берётся поле actions.

# Главное правило описания
Описывай СЦЕНУ, а не то, как её тебе показали. В тексте не должно быть слов
«кадр», «панель», «коллаж», «монтаж из», «сетка», «изображение разделено» и
подобных: их читает зритель, который смотрел видео и никакой панели не видел.
Фраза «сцена представляет собой монтаж из четырёх кадров» описывает наш способ
подачи, а не материал, и уводит зрителя в несуществующий монтаж.

Извлеки СЕМАНТИКУ СЦЕНЫ (не портретную репликацию) в чистый JSON:
{
  "timestamp": "{{scene_start}}",
  "scene_description": "<что происходит в сцене целиком, кратко>",
  "actions": ["<действие, видимое по изменению между моментами>", "..."],
  "characters": [{"appearance":"<кто/как выглядит>","emotion":"<эмоция>"}],
  "setting": "<место/эпоха/обстановка>",
  "mood": "<настроение сцены>",
  "cinematography": {"shot":"<план>","lighting":"<свет>","camera":"<движение/ракурс>"},
  "on_screen_text": "<текст на экране или null>",
  "notable": "<что визуально выделяется: костюмы, реквизит, насилие и т.п.>"
}
Опиши только то, что реально видно. Не выдумывай сюжет за пределами сцены.
Описание относится ко всему отрезку {{scene_start}}–{{scene_end}}, а не к одному моменту.
Верни только JSON.
',
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'content.frame_analysis'
  AND template NOT LIKE '%Главное правило описания%';
