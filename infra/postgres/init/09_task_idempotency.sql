-- 09 — Идемпотентность запуска исследования (задача #11).
--
-- Запуск — платная операция: разбор кадров и прогон респондентов стоят денег при
-- каждом вызове. Двойной клик по «Запустить», ретрай прокси или обновление
-- страницы не должны порождать второй прогон, а различить его потом нечем: две
-- задачи с одинаковыми параметрами выглядят как намеренный повтор.
--
-- ─── Почему уникальный ключ, а не проверка перед вставкой ────────────────────
-- Проверка «поищем такую же задачу, и если нет — вставим» гонку не закрывает:
-- два одновременных запроса оба ничего не находят и оба вставляют. Уникальный
-- индекс — единственное место, где это решается без блокировок, и он же делает
-- ON CONFLICT DO NOTHING осмысленным.
--
-- ─── Почему уникальность в пределах арендатора ───────────────────────────────
-- Одинаковые параметры у разных команд — это разные прогоны. Глобальный
-- уникальный ключ склеил бы их и отдал одной команде задачу другой: утечка
-- через ключ идемпотентности, которую RLS не поймает, потому что конфликт
-- случается на уровне индекса, до применения политик.
--
-- Идемпотентно и только вперёд: уже применённые файлы не редактируются (§5).

ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS idempotency_key text;

COMMENT ON COLUMN tasks.idempotency_key IS
  'Отпечаток параметров запуска (включая seed и снимок промптов). '
  'Повторный запуск с тем же ключом возвращает существующую задачу, а не создаёт вторую.';

-- Частичный индекс: NULL допустим и не участвует в уникальности. Так остаются
-- вставляемыми задачи, заведённые до появления ключа и внутренними путями
-- (например, перезапуском #30, у которого своя логика тождества).
CREATE UNIQUE INDEX IF NOT EXISTS tasks_tenant_idempotency_uniq
  ON tasks (tenant_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;
