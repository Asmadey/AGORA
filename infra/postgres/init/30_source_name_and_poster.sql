-- AGORA · 30 · Имя исходного файла и постер прогона
--
-- ─── Имя файла ──────────────────────────────────────────────────────────────
-- В списке исследований вместо названия ролика стоял ключ S3:
-- `tenants/de15d1e3…/uploads/f77c2e53….mp4`. Узнать в нём свой файл нельзя, а
-- именно по нему исследование и ищут глазами.
--
-- Имя не хранилось нигде: браузер передаёт `fileName` в маршрут подписи, и тот
-- берёт из него ровно расширение. Ключ намеренно не собирается из имени —
-- пользовательские имена содержат пробелы, кириллицу и совпадают между собой, а
-- ключ обязан быть уникальным и безопасным. Поэтому имя едет отдельным полем, а
-- не выводится из ключа.
--
-- ─── Постер ─────────────────────────────────────────────────────────────────
-- На экране отчёта постер берётся из первой ячейки таймлайна, а она лежит в
-- Mongo. Для списка из ста прогонов это сто запросов к Mongo ради картинки в
-- углу карточки. Ключ кадра уже известен воркеру в момент выгрузки — он его и
-- записывает сюда, одним UPDATE на прогон.
--
-- NULL в обоих полях законен: прогоны, сделанные до этой миграции, показывают
-- ключ и серую заглушку — ровно как раньше.

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS source_name text;
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS poster_ref text;

COMMENT ON COLUMN tasks.source_name IS
  'Имя файла, как его назвал пользователь. Для показа, не для доступа: ключ S3 — video_ref.';
COMMENT ON COLUMN tasks.poster_ref IS
  'Ключ S3 кадра-заставки. NULL — кадров нет либо прогон старше миграции 30.';
