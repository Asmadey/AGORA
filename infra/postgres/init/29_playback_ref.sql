-- AGORA · 29 · Копия ролика для просмотра
--
-- ─── Зачем отдельная колонка ────────────────────────────────────────────────
-- `video_ref` — исходник, тот самый файл, который загрузил человек. Его нельзя
-- подменять: он нужен для выгрузки «как есть» и для повторного разбора, если
-- конвейер изменится. Копия для просмотра — другой объект с другой судьбой: её
-- можно пересобрать, удалить по политике хранения и не восстанавливать.
--
-- NULL — законное состояние, а не ошибка. Так выглядят прогоны, сделанные до
-- появления копии, и прогоны, где сборка не удалась: плеер тогда берёт
-- исходник, как и раньше.

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS playback_ref text;

COMMENT ON COLUMN tasks.playback_ref IS
  'Ключ S3 копии для просмотра: H.264 720p с moov в начале файла. '
  'NULL — копии нет, плеер берёт video_ref.';
