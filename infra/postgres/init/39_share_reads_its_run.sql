-- ─────────────────────────────────────────────────────────────────────────
-- 39. Публичной ссылке нужен сам прогон, а не только строка ссылки
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что чинится. Роль `agora_share` имеет SELECT ровно на `reports` и
-- `report_shares` (03_rls.sql). Таблица `tasks` ей недоступна вовсе, и из
-- этого следовали две вещи, обе видимые на публичной странице:
--
--   1. Заголовок. Страница подставляла `title: null` и всегда писала
--      «Синтетическая фокус-группа» — не потому, что название не хранится, а
--      потому, что прочитать его было нечем.
--   2. Плеер. `playback_ref` и `video_ref` лежат в `tasks`. Показать материал
--      по ссылке было физически невозможно.
--
-- Владелец попросил, чтобы режим «Весь отчёт» показывал весь отчёт, включая
-- материал. Отсюда эта миграция.
--
-- ─── Почему политика, а не GRANT на таблицу ──────────────────────────────
-- §5 CLAUDE.md: нехватка прав лечится политикой, узкой по команде и по
-- таблице. GRANT SELECT на `tasks` без политики при включённом RLS не даст
-- ничего (нет политики = запрет), а снятие FORCE или BYPASSRLS открыли бы
-- роли все шестнадцать таблиц разом. Политику видно в `pg_policies`; снятый
-- FORCE не видно нигде — именно так он однажды и исчез.
--
-- ─── Что именно открывается ──────────────────────────────────────────────
-- Ровно одна строка: тот прогон, на который выпущена ЖИВАЯ ссылка с тем
-- токеном, который предъявлен в этом соединении. Условия жизни ссылки те же,
-- что у соседних политик: не отозвана и не просрочена. Отзыв ссылки закрывает
-- и прогон — в тот же момент и без участия кода приложения.
--
-- Область (`scope`) здесь НЕ проверяется, и это осознанно. Политика отвечает
-- на вопрос «какой прогон открывает этот токен», а не «что из него показать»:
-- второй вопрос решает страница, и решает по-разному для заголовка и для
-- материала. Смешать их в одном USING значило бы, что ссылка «только сводка»
-- теряет и заголовок тоже.
--
-- Идемпотентно: DROP POLICY IF EXISTS перед созданием, как в 03_rls.sql.

BEGIN;

DROP POLICY IF EXISTS tasks_public_share_read ON tasks;
CREATE POLICY tasks_public_share_read ON tasks
  FOR SELECT TO agora_share
  USING (
    EXISTS (
      SELECT 1
      FROM report_shares s
      WHERE s.task_id = tasks.id
        AND s.token_hash = app.current_share_token_hash()
        AND s.revoked_at IS NULL
        AND (s.expires_at IS NULL OR s.expires_at > now())
    )
  );

-- Без GRANT политика не сработает: RLS сужает уже выданное право, а не
-- заменяет его. Право только на чтение — публичная страница ничего не пишет,
-- кроме строки просмотра в аудит-логе (её GRANT выдан в 03_rls.sql).
GRANT SELECT ON tasks TO agora_share;

COMMIT;
