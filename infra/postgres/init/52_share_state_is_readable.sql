-- ─────────────────────────────────────────────────────────────────────────
-- 52. Публичная роль должна видеть состояние ссылки
-- ─────────────────────────────────────────────────────────────────────────
--
-- Политика `report_shares_public_read` в 03_rls.sql раньше возвращала только
-- живую ссылку. Поэтому страница не могла отличить истёкшую или отозванную
-- ссылку от случайного токена: `SELECT` возвращал ноль строк, а классификатор
-- видел `missing` и отдавал 404 вместо 410.
--
-- Условия жизни намеренно остаются в политиках, которые открывают данные:
--
-- * `tasks_public_share_read` из миграции 39 сам проверяет отзыв и срок;
-- * `reports_public_share_read` из 03_rls.sql делает ту же проверку;
-- * `report_share_views_public_insert` из 03_rls.sql не даёт писать аудит для
--   мёртвой ссылки.
--
-- Строка `report_shares` данными отчёта не является: в ней лежат область,
-- `task_id` и сроки, то есть состояние самой ссылки. Её получает только тот,
-- кто предъявил точный `token_hash`, а значит уже держит настоящий адрес.
-- Поэтому здесь снимаются только условия жизни, а доступ по точному хешу и
-- роль `agora_share` сохраняются. FORCE ROW LEVEL SECURITY не снимается,
-- BYPASSRLS не выдаётся и GRANT не расширяется.

BEGIN;

DROP POLICY IF EXISTS report_shares_public_read ON report_shares;
CREATE POLICY report_shares_public_read ON report_shares
  FOR SELECT TO agora_share
  USING (
    token_hash = app.current_share_token_hash()
  );

COMMIT;
