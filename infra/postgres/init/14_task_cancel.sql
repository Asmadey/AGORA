-- Отмена прогона и время его начала.
--
-- ─── Зачем ──────────────────────────────────────────────────────────────────
-- Удалить исследование в состоянии QUEUED или RUNNING было нельзя: маршрут
-- отвечал 409, и текст был честным — у воркера нет канала отмены. Он читает
-- чекпоинт и пишет прогресс; пропавшая строка задачи для него выглядит сбоем
-- базы, и он уходит в повтор.
--
-- Но накопились прогоны, которые не возьмёт уже никто: воркер перезапускался,
-- очередь чистилась, задача осталась в QUEUED навсегда. Отказ «дождитесь
-- окончания» для них — обещание, которое никогда не исполнится.
--
-- ─── Почему started_at, а не только created_at ──────────────────────────────
-- `created_at` — это момент постановки в очередь. Между ним и началом работы
-- задача может простоять сколько угодно: воркер занят, воркер лежит, очередь
-- разгребается. Считать «время обработки» по created_at значит показывать
-- пользователю сумму ожидания и работы под видом длительности прогона.
--
-- Миграция идемпотентна и только вперёд, как требует §5 CLAUDE.md.

BEGIN;

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS started_at timestamptz;

-- Момент запроса отмены, а не флаг. Отмена не мгновенна: воркер проверяет её
-- между узлами, а разбор кадров длится минуты. По времени запроса видно, сколько
-- прогон уже отменяется, — флаг такого не сказал бы, и «отменяется» навсегда
-- было бы неотличимо от «отмена не дошла».
ALTER TABLE tasks ADD COLUMN IF NOT EXISTS cancel_requested_at timestamptz;

-- Ограничение статуса переписывается: добавляется CANCELLED.
--
-- Отдельное значение, а не FAILED с текстом. Отменённый прогон — не отказ
-- системы, и складывать их в одну корзину значит терять способность отличить
-- «сломалось» от «остановили»: в списке они выглядели бы одинаково, а метрика
-- надёжности считала бы отмены авариями.
ALTER TABLE tasks DROP CONSTRAINT IF EXISTS tasks_status_check;
ALTER TABLE tasks ADD CONSTRAINT tasks_status_check
  CHECK (status IN ('QUEUED', 'RUNNING', 'REPORT_READY', 'FAILED', 'CANCELLED'));

-- Поиск зависших: QUEUED, которые никто не взял. Индекс частичный — активных
-- задач единицы, а таблица растёт всеми прогонами арендатора.
CREATE INDEX IF NOT EXISTS tasks_pending_idx
  ON tasks (tenant_id, created_at)
  WHERE status IN ('QUEUED', 'RUNNING');

COMMIT;
