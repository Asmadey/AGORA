-- ─────────────────────────────────────────────────────────────────────────
-- 42. Сборщику мусора в хранилищах — чтение прогонов ВСЕХ статусов
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что чинится. `agent_core/maintenance/orphan_storage.py` ищет объекты S3,
-- документы Mongo и слепки корпуса, которым не соответствует ни один прогон.
-- Вопрос, на который он отвечает, — «жив ли прогон с таким идентификатором»,
-- и задавать его нужно по ВСЕМ статусам сразу.
--
-- ─── Почему политики 41 недостаточно, и почему это опасно ────────────────
-- Миграция 41 выдала владельцу схемы `SELECT ... USING (status = 'RUNNING')`.
-- Для сборщика осиротевших прогонов это ровно та выборка, которая ему нужна.
--
-- Для сборщика хранилищ она смертельна. Под ней `SELECT id FROM tasks` в
-- тихий час возвращает ПУСТО — и пусто здесь означает не «прогонов нет», а
-- «все объекты осиротели». То есть кадры, отчёты и ролики всех завершённых
-- исследований подлежат удалению. Отказа при этом не будет: запрос успешен,
-- ответ корректен, уборка пройдёт штатно и сотрёт боевые данные.
--
-- Ровно такой формы дефект — пустое множество, прошедшее за успех — в этом
-- проекте встречался уже трижды: пустой список проверок CI между запусками,
-- `grep` по чужому образцу вывода, код возврата, съеденный конвейером. Ни у
-- одного из них не было прав на удаление. У сборщика они есть.
--
-- ─── Что защищает, кроме этой миграции ───────────────────────────────────
-- Сборщик ОТКАЗЫВАЕТСЯ работать, пока не убедится, что видит все статусы:
-- `assert_full_task_visibility` проверяет либо обход RLS у роли, либо наличие
-- политики без ограничения по строкам. Пока миграция не применена, сборщик на
-- managed-инстансе не запустится — и это правильное поведение, а не поломка.
--
-- Проверка написана так, что узкая политика 41 её НЕ удовлетворяет: у неё
-- `qual` не пуст. Иначе защита сводилась бы к «какая-нибудь политика есть».
--
-- ─── Насколько узко ──────────────────────────────────────────────────────
-- По команде: только SELECT. Сборщик про `tasks` ничего не пишет — он читает
-- идентификаторы и ссылки на объекты, а удаляет в S3, Mongo и
-- `corpus_snapshots`.
-- По таблице: только `tasks`.
-- По строкам: без ограничения — в этом весь смысл.
--
-- FORCE ROW LEVEL SECURITY остаётся на всех таблицах. Прецедент тот же, что у
-- 06_owner_read_auth_tables.sql и 41: узкая политика владельцу вместо снятия
-- FORCE или выдачи BYPASSRLS. Политику видно в `pg_policies`; снятый FORCE не
-- видно нигде — именно так он однажды и исчез.
--
-- Идемпотентно: DROP POLICY IF EXISTS перед созданием.

BEGIN;

DO $$
DECLARE
  owner_role text;
BEGIN
  SELECT tableowner INTO owner_role FROM pg_tables
   WHERE schemaname = 'public' AND tablename = 'tasks';

  EXECUTE 'DROP POLICY IF EXISTS tasks_sweeper_read ON tasks';
  EXECUTE format(
    'CREATE POLICY tasks_sweeper_read ON tasks FOR SELECT TO %I USING (true)',
    owner_role
  );
END $$;

COMMIT;
