-- 37. Каталог моделей транскрипции: основным становится GigaAM
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что меняется. Настройки предлагают gigaam-v3-e2e-rnnt и large-v3, parakeet
-- снят с предложения. Основание — замер 20.08.2026 на пяти минутах диалога из
-- прогона 0051, одна дорожка, один и тот же детектор речи
-- (docs/ASR_BAKEOFF_2026-08-20.md):
--
--     parakeet-tdt-0.6b-v3   40,3 слов/мин речи | 67,0 с | 3285 МБ
--     gigaam v3-e2e-rnnt     64,8 слов/мин речи | 21,2 с | 1694 МБ
--
-- Разница не в процентах: у parakeet текст на русском не восстанавливается до
-- смысла — «Сот мальчишек» вместо «Семьсот мальчишек», «господин Ярат» вместо
-- «Нератов». На этом тексте работают сразу три вещи: ответ персоны, проверка
-- её ссылки судьёй и цитаты в отчёте. В прогоне 0051 судья забраковал 7 из 20
-- ответов по grounding, и претензия была справедлива.
--
-- Почему parakeet остаётся ИСПОЛНИМЫМ. Снимок настроек прогона пиннит имя
-- модели. Убрать её отовсюду значило бы, что перезапуск прогона № 0051 падает
-- ConfigError — прошлый прогон перестал бы воспроизводиться из-за решения,
-- принятого после него. Поэтому в `agent_core/config.py` заведён
-- RETIRED_MODELS: из выбора модель уходит, из исполнения — нет.
--
-- А вот в ограничении схемы её быть не должно: ограничение описывает то, что
-- можно СОХРАНИТЬ в настройках, то есть выбрать заново.
--
-- Что со строками, где parakeet уже стоит. Их надо перевести ДО пересоздания
-- ограничения: обратный порядок падает на валидации существующих данных — так
-- уже было с turbo в миграции 31, и на боевой базе такая строка есть.

BEGIN;

-- Сначала данные, потом ограничение.
UPDATE settings
   SET whisper_model = 'gigaam-v3-e2e-rnnt'
 WHERE whisper_model NOT IN ('gigaam-v3-e2e-rnnt', 'large-v3');

ALTER TABLE settings DROP CONSTRAINT IF EXISTS settings_whisper_model_check;

ALTER TABLE settings
  ADD CONSTRAINT settings_whisper_model_check
  CHECK (whisper_model IN ('gigaam-v3-e2e-rnnt', 'large-v3'));

-- Умолчание схемы идёт следом за умолчанием интерфейса: строка настроек,
-- созданная в обход роута, иначе получала бы снятую модель молча.
ALTER TABLE settings ALTER COLUMN whisper_model SET DEFAULT 'gigaam-v3-e2e-rnnt';

COMMIT;
