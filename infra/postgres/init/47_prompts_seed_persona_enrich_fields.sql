-- ─────────────────────────────────────────────────────────────────────────
-- 47. persona.enrich: развёрнуты оставшиеся опровергаемые черты
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что меняется. В «опорные признаки» добавлены `{{children}}`,
-- `{{lifestyle_and_interests}}` и `{{technology_usage}}`. Файл
-- `prompts/persona.enrich.md` правится тем же изменением; миграция приводит к
-- нему копию в базе.
--
-- ─── Почему ──────────────────────────────────────────────────────────────
-- Миграция 45 развернула три группы черт по следам замера на боевом. Пересчёт
-- покрытия показал, что закрыто 47 упоминаний из 78, а 31 осталось видно
-- модели только внутри `skeleton_json` — и среди них ВТОРОЕ по частоте поле
-- всего списка:
--
--     social_activity      8   lifestyle_and_interests   не было развёрнуто
--     children             6   demographics              не было развёрнуто
--     education_level      5   lifestyle_and_interests   не было развёрнуто
--     streaming_frequency  3   technology_usage          не было развёрнуто
--     tech_savviness       3   technology_usage          не было развёрнуто
--     media_consumption    2   lifestyle_and_interests   не было развёрнуто
--
-- `big_five` сознательно НЕ разворачивается, и причина не в том, что там числа:
-- числа есть и в `decision_making` (impulsivity), и в `technology_usage`
-- (tech_savviness), и они развёрнуты. Разница в том, во что имя поля
-- переводится. «impulsivity: 1» читается как поступок — не покупает сгоряча.
-- «openness: 4» — психометрический конструкт, который в поведение превращается
-- только домыслом, а домысел судья бракует по классу «оценочная окраска».
--
-- ─── Зачем миграция, если код читает файл ────────────────────────────────
-- `persona/enrich.py` берёт шаблон с диска, из базы его не запрашивает никто.
-- На поведение генерации миграция не влияет. Нужна она затем же, зачем 44 и 45:
-- шаблон виден в Промпт-студии и читается как действующая инструкция, а
-- расхождение файла и засева ловит `evals/tests/test_task26_prompt_studio.py`.
--
-- Идемпотентно: повторный прогон присваивает то же значение. Сравнения текста
-- в WHERE нет — у `prompts` нет ни триггеров, ни `updated_at`.

