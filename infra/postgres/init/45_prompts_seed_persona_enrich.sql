-- ─────────────────────────────────────────────────────────────────────────
-- 45. persona.enrich: засев приводится к тексту файла
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что меняется. Промпт обогащения разворачивает три группы черт отдельными
-- переменными (`viewer_behavior`, `communication_style`, `decision_making`) и
-- запрещает противоречить скелету. Файл `prompts/persona.enrich.md` правится
-- тем же изменением; эта миграция приводит к нему копию в базе.
--
-- ─── Зачем миграция, если код читает файл ────────────────────────────────
-- `persona/enrich.py` действительно берёт шаблон с диска (`PROMPT_PATH`), а
-- `persona/tasks.py` промпт из базы не передаёт вовсе. То есть на поведение
-- боевой генерации эта миграция не влияет.
--
-- Нужна она по той же причине, что и 44-я: шаблон виден в Промпт-студии и
-- читается как действующая инструкция. Оставить там прежнюю редакцию значит
-- показывать владельцу текст, которого модель не получает, — и следующая
-- правка будет сделана в той копии, что попалась под руку.
--
-- Расхождение файла и засева ловит `evals/tests/test_task26_prompt_studio.py`;
-- он же и покраснел на этой правке до появления миграции.
--
-- ─── Почему правится промпт ──────────────────────────────────────────────
-- Замер на боевом 17.09.2026 по `personas.validation`: 74 претензии судьи к 27
-- персонам из 70, и 38 из них — противоречие атрибуту. Обогащение писало текст,
-- опровергающий собственный скелет: 'pacing_tolerance': 'медленный' против
-- «предпочитая быстрые, короткие ролики», 'directness': 'окольный' против
-- «прямолинейно», возраст 25 против «Девятнадцатилетняя».
--
-- Запрета противоречить в промпте не было ни одной строкой: «Только факты из
-- списка выше. Не добавляй…» охраняет от прибавления, а не от опровержения.
--
-- Идемпотентно: повторный прогон присваивает то же значение. Сравнения текста
-- в WHERE здесь НЕТ, в отличие от формулировки миграции 26, — у `prompts` нет
-- ни триггеров, ни `updated_at`, и второй UPDATE ничего не меняет.

