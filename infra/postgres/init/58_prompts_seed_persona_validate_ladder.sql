-- AGORA · 58 · persona.validate: тип и тяжесть каждой претензии
--
-- Точечная замена сохраняет возможные правила шага 1 и редакции соседних
-- миграций. Условие NOT LIKE делает повторный запуск идемпотентным.

UPDATE prompts
SET template = replace(
    replace(
        replace(
            template,
    '## Формат ответа',
    '## Разбор претензий

Для каждой найденной претензии укажи вид, тяжесть и короткое объяснение.

Вид `contradiction` означает, что текст говорит обратное атрибуту. Вид
`invented` означает досочинённую биографическую подробность, которой нет в
атрибутах или репликах корпуса. Вид `impersonal` означает, что текст не
описывает никого конкретного. Эти три вида относятся к тексту.

Вид `attribute_conflict` означает, что два атрибута несовместимы между собой.
Это претензия к генератору, а не к тексту. Не смешивай её с тремя видами
претензий к портрету.

Тяжесть `hard` ставь только проверяемому факту, который читатель назовёт
неверным: возраст, город, дети, занятость, частота просмотра, перевёрнутый
балл и тому подобное. Тяжесть `soft` ставь толкованию и нюансу. Мягкая
претензия и `attribute_conflict` не означают, что нужно выбрасывать персону.

## Формат ответа'
        ),
        '```json
{
  "consistent": true,
  "issues": [],
  "confidence": 0.0
}
```',
        '```json
{
  "consistent": true,
  "issues": [],
  "confidence": 0.0
}
```

Если расхождение найдено:

```json
{
  "consistent": false,
  "issues": [
    {
      "kind": "contradiction",
      "severity": "hard",
      "message": "что сказано в атрибутах и что утверждает текст"
    }
  ],
  "confidence": 0.0
}
```'
    ),
    '- `issues` — список строк, по одной на расхождение. В каждой: что в атрибутах,
  что в тексте. Пустой список при `consistent: true`.',
    '- `issues` — список объектов, по одному на расхождение. Каждый объект содержит
  `kind`, `severity` и `message`. Пустой список означает, что претензий нет.'
    ),
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'persona.validate'
  AND template NOT LIKE '%## Разбор претензий%';
