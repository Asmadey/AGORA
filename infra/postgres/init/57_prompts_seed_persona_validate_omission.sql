-- ─────────────────────────────────────────────────────────────────────────
-- 57. persona.validate: молчание и сочетания атрибутов не являются браком
-- ─────────────────────────────────────────────────────────────────────────
--
-- Судья должен искать сказанное НЕ ТО, а не несказанное. Портрет занимает
-- 400-600 знаков, тогда как атрибутов у персоны несколько десятков, и
-- обогащение прямо запрещает перечислять их полями.
--
-- Замер до правки по боевым наборам:
--   11.09: пересоздано 14 из 40 (35%), осталось несвязными 2, попыток 1.50;
--   16.09: пересоздано 8 из 20 (40%), осталось несвязными 2, попыток 1.60;
--   16.09: пересоздано 5 из 10 (50%), осталось несвязными 0, попыток 1.80.
-- Разбор 74 претензий дал три класса: около 27 - отсутствие упоминания;
-- настоящие противоречия текста атрибутам; и несовместимые между собой поля
-- скелета, которые генератор сэмплирует независимо.
--
-- Идемпотентно: после первой замены исходный маркер исчезает, поэтому повторный
-- прогон не меняет уже обновлённый шаблон. Точечная замена сохраняет возможную
-- редакцию других частей промпта в Промпт-студии.

UPDATE prompts
SET template = replace(
    template,
    '- Отличие от других персон набора. Персоны обязаны быть разными.',
    '- Отличие от других персон набора. Персоны обязаны быть разными.
- **Отсутствие упоминания атрибута в тексте само по себе не является
  расхождением.** Портрет - абзац прозы на 400-600 знаков, а атрибутов у
  персоны несколько десятков: назвать их все он не может и не должен. Судья
  ищет сказанное НЕ ТО, а не несказанное.
- **Атрибуты не оцениваются между собой.** Атрибуты - источник истины, но их
  внутренние сочетания не обсуждаются. Если два атрибута кажутся
  несовместимыми, это свойство сэмплирования, а не дефект текста, и
  расхождением не считается. Сравнивай текст с атрибутами, а не атрибуты между
  собой.'
)
WHERE key = 'persona.validate' AND tenant_id IS NULL;
