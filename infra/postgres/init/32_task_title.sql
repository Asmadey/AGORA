-- 32. Название исследования, заданное человеком
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что было. В списке исследований заголовком служил `source_name` — имя
-- залитого файла, а до миграции 30 и вовсе ключ S3
-- (`tenants/…/uploads/f77c2e53….mp4`). Имя файла — факт о загрузке, а не
-- название работы: «15 min.mp4» ничего не говорит о том, что исследовали.
--
-- Почему отдельная колонка, а не переименование source_name. Это разные
-- сведения, и хранить их в одном поле значит терять одно при правке другого.
-- Имя файла нужно, чтобы понять, ЧТО именно залито, — особенно когда название
-- дали общее («Ролик для ВК, апрель»). Переименовав, человек стёр бы
-- единственную запись об исходнике.
--
-- Отсюда порядок показа: title, если задан; иначе source_name; иначе video_ref.
-- Прогоны, созданные до этой миграции, продолжают показывать имя файла — их
-- заголовок не меняется, пока владелец сам его не задаст.

BEGIN;

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS title text;

-- Ограничение длины — то же, что у названия проекта: одно поле ввода, одни
-- ожидания. Пустая строка запрещена наравне с пробелами: «переименовал в
-- пустоту» выглядит на экране как потеря названия, а не как выбор.
ALTER TABLE tasks DROP CONSTRAINT IF EXISTS tasks_title_check;
ALTER TABLE tasks
  ADD CONSTRAINT tasks_title_check
  CHECK (title IS NULL OR (length(btrim(title)) BETWEEN 1 AND 200));

COMMIT;
