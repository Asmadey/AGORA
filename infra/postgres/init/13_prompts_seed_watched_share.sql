-- редактируется (§5 CLAUDE.md), а 07 генерируется скриптом, и перегенерация
-- переписала бы тексты всех промптов заодно.
--
-- Что изменилось. В ответе появилось поле perception.watched_share_pct — доля
-- ролика, которую персона досмотрела бы, целым числом процентов.
--
-- Оно понадобилось потому, что экран отчёта показывал «Досмотрено, %», а взять
-- это число было неоткуда: retention_intent категориален («скорее досмотреть»
-- против «скорее выключить»), и процент из категории не выводится никаким
-- честным способом. В прототипе интерфейса там стояло выдуманное число.
--
-- Намерение и поведение — разные величины, и одна не заменяет другую. Поэтому
-- поле добавлено рядом с retention_intent, а не вместо него, и QA сверяет их
-- между собой: «выключил бы» при 95% означает, что одна из формулировок
-- выдумана (agent_core/qa/checks.py).
--
-- Поле необязательное: анкету без вопроса о доле просмотра пользователь вправе
-- запустить, и отчёт по ней показывает прочерк, а не ноль.
--
-- Идемпотентно по условию на template: строка, где watched_share_pct уже есть,
-- под UPDATE не попадает.

