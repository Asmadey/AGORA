-- AGORA · 17 · Снимок настроек прогона
--
-- ─── Зачем ──────────────────────────────────────────────────────────────────
-- Жёсткий кап вызовов VLM (#27) существовал ровно в двух местах: в интерфейсе,
-- где его выставляют, и в `CallBudget.for_task`, который умеет его применить.
-- Между ними не было ничего: воркер получал в очереди `prompts_snapshot` и не
-- получал настроек, `analyze_panels` звался без бюджета, и кап не действовал
-- никогда. Настройка была, ограничения не было — и отличить одно от другого
-- можно было только по счёту от провайдера.
--
-- ─── Почему снимок, а не чтение настроек воркером ───────────────────────────
-- По той же причине, по которой пиннится модель Whisper (#15) и версии
-- промптов (Decision Log #10): пока задача стоит в очереди, команда может
-- сменить кап. Тогда часть панелей разобрана под одним потолком, часть под
-- другим, и разница в полноте разбора выглядела бы свойством материала, а не
-- настройки. Это ровно тот вид расхождения, который потом объясняют
-- «наверное, ролик сложный».
--
-- Есть и вторая причина, техническая: воркер ходит в Postgres под ролью
-- арендатора через `tenant_scope`, и лишнее чтение на каждый прогон — лишний
-- повод для отказа там, где значение уже известно на запуске.
--
-- ─── Форма ──────────────────────────────────────────────────────────────────
-- Контракт полей совпадает с `apps/web/lib/settings.ts` и с тем, что читает
-- `CallBudget.for_task`: costCap ∈ {auto, hard}, costCapValue осмыслен только
-- при hard. Хранится как есть, а не разложенным по колонкам: снимок — это
-- копия того, что было, а не нормализованная сущность. Разложенный по колонкам
-- снимок пришлось бы мигрировать всякий раз, когда в настройках появится поле.
--
-- Пустой объект по умолчанию — законное состояние: так выглядят все прогоны,
-- начатые до этой миграции, и `CallBudget.for_task({})` честно означает
-- «без ограничения», то есть прежнее поведение.

BEGIN;

ALTER TABLE tasks
  ADD COLUMN IF NOT EXISTS settings_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb;

COMMIT;
