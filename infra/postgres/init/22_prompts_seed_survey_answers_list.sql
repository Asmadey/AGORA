-- AGORA · 22 · respondent.user: ответы анкеты списком пар, а не словарём
--
-- ─── Зачем ──────────────────────────────────────────────────────────────────
-- Ответы персон переводятся на строгий режим (Structured Outputs, `strict:
-- true`). В нём словарь с произвольными ключами невыразим: `additionalProperties
-- : false` и «ключи заранее неизвестны» противоречат друг другу, а без
-- `additionalProperties: false` провайдер отвергает схему целиком.
--
-- Поэтому `survey_answers` едет списком пар `{question, answer}`. У пары есть
-- место и под идентификатор вопроса, и под его текст — промпт разрешает персоне
-- отвечать любым из двух, и правило покрытия в `qa/checks.py` принимает оба.
--
-- ─── Почему промпт правится вместе со схемой ────────────────────────────────
-- Схема выигрывает у промпта: модель физически не сможет вернуть словарь. Но
-- промпт, описывающий словарь, остаётся вторым, противоречащим указанием, и
-- модель тратит на него внимание — а читатель Промпт-студии видит формат,
-- которого больше нет. Расхождение промпта со схемой не ломает прогон и потому
-- живёт долго.
--
-- ─── Почему replace(), а не новый текст целиком ─────────────────────────────
-- Миграция 20 перенесла в SQL весь шаблон, и теперь у него две копии: файл
-- `prompts/respondent.user.md` и строка в базе. Копирование целиком снова
-- развело бы их при первой же правке файла. Точечная замена трогает ровно те
-- два блока, что изменились, и не зависит от остального текста.
--
-- Идемпотентно по условию на template: строка, где список уже есть, под UPDATE
-- не попадает. Правки команд не затрагиваются — у них tenant_id NOT NULL.

BEGIN;

UPDATE prompts
SET template = replace(
      replace(
        template,
        '"survey_answers": { "<id или текст вопроса>": "<ответ по типу вопроса>" },',
        '"survey_answers": [
    { "question": "<id или текст вопроса>", "answer": "<ответ по типу вопроса>" }
  ],'
      ),
      '- `survey_answers` покрывает ВСЕ вопросы из анкеты по их типам (шкала → число,
  эмоции/ценности → массив, удержание → продолжить/остановиться, рекомендация →
  один из 4 вариантов, доля просмотра → целое 0–100, открытый → текст).',
      '- `survey_answers` — список пар, по одной на КАЖДЫЙ вопрос анкеты. В `question`
  — идентификатор вопроса либо его текст, в `answer` — ответ по типу вопроса
  (шкала → число, эмоции/ценности → перечисление через запятую, удержание →
  продолжить/остановиться, рекомендация → один из 4 вариантов, доля просмотра →
  целое 0–100, открытый → текст). Пропущенный вопрос — брак ответа целиком.'
    ),
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'respondent.user'
  AND template LIKE '%"survey_answers": { "<id или текст вопроса>"%';

COMMIT;
