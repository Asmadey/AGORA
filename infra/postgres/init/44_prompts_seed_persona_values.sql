-- 44. Промпт генерации персон перестаёт обещать «3-5 ценностей»
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что меняется. В `persona.generate` строка «values (3-5, из ВЦИОМ-набора
-- портрета)» заменена на «values (ровно 5, из канонического перечня 17
-- традиционных ценностей)».
--
-- ─── Важное про этот промпт ──────────────────────────────────────────────
-- Он НЕ ПОДКЛЮЧЁН к боевой генерации, и миграция его правды не меняет.
-- Проверено 16.09.2026: и задача Celery (`persona/tasks.py`), и CLI зовут
-- `generator.generate_named` — детерминированный путь без модели. Шаблон
-- читает только `generator.render_prompt`, которого не вызывает никто.
--
-- Владелец правил здесь «3-5» на «5», ожидая пять ценностей, и получил прежние
-- три. Настоящая тройка была прибита в `_map_values(rng, n=3)`.
--
-- Тогда зачем миграция. Затем, что промпт виден в Промпт-студии и читается как
-- действующая инструкция. Оставить в нём «3-5» значит оставить ровно ту
-- ловушку, в которую уже попались: текст, обещающий поведение, которого нет.
-- Реестр промптов (`apps/web/lib/prompt-registry.ts`) теперь говорит об этом
-- прямо, а `calledBy` у него — «никем».
--
-- Число ценностей задаёт `VALUES_PER_PERSONA` в `persona/generator.py`,
-- перечень — `data/values/traditional_values.json`.
--
-- Без `updated_at`: такой колонки у `prompts` нет (см. миграцию 43).
--
-- Идемпотентно: повторный прогон запишет тот же текст.

BEGIN;

UPDATE prompts SET template = '# persona.generate (seed)
Генерация Persona DNA. Переменные: {{criteria}}, {{portrait_md}}, {{size}}, {{seed}},
{{segment_distributions}}, {{verbatim_pool}}.
---
Сгенерируй {{size}} УНИКАЛЬНЫХ синтетических персон — правдоподобных представителей аудитории,
описанной ниже. Это не усреднённые копии, а разные живые люди со своими взглядами, которые
могут спорить друг с другом.

Портрет аудитории (grounding):
{{portrait_md}}

Критерии выборки (строго соблюдай пропорции): {{criteria}}
Реальные распределения сегмента (сэмплируй ПО НИМ, а не равномерно): {{segment_distributions}}
Образцы живой речи аудитории (задают лексику и способ рассуждения персон): {{verbatim_pool}}
seed = {{seed}} (детерминизм: те же входы → тот же результат).

Для каждой персоны верни объект:
- id, name (имя), age (число), age_group, gender, geo, city
- occupation (род занятий), position (должность), career_experience (кратко), hobbies (2-4)
- generation (поколение: зумеры/миллениалы/иксы/бумеры по возрасту)
- big_five (шкала 1..5): openness, conscientiousness, extraversion, agreeableness, neuroticism
- values (ровно 5, из канонического перечня 17 традиционных ценностей)
- media_habits, genre_tastes, tolerances, decision_pattern (как решает смотреть/бросить)
- speech_style (2-3 характерные черты речи, опираясь на образцы)
- narrative (связный портрет 3-4 предложения от 3-го лица)

Правила: разнообразие обязательно (против mode collapse); не тащи стереотипы; персоны должны
покрывать спектр мнений сегмента, включая критиков. Верни ТОЛЬКО валидный JSON-массив.
'
 WHERE key = 'persona.generate' AND tenant_id IS NULL;

