-- Состояние генерации набора персон.
--
-- ─── Зачем ──────────────────────────────────────────────────────────────────
-- Генерация аудитории была единственной операцией продукта без обратной связи.
-- Скелеты персон собираются за миллисекунды, а обогащение — последовательный
-- цикл: один вызов модели на персону, таймаут 60 секунд на каждый. Шестьдесят
-- персон не помещались даже в таймаут маршрута (120 секунд): пользователь видел
-- спиннер, который однажды превращался в ошибку, — при том что половина персон
-- уже была написана и оплачена.
--
-- Теперь набор создаётся сразу, а наполняется в фоне. Строка появляется в
-- списке немедленно, и по ней видно «40 из 60».
--
-- ─── Почему статус на самом наборе, а не в отдельной таблице заданий ────────
-- Задание и набор здесь одно и то же: у задания нет ни одного свойства, которое
-- пережило бы генерацию и не относилось бы к набору. Отдельная таблица
-- потребовала бы соединения на каждом экране ради поля, которое всё равно
-- читают вместе с именем и размером.
--
-- ─── Почему generated_count, а не доля ──────────────────────────────────────
-- Доля скрывает масштаб: «60%» одинаково выглядит на пяти персонах и на пятистах,
-- а ждать их надо по-разному. Пользователь просил «40/60» — числами.

BEGIN;

ALTER TABLE persona_sets
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'ready';

-- Наборы, созданные до этой миграции, уже наполнены — им 'ready' по умолчанию.
ALTER TABLE persona_sets DROP CONSTRAINT IF EXISTS persona_sets_status_check;
ALTER TABLE persona_sets ADD CONSTRAINT persona_sets_status_check
  CHECK (status IN ('generating', 'ready', 'failed'));

-- Сколько персон уже записано. Считать их COUNT(*) на каждый опрос списка
-- значило бы сканировать personas по всем наборам арендатора несколько раз в
-- секунду, пока идёт генерация.
ALTER TABLE persona_sets
  ADD COLUMN IF NOT EXISTS generated_count integer NOT NULL DEFAULT 0;

-- Причина отказа рядом с набором: без неё «failed» означает только то, что
-- что-то не вышло, и следующий шаг пользователю неизвестен.
ALTER TABLE persona_sets ADD COLUMN IF NOT EXISTS error text;

-- Момент окончания. По нему видно, сколько заняла генерация, — и видно, что
-- набор в 'generating' висит подозрительно долго.
ALTER TABLE persona_sets ADD COLUMN IF NOT EXISTS finished_at timestamptz;

COMMIT;
