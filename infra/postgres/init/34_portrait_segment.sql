-- ─────────────────────────────────────────────────────────────────────────
-- 34. Портрет сегмента доезжает до сборки персоны
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что было. Раздел «Портреты» оказался отключён от продукта целиком: `grep
-- portrait` по agent_core/pipeline/ давал ноль попаданий, а реестр промптов
-- при этом утверждал, что «портрет подмешивается в генерацию персон».
--
-- Куда подключён. В ОБОГАЩЕНИЕ narrative, не в сэмплирование скелета. Скелет —
-- возраст, география, ценности — обязан остаться детерминированной выборкой из
-- долей корпуса: на этом держится метрика persona_grounding. Портрет влияет на
-- то, КАК персона описана, а не на то, кто она.
--
-- Зачем колонка. Сопоставить персону с портретом можно только по сегменту.
-- Имя портрета человек правит руками, и матчинг по имени сломался бы на первом
-- переименовании — молча, потому что персона просто осталась бы без портрета.
--
-- Формат ключа тот же, что у дистилляции (`portraits/distill.py`,
-- group_by_segment): `age_group|geo|gender`, где `*` в позиции пола означает
-- слитые тонкие сегменты. Свой формат означал бы, что собранные дистилляцией
-- портреты не найдутся никогда.

BEGIN;

ALTER TABLE audience_portraits ADD COLUMN IF NOT EXISTS segment_key text;

-- Индекс частичный: портреты, заведённые вручную, сегмента не имеют и в
-- сопоставлении не участвуют.
CREATE INDEX IF NOT EXISTS audience_portraits_segment_idx
  ON audience_portraits (tenant_id, segment_key)
  WHERE segment_key IS NOT NULL;

COMMIT;
