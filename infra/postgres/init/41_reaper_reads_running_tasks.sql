-- ─────────────────────────────────────────────────────────────────────────
-- 41. Сборщику осиротевших прогонов — узкая политика на идущие прогоны
-- ─────────────────────────────────────────────────────────────────────────
--
-- Что чинится. Сборщик (agent_core/maintenance/reaper.py) обходит прогоны в
-- статусе RUNNING и переводит в FAILED те, чей воркер убит извне. Обойти их он
-- обязан ПО ВСЕМ арендаторам: осиротевший прогон мешает своему владельцу, а не
-- тому, кто в этот момент смотрит на экран.
--
-- Первая редакция ходила под `agora_login` и перечисляла арендаторов из
-- `teams`. Она падала с «permission denied for table teams», и падала
-- правильно: `agora_login` объявлен NOINHERIT именно затем, чтобы запрос без
-- `SET LOCAL ROLE` не имел прав вовсе. А под `agora_app` обход невозможен по
-- существу: эта роль тенант-ограничена по замыслу, и сквозная политика для неё
-- сломала бы изоляцию — то, ради чего вся схема и построена.
--
-- ─── Почему политика владельцу, а не новая роль ──────────────────────────
-- Сборщик — обслуживающая операция того же рода, что миграции: он не отвечает
-- на запросы пользователя и не ходит из веба. Владелец схемы уже выполняет
-- миграции, и отдельная роль с паролем добавила бы третий секрет ради задачи,
-- которая просыпается четыре раза в час.
--
-- Прецедент тот же: 06_owner_read_auth_tables.sql выдаёт владельцу узкий
-- FOR SELECT на две таблицы аутентификации, потому что при FORCE политики
-- действуют и на владельца. FORCE при этом остаётся на всех таблицах.
--
-- ─── Насколько узко ──────────────────────────────────────────────────────
-- По команде: только SELECT и UPDATE, без INSERT и DELETE — сборщик меняет
-- статус, а не заводит и не удаляет прогоны.
-- По строкам: только `status = 'RUNNING'`. Завершённые, отменённые и стоящие в
-- очереди владельцу через эти политики не видны вовсе.
-- По таблице: только `tasks`.
--
-- WITH CHECK на UPDATE намеренно не ограничен статусом RUNNING: сборщик именно
-- УВОДИТ строку из этого статуса, и условие на новое значение запретило бы ему
-- сделать единственное, ради чего он существует.
--
-- Политику видно в `pg_policies`. Снятый FORCE не видно нигде — именно так он
-- однажды и исчез.
--
-- Идемпотентно: DROP POLICY IF EXISTS перед созданием.

BEGIN;

DO $$
DECLARE
  owner_role text;
BEGIN
  SELECT tableowner INTO owner_role FROM pg_tables
   WHERE schemaname = 'public' AND tablename = 'tasks';

  EXECUTE 'DROP POLICY IF EXISTS tasks_reaper_read ON tasks';
  EXECUTE format(
    'CREATE POLICY tasks_reaper_read ON tasks FOR SELECT TO %I USING (status = ''RUNNING'')',
    owner_role
  );

  EXECUTE 'DROP POLICY IF EXISTS tasks_reaper_finish ON tasks';
  EXECUTE format(
    'CREATE POLICY tasks_reaper_finish ON tasks FOR UPDATE TO %I '
    'USING (status = ''RUNNING'') WITH CHECK (true)',
    owner_role
  );
END $$;

COMMIT;
