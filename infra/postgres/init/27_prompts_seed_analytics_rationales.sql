-- AGORA · 27 · analytics.report: обоснования под числами
--
-- ─── Зачем ──────────────────────────────────────────────────────────────────
-- «NPS −33» — это результат, а не вывод. Решение по нему принимают, догадываясь
-- о причине, и догадка редко совпадает с тем, что персоны написали в вербатимах.
-- Число без обоснования выглядит объективнее, чем оно есть: за ним стоят
-- двенадцать текстов, которых читатель отчёта не видит.
--
-- ─── Почему тем же вызовом ──────────────────────────────────────────────────
-- Аналитик и так получает все ответы целиком. Отдельный вызов на каждую метрику
-- утроил бы стоимость синтеза ради трёх абзацев и вдобавок дал бы три
-- независимых пересказа одних и тех же вербатимов, которые могут не сойтись
-- между собой — а несходящиеся объяснения под соседними числами читатель
-- заметит раньше, чем мы.
--
-- Идемпотентно по маркеру в тексте.

UPDATE prompts
SET template = template || '

# Обоснования под числами

Кроме синтеза верни поле `rationales` — по одной фразе на метрику, объясняющей,
ПОЧЕМУ число получилось таким:

```json
"rationales": {
  "nps": "<что мешает или помогает рекомендовать — со ссылкой на момент или цитату>",
  "watched_share": "<где внимание держится, а где рассеивается>",
  "emotional_index": "<какие эмоции преобладают и от чего>"
}
```

Правила те же, что для нарратива: опирайся на вербатимы и таймкоды из ответов, не
пересказывай само число словами. «NPS низкий, потому что оценки низкие» —
негодное обоснование: оно повторяет вопрос вместо ответа. Годное называет то, что
персоны написали: какой момент оттолкнул, какая часть показалась затянутой.

Если оснований в ответах нет, оставь поле пустой строкой. Пустое обоснование
честнее выдуманного: по выдуманному примут решение.'
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'analytics.report'
  AND template NOT LIKE '%Обоснования под числами%';
