-- ─────────────────────────────────────────────────────────────────────────
-- 53. persona.generate: номер версии догоняет текст
-- ─────────────────────────────────────────────────────────────────────────
--
-- Миграция 51 сменила шаблон `persona.generate` (1550 → 2086 знаков: появилась
-- секция дополнительного контекста), но НЕ тронула `version`. Номер так и
-- остался первым.
--
-- Это не косметика. `version` читается и показывается оператору в
-- Промпт-студии (apps/web/lib/server/prompts.ts), то есть человек видит «версия
-- 1» рядом с текстом, которого в первой версии не было. Сравнить «что в базе» с
-- «что ожидалось» по номеру после этого нельзя — а номер для того и заведён.
--
-- Соседняя миграция 49 сделала правильно: `version = version + 1` со сторожем
-- `AND version = 2`. Сторож и делает повтор безопасным — второй прогон найдёт
-- уже другую версию и выдаст UPDATE 0.
--
-- Здесь сторож двойной: номер И признак текста. Номер один отличал бы плохо —
-- первая версия могла быть какой угодно; признак текста один сработал бы и на
-- будущих редакциях, которые этот фрагмент сохранят.

BEGIN;

UPDATE prompts
   SET version = version + 1
 WHERE tenant_id IS NULL
   AND is_default
   AND key = 'persona.generate'
   AND version = 1
   AND template LIKE '%{{audience_context}}%';

COMMIT;
