-- AGORA · 16 · Засев content.frame_analysis: описание относится к сцене, а не к моменту
--
-- Отдельный файл по той же причине, что 10–13: применённая миграция не
-- редактируется (§5 CLAUDE.md), а 07 генерируется скриптом, и перегенерация
-- переписала бы тексты всех промптов заодно.
--
-- ─── Что изменилось и почему ────────────────────────────────────────────────
-- Панель из четырёх кадров уходила в модель одной картинкой, модель возвращала
-- одно описание, а таймкод ему проставлялся от ПЕРВОГО кадра панели. Кадры при
-- этом брались подряд по всему ролику, поэтому в одну панель попадали моменты,
-- разнесённые на полминуты. На ролике 2:42 это дало шесть описаний вместо двух
-- десятков.
--
-- Персона, сославшаяся на момент внутри панели, получала описание от её начала,
-- и QA-судья справедливо видел несовпадение, называя его прямо: «в таймкоде
-- 0:00-0:25 (согласно таймлайну это 0:00-2:00)». Отсюда 40–60% отбраковок по
-- grounding и непроходимый golden-сет.
--
-- Теперь панель — это одна сцена, а кадры берутся ВНУТРИ неё. Промпт получает
-- границы сцены и моменты кадров и прямо говорит модели, что кадры
-- последовательны и что описание относится ко всему отрезку. Таймкоды в
-- результат всё равно проставляет код (Decision Log #14): модель видит только
-- подставленное значение и вольна его переписать.
--
-- Идемпотентно по условию на template: строка, где переменная {{scene_start}}
-- уже есть, под UPDATE не попадает.

UPDATE prompts
SET template = '# content.frame_analysis (seed)
VLM-разбор сцены по панели кадров. Переменные: {{frames}}, {{scene_start}}, {{scene_end}}, {{panel_size}}, {{frame_times}}, {{timestamp}}.
---
На вход — панель из {{panel_size}} кадров ОДНОЙ сцены видео.
Сцена длится с {{scene_start}} по {{scene_end}} секунду; кадры сняты в моменты: {{frame_times}}.

Кадры идут по порядку слева направо, сверху вниз — это последовательные моменты одной
сцены, а не разные сцены. Сравни их между собой: что изменилось от первого к последнему
и есть ли движение — именно из этого берётся поле actions.

Извлеки СЕМАНТИКУ СЦЕНЫ (не портретную репликацию) в чистый JSON:
{
  "timestamp": "{{scene_start}}",
  "scene_description": "<что происходит в сцене целиком, кратко>",
  "actions": ["<действие, видимое по изменению между кадрами>", "..."],
  "characters": [{"appearance":"<кто/как выглядит>","emotion":"<эмоция>"}],
  "setting": "<место/эпоха/обстановка>",
  "mood": "<настроение сцены>",
  "cinematography": {"shot":"<план>","lighting":"<свет>","camera":"<движение/ракурс>"},
  "on_screen_text": "<текст на экране или null>",
  "notable": "<что визуально выделяется: костюмы, реквизит, насилие и т.п.>"
}
Опиши только то, что реально видно. Не выдумывай сюжет за пределами кадров.
Описание относится ко всему отрезку {{scene_start}}–{{scene_end}}, а не к одному кадру.
Верни только JSON.
',
    version = version + 1
WHERE tenant_id IS NULL
  AND is_default
  AND key = 'content.frame_analysis'
  AND template NOT LIKE '%{{scene_start}}%';
