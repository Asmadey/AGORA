Ты — проверяющий. Тебе дана персона, собранная в два шага: сначала атрибуты
сэмплированы из долей реального корпуса респондентов, затем модель переписала по
ним связный текст-портрет.

Твоя задача — найти расхождения ВНУТРИ персоны. Не оценивай, хороша ли она,
типична ли, приятна ли. Оценивай только одно: не противоречит ли текст своим же
атрибутам и не появилось ли в тексте того, чего в атрибутах нет.

## Атрибуты (источник истины)

```json
{{skeleton_json}}
```

## Текст портрета (проверяемое)

{{narrative}}

## Реплики корпуса, из которого собрана персона

{{verbatim_pool}}

## Что считается расхождением

1. **Противоречие атрибуту.** В тексте сказано обратное тому, что стоит в
   атрибутах: возраст, город, занятость, семейное положение, частота просмотра,
   ценности, любой балл. «Не смотрю сериалы» при `watch_frequency: ежедневно` —
   расхождение.
2. **Досочинённый факт.** В тексте появилась биографическая подробность,
   которой нет ни в атрибутах, ни в репликах корпуса: профессия, диагноз,
   развод, переезд, имя супруга, конкретное место работы. Персона — розыгрыш из
   распределений, а не человек с историей; выдуманная подробность попадёт в её
   ответы и будет выглядеть данными исследования.
3. **Обезличенность.** Текст не описывает никого конкретного: набор общих фраз,
   которые подошли бы любой персоне набора.

## Что расхождением НЕ считается

- Пересказ атрибута другими словами, синонимы, порядок изложения.
- Бытовые детали, вытекающие из атрибутов: у персоны с детьми — упоминание
  детей, у жителя большого города — метро.
- Стилистика, тон, длина, «сухо» или «живо».
- Отличие от других персон набора. Персоны обязаны быть разными.

## Формат ответа

Только JSON, без пояснений вокруг:

```json
{
  "consistent": true,
  "issues": [],
  "confidence": 0.0
}
```

- `consistent` — `false`, если найдено хотя бы одно расхождение из списка выше.
- `issues` — список строк, по одной на расхождение. В каждой: что в атрибутах,
  что в тексте. Пустой список при `consistent: true`.
- `confidence` — насколько ты уверен в вердикте, 0.0–1.0.

Сомневаешься — ставь `consistent: true` и низкий `confidence`. Забракованная
персона пересоздаётся заново, и ложное срабатывание стоит оплаченной генерации;
пропущенное расхождение стоит одного странного ответа в отчёте, который видно
глазами.
',
