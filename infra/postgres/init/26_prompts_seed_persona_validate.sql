-- ─── Что чинится ────────────────────────────────────────────────────────────
-- Миграция 21 засеяла persona.validate плоским текстом, а prompts/persona.validate.md
-- живёт размеченным: пустые строки, ограждение json, выделение пунктов. Тексты
-- разошлись — и это не косметика: на чистой базе модель получала одну редакцию,
-- а падение назад к файлу (`_prompt` в nodes.py) давало другую. Две инструкции
-- на одну роль расходятся дальше с каждой правкой, потому что правят обычно ту,
-- что попалась под руку.
--
-- ─── Почему это не заметили ─────────────────────────────────────────────────
-- Сверка засевов с файлами читала только формы `VALUES (...)` и `SET template =`,
-- а миграция 21 написана как `INSERT ... SELECT` — ей нужен `WHERE NOT EXISTS`
-- для идемпотентности. Проверка не видела засев вовсе и говорила «ключ не найден»
-- вместо «текст разошёлся». Разбор третьей формы добавлен в
-- evals/tests/test_task26_prompt_studio.py этим же изменением.
--
-- Идемпотентно: WHERE отсекает повтор по совпадению текста.

