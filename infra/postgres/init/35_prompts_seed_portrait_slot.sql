-- ─────────────────────────────────────────────────────────────────────────
-- 35. Слот портрета в промпте обогащения персоны
-- ─────────────────────────────────────────────────────────────────────────
--
-- Отдельным файлом от миграции 34, где заводится колонка сегмента: имя обязано
-- попадать под маску `*prompts_seed*.sql`, иначе сверка текстов промптов с
-- файлами эту правку не увидит и покраснеет с неверной причиной. Так уже было
-- с четырьмя другими формами записи — проверка их не знала и молчала там, где
-- текст разошёлся.
--
-- Точечной вставкой, а не заменой шаблона целиком: у арендатора может быть своя
-- редакция из Промпт-студии, и полная замена стёрла бы её.

BEGIN;

-- Слот портрета в промпте обогащения. Точечной вставкой, а не заменой шаблона целиком:
-- у арендатора может быть своя редакция из Промпт-студии.
UPDATE prompts
SET template = replace(
      replace(
        template,
        '{{hobbies}}, {{work_status}}, {{min_len}}.',
        '{{hobbies}}, {{work_status}}, {{min_len}}, {{portrait_md}}.'
      ),
      'Увлечения: {{hobbies}}.

Требования к тексту:',
      'Увлечения: {{hobbies}}.

{{portrait_md}}

Требования к тексту:'
    )
WHERE key = 'persona.enrich'
  AND template NOT LIKE '%{{portrait_md}}%';

COMMIT;
