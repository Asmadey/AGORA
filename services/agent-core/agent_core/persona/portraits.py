"""
Сопоставление персоны с портретом её сегмента.

─── Зачем ────────────────────────────────────────────────────────────────────
Раздел «Портреты» был отключён от продукта целиком: `grep portrait` по
`agent_core/pipeline/` давал ноль попаданий, а реестр промптов при этом
утверждал, что «портрет подмешивается в генерацию персон».

Подключён он к ОБОГАЩЕНИЮ, а не к сэмплированию скелета. Скелет — возраст,
география, ценности — обязан остаться детерминированной выборкой из долей
корпуса: на этом держится метрика `persona_grounding`. Портрет влияет на то,
КАК персона описана, а не на то, кто она.

─── Почему ключ именно такой ─────────────────────────────────────────────────
`age_group|geo|gender` — формат, которым дистилляция называет сегменты
(`portraits/distill.py`, `group_by_segment`). Свой формат здесь означал бы, что
собранные дистилляцией портреты не найдутся никогда, а заметить это можно было
бы только по тому, что narrative не изменился.
"""

from __future__ import annotations

from typing import Any

#: Чем дистилляция помечает слитые тонкие сегменты: у неё сегмент меньше трёх
#: записей уезжает в общую корзину `age|geo|*`. Не искать её значило бы
#: оставить без портрета ровно те сегменты, ради которых слияние и сделано.
ANY = "*"


def segment_key_of(persona: dict[str, Any]) -> str:
    """Ключ сегмента персоны в формате дистилляции."""
    demo = persona.get("demographics") or {}
    age = demo.get("age_group") or "?"
    geo = demo.get("geo") or "?"
    gender = demo.get("gender") or "?"
    return f"{age}|{geo}|{gender}"


def portrait_for(persona: dict[str, Any], portraits: dict[str, str]) -> str:
    """
    Портрет сегмента персоны или пустая строка.

    Пустая строка, а не ближайший похожий: чужой портрет хуже отсутствующего.
    Персона получит описание сегмента, к которому не принадлежит, и выглядеть
    это будет убедительно — то есть неотличимо от верного.
    """
    if not portraits:
        return ""

    key = segment_key_of(persona)
    if key in portraits:
        return portraits[key]

    age, geo, _ = key.split("|")
    return portraits.get(f"{age}|{geo}|{ANY}", "")
