"""
Следует ли назначение ценностей корпусу — три числа вместо тишины.

─── Почему этого не было ────────────────────────────────────────────────────
`persona_grounding` называется «заземлением персоны», а сверяет возраст, гео,
пол и средние баллы. Ценности в ней не участвуют и никогда не участвовали.

При этом `persona/enrich.py` утверждал обратное: «по ним считается
persona_grounding» в комментарии к `GROUNDED_FIELDS`, где `values_and_beliefs`
перечислено. Каждый, кто открывал файл, видел «ценности заземлены» и шёл
дальше. Три дефекта прожили из-за этой строки месяцы: три ценности вместо
пяти, одинаковый топ-2 у всех персон и значения из топ-15 корпуса вместо
канонического перечня.

Метрика, не покрывающая то, что обещает её имя, опаснее отсутствующей: вторую
заводят, на первую полагаются.

─── Чем этот модуль НЕ является ─────────────────────────────────────────────
Защитой. Защита приехала 16.09.2026 тестами `test_persona_values.py`, и они
блокируют слияние — чего метрика не делает по решению владельца
(`required: false`).

Здесь добавляются ровно две вещи, которых у тестов нет:

* ПОРЯДОК всех семнадцати. Тест `test_частые_в_корпусе_остаются_частыми`
  сравнивает «Крепкую семью» с «Коллективизмом» — две крайности, — и молчит о
  пятнадцати значениях между ними.
* ЧИСЛО, которое человек сравнит с прошлым прогоном. Тест отвечает «да/нет» и
  не показывает, что корреляция сползла с 0.95 до 0.82 за три правки.

─── Почему не сравниваются абсолютные доли ──────────────────────────────────
Прямое соответствие корпусу разорвано СОЗНАТЕЛЬНО: пять ценностей на персону
против 1.45 у реального респондента, плюс сглаживание `+1`, дающее вес
значениям с нулевой поддержкой.

Проверка вида `|gen − real| ≤ 0.10` краснела бы всегда и по построению. Метрика,
красная независимо от состояния системы, — это шум, который перестают читать, и
рядом с ним перестают читать остальные.

Поэтому сравнивается порядок, а не величины.
"""

from __future__ import annotations

import statistics
from collections.abc import Sequence
from typing import Any

#: Ниже этого порядок перестаёт считаться следующим корпусу.
#:
#: 0.8, а не 0.95: выборка без повторов сжимает верхушку (одна персона не может
#: взять «Крепкую семью» дважды), сглаживание приподнимает хвост, и точного
#: совпадения рангов не бывает даже у исправного генератора. Замер на 200
#: персонах даёт около 0.95 — порог оставляет запас на колебания выборки, но
#: ловит подмену весов равномерными (там корреляция уходит к нулю).
MIN_RANK_CORRELATION = 0.8

#: Сколько персон нужно, чтобы отсутствие ценности значило дефект, а не невезение.
#:
#: У «Созидательного труда» вес 0.44 %: на ста персонах он может не выпасть ни
#: разу честно. На пятистах ожидание около одиннадцати появлений, и ноль здесь
#: уже означает, что значение выпало из пула.
COVERAGE_SAMPLE = 500


def _ranks(values: Sequence[float]) -> list[float]:
    """
    Ранги со средним на связках.

    Связки — не редкость, а норма: в корпусе несколько пар ценностей с равной
    частотой («Милосердие» и «Приоритет духовного» по 10, «Жизнь» и
    «Взаимопомощь» по 9). Ранг по порядку сортировки дал бы им разные места и
    занизил корреляцию на ровном месте.
    """
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        shared = (i + j) / 2 + 1
        for k in range(i, j + 1):
            ranks[order[k]] = shared
        i = j + 1
    return ranks


def spearman(a: Sequence[float], b: Sequence[float]) -> float:
    """
    Ранговая корреляция. `0.0` — когда считать нечего.

    Ноль, а не `NaN`, при вырожденном входе (все значения равны): `NaN`
    просочился бы в отчёт и сравнился бы с порогом непредсказуемо — `NaN < 0.8`
    ложно, то есть метрика молча стала бы зелёной.
    """
    if len(a) != len(b) or len(a) < 2:
        return 0.0

    ra, rb = _ranks(a), _ranks(b)
    if len(set(ra)) < 2 or len(set(rb)) < 2:
        return 0.0

    ma, mb = statistics.fmean(ra), statistics.fmean(rb)
    num = sum((x - ma) * (y - mb) for x, y in zip(ra, rb, strict=True))
    da = sum((x - ma) ** 2 for x in ra) ** 0.5
    db = sum((y - mb) ** 2 for y in rb) ** 0.5
    if da == 0 or db == 0:
        return 0.0
    return round(num / (da * db), 4)


def values_grounding(*, size: int, seed: int) -> dict[str, Any]:
    """
    Замер: генерирует персон и сверяет порядок ценностей с корпусом.

    Ни модели, ни артефактов, ни денег: генератор детерминирован, корпус лежит
    в образе. Поэтому метрика работает везде, где работает `pytest`, — в
    отличие от `persona_grounding`, которому нужен артефакт эталонного прогона.
    """
    from .generator import TRADITIONAL_VALUES, GenerationConfig, PersonaGenerator

    gen = PersonaGenerator.from_corpus()
    personas = gen.generate(GenerationConfig(size=size, seed=seed))

    counts = dict.fromkeys(TRADITIONAL_VALUES, 0)
    for p in personas:
        for v in (p.get("values_and_beliefs") or {}).get("important_values") or []:
            if v in counts:
                counts[v] += 1

    # value_counts уже собран только из личного вопроса корпуса. Не сверяемся
    # напрямую с psychographics_and_values: это поле смешивает два вопроса.
    corpus = gen.dist.value_counts
    order = list(TRADITIONAL_VALUES)
    got = [counts[v] for v in order]
    expected = [corpus.get(v, 0) for v in order]

    missing = [v for v in order if counts[v] == 0]
    return {
        "personas": size,
        "rank_correlation": spearman(expected, got),
        "coverage": 17 - len(missing),
        "missing": missing,
        # Доля самой частой ценности. Ровно 1.0 означает, что она стоит у ВСЕХ
        # персон, — это константа, а не выборка.
        "max_share": round(max(got) / size, 4) if size else 0.0,
    }
