"""
Поиск файлов репозитория, которые нужны воркеру в работе.

─── Зачем отдельный модуль ──────────────────────────────────────────────────
Раскладок две, и они не совпадают:

    репозиторий   AGORA/services/agent-core/agent_core/…   данные в AGORA/data/
    образ         /app/agent_core/…                        данные в /app/data/

Арифметика по `Path(__file__).parents[N]` верна ровно для одной из них. Для
второй она даёт мимо — и молча: `parents[4] / "data"` в образе разворачивается
в `/data`, то есть в корень файловой системы, где ничего нет.

Так и случилось с корпусом, когда генерация аудитории переехала из веба в
воркер: `FileNotFoundError: '/data/grounding/unified_respondent_sessions.json'`.
Причём отказ был двойным — файла в образе не было вовсе, а путь к нему был
неверным; починка одного оставила бы вторую половину.

Тот же приём уже дважды написан по месту (`_find_prompt` в `persona/enrich.py`
и в `respondent/run.py`) — верный признак, что жить он должен один раз.

─── Почему поиск, а не переменная окружения ─────────────────────────────────
Переменную надо не забыть выставить в образе, в compose, в CI и в тестах, и
забытая проявляется как «файл не найден» — то есть так же, как дефект, который
она должна была предотвратить. Поиск по известным раскладкам не требует ничего.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["find_data_file", "find_repo_file"]

#: Сколько уровней вверх осматривать. Шести хватает обеим раскладкам с запасом;
#: больше — риск подняться выше корня репозитория и найти чужой файл.
_MAX_DEPTH = 6


def find_repo_file(relative: str) -> Path | None:
    """
    Файл по пути относительно корня раскладки. `None` — не найден.

    `None`, а не исключение: вызывающий сам решает, отсутствие это отказ
    (корпус) или законное состояние (необязательная фикстура).
    """
    here = Path(__file__).resolve()
    tail = Path(relative)
    for parent in here.parents[:_MAX_DEPTH]:
        candidate = parent / tail
        if candidate.exists():
            return candidate
    return None


def find_data_file(relative: str) -> Path | None:
    """
    Файл из каталога `data/`.

    В репозитории это `AGORA/data/…`, в образе воркера — `/app/data/…`
    (см. `infra/worker.Dockerfile`, где `data/` копируется рядом с исходниками).
    """
    return find_repo_file(str(Path("data") / relative))
