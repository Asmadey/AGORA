"""
Что видит собеседник: срез данных для аналитика и для персоны.

─── Изоляция здесь механизм, а не проверка ──────────────────────────────────
Персона не «просит не подглядывать» — ей нечего показать. В срез попадают её
профиль, материал, анкета и ЕЁ прежние ответы; чужие ответы в структуру не
кладутся вовсе. Тот же приём, что в `respondent.run.build_slice`, и та же
причина: проверка вывода зелена ровно до первого совпадения формулировок.

─── Почему персона не знает об отчёте ───────────────────────────────────────
Она зритель, а не участник исследования. Агрегат, темы и чужие оценки ей знать
неоткуда, а знание превратило бы ответ в подстройку под уже посчитанный итог —
то есть в то самое соглашательство, против которого написан весь промпт.

─── Про объём ───────────────────────────────────────────────────────────────
Аналитик получает ВСЕ ответы этого исследования, без выборок. Размер продукта
это допускает: потолок аудитории — 100 персон (`AUDIENCE_SIZE_BOUNDS`), самый
большой боевой набор дал 231 КБ ответов. Урезать то, что влезает, значит
отвечать по части данных и не иметь способа об этом сказать.

Урезается не содержание, а служебное — см. `slim_pack` ниже. Разница
принципиальная: выборка отвечает по части данных, чистка отдаёт те же данные
без их внутренних координат.
"""

from __future__ import annotations

import copy
import json
from typing import Any


def _own_answers(answers: list[dict[str, Any]], persona_id: str) -> list[dict[str, Any]]:
    """Ответы одной персоны. Копия: срез не вправе менять то, из чего собран."""
    return [
        copy.deepcopy(a)
        for a in answers
        if str(a.get("persona_id") or a.get("personaId") or "") == str(persona_id)
    ]


#: Поля сцены, которые в разговор не едут.
#:
#: `screenshot` — подписанная ссылка на файл в S3. Текстовая модель картинок не
#: видит; на боевом прогоне 0091 это 15 233 токена URL, из которых не следует
#: ничего.
#:
#: `frame_times`, `panel_index`, `key` — внутренние координаты нарезки и склейки
#: панелей. Нужны конвейеру, а не собеседнику.
#:
#: `timestamp` — строковый двойник `timestamp_sec`: «6.00» против 6.0.
#:
#: ЧЕГО ЗДЕСЬ НЕТ И НЕ ДОЛЖНО БЫТЬ: `time`. Оно выглядит четвёртым написанием
#: времени, но в нём лежит «0:06–0:16» — ровно тот формат `MM:SS`, который
#: промпт требует для ссылок, а `has_support` ищет регуляркой. Убрав его, мы
#: оставили бы модели только числа вида 6.0: она писала бы «на 6-й секунде»,
#: опора не засчитывалась бы, и каждый ответ получал бы пометку «без опоры на
#: материал». Отказа при этом не было бы — чат выглядел бы исправным.
_SCENE_NOISE = ("screenshot", "frame_times", "panel_index", "key", "timestamp")

#: Ключи пакета, которые в разговор не едут.
#:
#: `timeline` — не данные, а ВИД: он собран для экрана из тех же `scenes` и
#: `transcript`, в другой форме. Модель получала описания всех сцен дважды —
#: 61 403 токена на прогоне 0091.
_PACK_NOISE = ("timeline",)


def slim_pack(pack: dict[str, Any]) -> dict[str, Any]:
    """
    Пакет материала без служебного веса.

    ─── Зачем ────────────────────────────────────────────────────────────────
    16.09.2026 чат по прогону 0091 отвечал отказом: 260 945 токенов входа при
    потолке 262 144. Замер показал, что 88 % веса — пакет материала, и 34 % от
    всего контекста не несут ни одного факта, которого нет рядом.

    ─── Что это НЕ ───────────────────────────────────────────────────────────
    Не выборка. Ни одна сцена, ни одна реплика и ни одно описание отсюда не
    пропадают: убираются только внутренние координаты и дубликат вида. Разница
    важна — выборка означала бы ответ по части материала, и об этом пришлось бы
    предупреждать в каждом ответе.

    Копия, а не правка на месте: пакет читается один раз и живёт дальше, а срез
    не вправе менять то, из чего собран, — тот же довод, что у `_own_answers`.
    """
    slim = {k: copy.deepcopy(v) for k, v in pack.items() if k not in _PACK_NOISE}

    scenes = slim.get("scenes")
    if isinstance(scenes, list):
        slim["scenes"] = [
            {k: v for k, v in scene.items() if k not in _SCENE_NOISE}
            if isinstance(scene, dict)
            else scene
            for scene in scenes
        ]

    return slim


#: Потолок контекста модели. Тот же, о котором сообщил отказ 16.09.2026:
#: «maximum context length is 262144 tokens».
CONTEXT_LIMIT = 262_144

#: Выше этого — едем оглавлением и инструментами, а не материалом целиком.
#:
#: Запас до потолка не про осторожность, а про арифметику: сверх среза в
#: запросе живут вопрос, история разговора и место под ответ
#: (`client.MAX_TOKENS`), а сама оценка приблизительна. Порог, равный потолку,
#: означал бы проверку, срабатывающую после того, как всё сломалось.
TOOLS_THRESHOLD = 150_000

#: Символов на токен. Замер на боевом прогоне 0091: оценка по этому делителю
#: дала 261 103 там, где шлюз насчитал 260 945 — расхождение 0.06 %. Точный
#: счётчик потребовал бы токенизатора модели в образе ради решения, которое
#: принимается один раз за разговор.
CHARS_PER_TOKEN = 2.6


def estimate_tokens(obj: Any) -> int:
    """Приблизительный вес среза в токенах. Приблизительный — и этого хватает."""
    return int(len(json.dumps(obj, ensure_ascii=False, default=str)) / CHARS_PER_TOKEN)


def needs_tools(context_or_pack: Any) -> bool:
    """Не помещается целиком — значит, поедет оглавлением и инструментами."""
    return estimate_tokens(context_or_pack) > TOOLS_THRESHOLD


def index_pack(pack: dict[str, Any]) -> dict[str, Any]:
    """
    Пакет, свёрнутый до оглавления: полные описания сцен модель запросит сама.

    ─── Что остаётся, а что уходит ───────────────────────────────────────────
    Уходят `scenes` — 157 953 токена на прогоне 0091, 60 % всего веса. Вместо
    них `scene_index`: номер, таймкод, одна фраза, около 8 000 токенов.

    Речь ОСТАЁТСЯ на месте. Она втрое легче сцен (11 087 токенов) и нужна почти
    любому вопросу; сворачивать её ради одного процента веса значило бы
    добавить раунд там, где он не нужен.

    Нумерация оглавления совпадает с нумерацией на экране исследования
    (`Timeline.tsx`, `sceneNumber`) — см. `tools.scene_index`. Расхождение здесь
    не дало бы ошибки: оно дало бы уверенный ответ про чужую сцену.
    """
    from .tools import scene_index

    slim = slim_pack(pack)
    slim["scene_index"] = scene_index(pack)
    slim.pop("scenes", None)
    return slim


def persona_context(
    *,
    persona: dict[str, Any],
    pack: dict[str, Any],
    survey: Any,
    answers: list[dict[str, Any]],
    history: list[dict[str, Any]],
    with_tools: bool = False,
) -> dict[str, Any]:
    """Срез для допроса персоны. Чужих ответов здесь нет как данных."""
    return {
        "persona_dna": copy.deepcopy(persona.get("dna") or {}),
        "video_understanding": index_pack(pack) if with_tools else slim_pack(pack),
        "survey": copy.deepcopy(survey),
        "my_previous_answers": _own_answers(answers, str(persona.get("id") or "")),
        "chat_history": copy.deepcopy(history),
    }


def analyst_context(
    *,
    report: dict[str, Any],
    pack: dict[str, Any],
    survey: Any,
    answers: list[dict[str, Any]],
    qa_flags: list[dict[str, Any]] | None,
    history: list[dict[str, Any]],
    with_tools: bool = False,
) -> dict[str, Any]:
    """Срез для аналитика: отчёт и все ответы этого исследования."""
    return {
        "report": copy.deepcopy(report),
        "all_persona_answers": copy.deepcopy(answers),
        "video_understanding": index_pack(pack) if with_tools else slim_pack(pack),
        "survey": copy.deepcopy(survey),
        "qa_flags": copy.deepcopy(qa_flags or []),
        "chat_history": copy.deepcopy(history),
    }
