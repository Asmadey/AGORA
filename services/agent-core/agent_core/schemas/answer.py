"""
Приведение ответа персоны к словарю корпуса.

─── Что чинится ──────────────────────────────────────────────────────────────
Владелец увидел в списке персон разнобой: одни отвечали на «досмотрит?»
процентами, другие словами — «хотелось досмотреть», «скорее досмотреть».
Причина не в модели. Словарей для одного поля в репозитории было ТРИ:

    корпус ВЦИОМ            3 закрытых значения (140 / 22 / 3 из 165 записей)
    промпт персоны          4 подсказки, придуманных отдельно от корпуса
    правило в том же промпте  2 («удержание → продолжить/остановиться»)

Корпус — единственный из трёх, который что-то значит: на нём заземлён продукт,
и только с ним ответы персон можно сравнить с ответами живых людей. К нему и
приводим.

─── Почему приведение, а не строгая схема ────────────────────────────────────
Строгий режим для ответа персоны выключен намеренно, по замеру: 8 разобранных
ответов из двенадцати со схемой против 12 из 12 без неё; это держит
`test_respondent_goes_without_a_schema`. `RESPONDENT` и `_PERCEPTION` в
рантайме не используются вовсе.

Значит, ограничить провайдера нечем, и приведение стоит ПОСЛЕ разбора. Оно не
запрещает модели ответить как угодно — оно превращает ответ в величину, которую
можно сложить с другими.

─── Почему исходная строка сохраняется ───────────────────────────────────────
Два довода, и второй важнее. Переписывать чужой ответ молча нельзя. И по
несовпадению видно то, чего иначе не увидеть: что промпт разошёлся с моделью —
например, после правки промпта, которую никто не сверил с этим модулем.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

#: Словарь корпуса. Ровно эти три строки лежат в
#: `packages/shared/schemas/respondent-session.schema.json` и в
#: `data/grounding/unified_respondent_sessions.json`.
RETENTION_CONTINUE = "Скорее хотелось досмотреть до конца"
RETENTION_STOP = "Скорее хотелось остановить просмотр"
RETENTION_UNSURE = "Затрудняюсь ответить"

RETENTION_VALUES = (RETENTION_CONTINUE, RETENTION_STOP, RETENTION_UNSURE)

#: Отрицание проверяется ПЕРВЫМ. «не стал бы досматривать» содержит и «досмотр»,
#: и отрицание, и порядок решает, в какую сторону будет ошибка. Ошибаться в
#: сторону «досмотрят» нельзя: это завышает главную метрику отчёта.
_STOP = (
    "не досм", "не стал", "не буду", "не хотел",
    "выключ", "останов", "прекрат", "бросил", "перестал",
)
_CONTINUE = ("досмотр", "до конца", "продолж", "не отрыва", "досматрив")
_UNSURE = ("затрудня", "не знаю", "сложно сказать")

#: Процент в поле категории. Не приводится ни к чему: это признак, что модель
#: перепутала два вопроса анкеты, и молча превратить его в «досмотрят» значит
#: сделать отчёт увереннее, чем данные под ним.
_PERCENT = re.compile(r"^\s*\d{1,3}\s*%?\s*$")


@dataclass(frozen=True)
class Retention:
    """
    Приведённая категория и то, что сказала модель.

    `value is None` означает «привести не удалось» — законное состояние, с
    которым дальше работает `retention_stance`. Подставлять сюда
    «Затрудняюсь ответить» нельзя: это ЗНАЧЕНИЕ корпуса, участвующее в долях, а
    не признак неудачи разбора.
    """

    value: str | None
    raw: str


def normalize_retention(said: object) -> Retention:
    """Ответ персоны про досмотр — в словарь корпуса."""
    raw = str(said or "").strip()
    if not raw:
        return Retention(value=None, raw="")

    text = raw.lower()

    for known in RETENTION_VALUES:
        if text == known.lower():
            return Retention(value=known, raw=raw)

    if _PERCENT.match(raw):
        return Retention(value=None, raw=raw)

    if any(m in text for m in _UNSURE):
        return Retention(value=RETENTION_UNSURE, raw=raw)
    if any(m in text for m in _STOP):
        return Retention(value=RETENTION_STOP, raw=raw)
    if any(m in text for m in _CONTINUE):
        return Retention(value=RETENTION_CONTINUE, raw=raw)

    return Retention(value=None, raw=raw)
