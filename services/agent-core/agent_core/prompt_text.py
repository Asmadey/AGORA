"""
Тело промпта отдельно от его документации.

─── Зачем ────────────────────────────────────────────────────────────────────
Файлы `prompts/*.md` устроены так: служебная шапка, разделитель `---`, тело.
Шапка объясняет ЧЕЛОВЕКУ, что за промпт и какие переменные подставляются:

    # qa.grounding (seed) — LLM-as-judge
    Переменные: {{persona_answer}}, {{video_understanding}}.

    ---

    Ты — верификатор. ...

Веб это понимает: `loadPromptSource` делит по первому `\\n---\\n` и показывает
шапку отдельно. Воркер не делил — и подставлял переменные в неё тоже. Ответ
персоны и понимание видео уезжали в модель дважды: один раз в перечне
переменных, второй раз по месту.

По трассам прогона 0051 это около 1,16 миллиона токенов из примерно 2,8 — то
есть больше трети прогона уходило на повтор тех же данных под заголовком
«Переменные». Плюс модель получала весь разбираемый JSON первым, до инструкций.

─── Почему не «резать до первого ---» ────────────────────────────────────────
Черта бывает и в теле: автор ставит её для читаемости, и безусловное правило
съело бы начало промпта. Признак именно служебной шапки — строка «Переменные:»
до первого разделителя. Её ставит формат, а не автор.

Резать в момент чтения, а не в базе: снимки прогонов уже содержат шаблоны с
шапкой, и перезаписывать их задним числом значило бы менять то, по чему прогон
уже отработал.
"""

from __future__ import annotations

#: Разделитель шапки и тела. Ровно в таком виде его ставит формат и ищет веб.
SEPARATOR = "\n---\n"

#: Подпись формата: строка, которой шапка объявляет подставляемые переменные.
#: Без неё текст до `---` считается телом промпта, а не документацией.
MARKER = "Переменные:"


def body_of(template: str | None) -> str:
    """
    Тело промпта без служебной шапки.

    Шапка снимается только когда она есть по обоим признакам сразу: до первого
    `---` встречается «Переменные:». Иначе шаблон возвращается как есть —
    промпт, написанный владельцем в студии, шапки не имеет и резать в нём
    нечего.

    Идемпотентно: повторный вызов ничего не меняет.
    """
    text = template or ""
    cut = text.find(SEPARATOR)
    if cut < 0:
        return text
    if MARKER not in text[:cut]:
        return text
    return text[cut + len(SEPARATOR):].lstrip("\n")
