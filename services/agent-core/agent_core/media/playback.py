"""
Копия ролика для просмотра в браузере — 720p H.264 с индексом в начале файла.

─── Что чинится ──────────────────────────────────────────────────────────────
Отчёт читают рядом с роликом, а ролик отдаётся из S3 как есть. Отсюда две беды,
обе портят просмотр и обе невидимы в логах:

· Исходник может быть в HEVC или AV1. Chrome и Firefox такое не покажут, и
  человек увидит чёрный прямоугольник вместо материала, по которому только что
  прочитал выводы.
· Индекс mp4 (`moov`) обычно лежит в КОНЦЕ файла. Пока он не скачан, перемотка
  невозможна: на ролике в 700 МБ прыжок на вторую минуту означает скачать всё.

─── Почему progressive, а не HLS ─────────────────────────────────────────────
Замер на боевом железе (18.08.2026, ролик 161,7 с / 40 МБ):

    лесенка 1080/720/480/360   158 с   217 МБ
    одна ступень HLS            57 с    61 МБ
    progressive + faststart     56 с    59 МБ

Смысл HLS — переключение качества на лету, и оно требует НЕСКОЛЬКИХ ступеней. С
одной ступенью берётся вся механика и не берётся ни одной её выгоды, зато
платится дважды: библиотекой hls.js для Chrome и Firefox и подписью ссылок —
бакет закрытый, а плейлист ссылается на два десятка сегментов, каждый со своим
часовым сроком. Ролик, открытый дольше часа, начал бы спотыкаться на середине, и
выглядело бы это сбоем сети. Один файл — одна ссылка, один срок.

Лесенка нужна, когда ролик смотрят с телефона по мобильной сети. Сегодня его
смотрит один человек рядом с отчётом, обычно из того же кабинета, откуда и
загрузил.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

from .errors import MediaError
from .probe import _tool, probe

#: Целевая ширина. 720p — компромисс между «видно детали кадра» и весом:
#: перекодированный ролик вчетверо легче исходного 1080p.
DEFAULT_WIDTH = 1280

#: Пресет x264. `veryfast` выбран замером: он даёт ~1× реального времени на
#: четырёх ядрах, которые к тому же делятся с whisper и pyannote. Более
#: медленные пресеты экономят проценты веса ценой минут прогона.
PRESET = "veryfast"

FFMPEG_TIMEOUT = 60 * 60


def needs_transcode(src: str | Path, width: int = DEFAULT_WIDTH) -> bool:
    """
    Нужно ли вообще перекодировать.

    Ролик, который уже H.264 и не шире целевой ширины, перекодировать незачем:
    это минута процессора и потеря качества в обмен на ничто. Контейнер при этом
    всё равно пересобирается — ради `faststart`, — но видеопоток копируется.
    """
    info = probe(src)
    return info.codec.lower() not in ("h264", "avc1") or info.width > width


def make_playback(
    src: str | Path,
    dst: str | Path,
    width: int = DEFAULT_WIDTH,
) -> Path:
    """
    Собирает копию для просмотра. Возвращает путь к готовому файлу.

    `-movflags +faststart` переносит `moov` в начало вторым проходом по файлу —
    поэтому ключ стоит всегда, даже когда видеопоток копируется без сжатия.
    Именно он и есть причина существования этой функции: без него перемотка
    требует полной загрузки, а с ним работает сразу.
    """
    src_p, dst_p = Path(src), Path(dst)
    dst_p.parent.mkdir(parents=True, exist_ok=True)

    if needs_transcode(src_p, width):
        video_args = [
            # `-2` вместо `-1`: высота округляется до чётной, иначе yuv420p
            # отвергает кадр с нечётной стороной, и отказ приходит не от
            # масштабирования, а от кодека — искать его будут не там.
            "-vf", f"scale='min({width},iw)':-2",
            "-c:v", "libx264", "-preset", PRESET, "-crf", "23",
            "-pix_fmt", "yuv420p",
        ]
    else:
        video_args = ["-c:v", "copy"]

    result = subprocess.run(
        [_tool("ffmpeg"), "-y", "-v", "error", "-i", str(src_p),
         *video_args,
         # Звук приводится к AAC всегда: он лёгкий, а исходный кодек может быть
         # таким же неиграбельным, как видео.
         "-c:a", "aac", "-b:a", "128k",
         "-movflags", "+faststart",
         str(dst_p)],
        capture_output=True, timeout=FFMPEG_TIMEOUT,
    )
    if result.returncode != 0 or not dst_p.exists() or dst_p.stat().st_size == 0:
        raise MediaError(
            "не удалось собрать копию для просмотра: "
            + (result.stderr.decode("utf-8", "replace")[-300:] or "ffmpeg молча не создал файл")
        )
    return dst_p
