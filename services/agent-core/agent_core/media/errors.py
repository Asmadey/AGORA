"""Ошибки препроцессинга."""

from __future__ import annotations


class MediaError(RuntimeError):
    """
    Файл не годится для разбора либо ffmpeg отказался его обрабатывать.

    Отдельный тип нужен, чтобы вызывающий отличал предсказуемый отказ («в файле
    нет видеодорожки», «контейнер повреждён») от поломки развёртывания («ffmpeg
    не установлен»). Без этого различия второе маскируется под первое: продукт
    показывает пользователю «неподдерживаемый файл», хотя на самом деле сломан
    сам сервис, и никто об этом не узнает.

    Именно так уже вышло с ffprobe в веб-контейнере: его там не было, а ответ
    выглядел как отказ по содержимому файла.
    """


class FFmpegMissing(MediaError):
    """
    ffmpeg или ffprobe отсутствуют в системе.

    Наследуется от MediaError, чтобы общий except не пропустил её мимо, но
    отдельным типом — чтобы код, которому важно различие, мог его сделать.
    """
