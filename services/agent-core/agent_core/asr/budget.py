"""
Помещаются ли расшифровка и диаризация в память одновременно.

─── Зачем этот модуль вообще ─────────────────────────────────────────────────
`transcribe_and_diarize` запускает обе половины в потоках одного процесса. Это
даёт настоящее перекрытие — и CTranslate2, и torch отпускают GIL, — но пиковая
память складывается, потому что процесс один.

Замер на боевом сервере 18.08.2026, дорожка 15 минут, каждый прогон отдельным
процессом, пик по `ru_maxrss`:

    pyannote speaker-diarization-community-1     2,4 ГБ
    faster-whisper large-v3 (int8)               5,0 ГБ
    parakeet-tdt-0.6b-v3 кусками по минуте       1,2 ГБ

С whisper пара просит 7,4 ГБ. На сервере 11,6 ГБ, из которых заняты web,
postgres, LangFuse и сам воркер, и в журнале ядра шесть убийств по OOM с
anon-rss от 6,4 до 8,7 ГБ. Убитый воркер не выглядит нехваткой памяти: прогон
просто обрывается, а следующий на том же ролике обрывается снова, и объяснение
ищут в ролике.

─── Почему таблицей, а не расчётом ──────────────────────────────────────────
Расход модели не выводится из её размера: у whisper большая часть пика — не
веса, а буферы декодера (на дорожке 120 секунд уже 3,9 ГБ из 5,0). Считать его
формулой значит получить число, которое выглядит обоснованным и не совпадает с
действительностью. Таблица честнее: в ней видно, что каждое значение измерено, и
видно дату замера.
"""

from __future__ import annotations

from ..config import ONNX_MODELS

#: Пик расшифровки по движкам, мегабайты. Ключ — имя модели из каталога
#: настроек. Значения измерены, а не взяты из документации.
TRANSCRIBE_PEAK_MB: dict[str, int] = {
    "parakeet-tdt-0.6b-v3": 1200,
    "large-v3": 5100,
}

#: Пик диаризации. Одна модель на все прогоны, поэтому не таблица.
DIARIZE_PEAK_MB = 2500

#: Запас. Не «на всякий случай»: рядом с этими двумя в процессе живут ffmpeg,
#: буфер прочитанной дорожки и сам питон, а мерить пик каждого по отдельности
#: значит мерить то, что меняется от версии к версии.
HEADROOM_MB = 1024

#: Сколько считать за расход движка, которого нет в таблице. Заведомо больше
#: самого прожорливого: движок без замера обязан уходить в последовательную
#: ветку. Обратное умолчание проявляется убитым воркером в тот день, когда
#: движок добавили, — то есть тогда, когда его меньше всего подозревают.
UNKNOWN_PEAK_MB = max(TRANSCRIBE_PEAK_MB.values()) + 1


def peak_mb(model: str) -> int | None:
    """Замеренный пик расшифровки или None, если модель не мерили."""
    return TRANSCRIBE_PEAK_MB.get(model)


def available_mb() -> float:
    """
    Сколько памяти реально доступно.

    `MemAvailable`, а не `MemFree`: свободная память на работающем сервере почти
    всегда мала, потому что ядро держит в ней кэш страниц — и решение по
    `MemFree` уводило бы в последовательную ветку всегда.

    На не-Linux (разработка на macOS) вернётся 0, и вызывающий получит запрет на
    параллельность. Это верное умолчание: ошибиться в сторону медленного прогона
    можно, в сторону убитого воркера — нет.
    """
    try:
        with open("/proc/meminfo") as f:
            for line in f:
                if line.startswith("MemAvailable:"):
                    return float(line.split()[1]) / 1024
    except OSError:
        pass
    return 0.0


def can_run_together(model: str, available_mb: float | None = None) -> bool:
    """
    Можно ли расшифровывать и диаризовать одновременно.

    `available_mb` параметром, а не только чтением системы: иначе проверить это
    решение можно было бы только на машине нужного размера, то есть никогда.
    """
    free = available_mb if available_mb is not None else globals()["available_mb"]()
    need = TRANSCRIBE_PEAK_MB.get(model, UNKNOWN_PEAK_MB) + DIARIZE_PEAK_MB
    return free >= need + HEADROOM_MB


def engine_of(model: str) -> str:
    """Имя движка для сообщений. Не для выбора кода — тот идёт по ONNX_MODELS."""
    return "parakeet" if model in ONNX_MODELS else "whisper"
