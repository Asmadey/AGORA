"""
Транскрипт и диаризация (задача #15).

Три операции над звуковой дорожкой, которую подготовил agent_core.media:

  transcribe   — речь в текст с таймкодами (faster-whisper);
  vad_segments — участки, где вообще есть речь (VAD из того же faster-whisper);
  diarize      — кто говорит на каждом участке (pyannote.audio).

─── Почему VAD отдельной функцией, а не флагом транскрипции ───────────────
Он нужен дважды и в разных местах: чтобы не гонять Whisper по тишине и чтобы
сократить работу диаризации. Спрятанный внутрь transcribe, он был бы недоступен
второму потребителю, и тот считал бы речевые участки заново — другим способом,
с другими границами. Две несогласованные разметки одного файла дают таймкоды,
которые почти совпадают, и это хуже, чем явно разные.

─── Про сравнение диаризации ──────────────────────────────────────────────
Пункт cdd требует, чтобы диаризация по речевым участкам давала те же метки, что
и по полному треку. Имена кластеров произвольны (SPEAKER_00, SPEAKER_01 —
порядок зависит от внутренней сортировки), поэтому сравнивать надо разбиение, а
не строки: число говорящих и порядок их появления.
"""

