"""
Переспрос забракованных персон — задача из списка владельца, пункт 33.

─── Что было до этого ────────────────────────────────────────────────────────
Забракованный ответ ИСКЛЮЧАЛСЯ из агрегата и на этом всё: персона не
переспрашивалась, деньги за ответ были потрачены, а отчёт вставал на остатке.
Отчёт на остатке выглядит нормальным отчётом — NPS посчитан, доли посчитаны, —
и по нему принимают решение о материале. Golden-сет ловил это как «агрегат
посчитан по 3 ответам из 12», человек не ловил никак.

─── Почему порог, а не «переспрашивать всегда» ───────────────────────────────
Переспрос стоит денег: каждая попытка — вызов модели с полным пакетом
материала, помноженный на число забракованных персон. Единичная претензия
отчёту не угрожает: агрегат по одиннадцати ответам из двенадцати — это тот же
агрегат. Угрожает массовая, поэтому порог стоит там, где отчёт начинает
терять представительность.

─── Почему персона не видит текста претензии ─────────────────────────────────
Это главное решение модуля, и оно неочевидное.

Претензия судьи адресована ОТВЕТУ и содержит правильный ответ внутри себя: «в
вербатиме сказано, что герой скупал чипы, а в материале в этот момент речь об
отказе от DJI». Отдать такое персоне — значит подсказать. Вторая попытка
окажется лучше первой не потому, что персона подумала, а потому, что ей
продиктовали, и отчёт будет измерять качество подсказки.

Поэтому персона получает подсказку ПО ВИДУ претензии: что делать иначе, а не
что именно она напутала. Проверяется это буквально — тест сверяет, что ни одно
значимое слово претензии не доехало до промпта.
"""

from __future__ import annotations

from typing import Any

#: Сколько ответов разрешено переспросить за прогон.
#:
#: ─── Почему потолок, а не порог ────────────────────────────────────────────
#: Здесь стоял порог: переспрашивать, только если забраковано больше трети.
#: Он защищал бюджет не с той стороны. На прогоне № 0050 забраковали восемь
#: ответов из двадцати семи — 29,6 %, ниже порога, — и переспроса не было. То
#: есть механизм отказывал ровно там, где он дёшев: восемь вызовов.
#:
#: Владелец прочитал «забракованные персоны переспрашиваются» как «всегда», и
#: это была моя формулировка, а не его невнимательность.
#:
#: Опасна другая сторона: прогон, где забраковано почти всё. Там переспрос
#: удваивает стоимость и почти ничего не спасает — если материал или промпт
#: таковы, что модель врёт систематически, вторая попытка врёт так же.
#: Пятнадцать — верхняя граница того, что укладывается в гейт #22 по времени
#: прогона; значение настраивается арендатором, ноль означает «не
#: переспрашивать».
DEFAULT_CAP = 15

#: Сколько кругов переспроса. Один.
#:
#: Вторая отбраковка окончательна. Без дна цикл крутился бы, пока не кончатся
#: деньги, и каждый круг выглядел бы осмысленной работой: доля выживших растёт,
#: значит система «чинится».
MAX_ROUNDS = 1

#: Что делать иначе — по виду претензии, а не по её тексту.
#:
#: Формулировки процедурные: они говорят, КАК опираться на материал, и не
#: называют ни одной детали материала. Персона, прочитавшая такую подсказку, не
#: узнаёт из неё ни одного факта, которого не было в её пакете.
_HINTS = {
    "grounding": (
        "В прошлый раз твой ответ не удалось сверить с показанным. "
        "Опирайся только на то, что есть в пакете, и бери таймкод готовым из поля "
        "time той записи, о которой говоришь, — не составляй его сам и не "
        "пересказывай по памяти."
    ),
    "consistency": (
        "В прошлый раз твой ответ разошёлся сам с собой. Проверь перед отправкой, "
        "что баллы, доля просмотра и намерение досмотреть говорят об одном и том "
        "же, и что сказанное совпадает с твоим характером из профиля."
    ),
}


def hint_for(kinds: set[str]) -> str:
    """Подсказка по видам претензий. Пустая строка — подсказывать нечего."""
    parts = [_HINTS[k] for k in sorted(kinds) if k in _HINTS]
    return " ".join(parts)


def personas_to_ask(flagged: list[dict[str, Any]]) -> set[tuple[str, int]]:
    """Кого переспрашиваем: пары «персона, повтор»."""
    out: set[tuple[str, int]] = set()
    for verdict in flagged:
        pid = verdict.get("persona_id")
        # Вердикт diversity относится к выборке целиком и персоны не называет —
        # переспрашивать по нему некого, а разброс от повтора не вырастет.
        if not pid:
            continue
        out.add((str(pid), int(verdict.get("replication") or 0)))
    return out


def kinds_for(flagged: list[dict[str, Any]], persona: tuple[str, int]) -> set[str]:
    """Виды претензий к конкретному ответу."""
    return {
        str(v.get("kind") or "")
        for v in flagged
        if (str(v.get("persona_id") or ""), int(v.get("replication") or 0)) == persona
    } - {""}


def needs_requestion(
    answers: list[dict[str, Any]],
    flagged: list[dict[str, Any]],
    cap: int = DEFAULT_CAP,
) -> bool:
    """
    Стоит ли переспрашивать. Любая непустая отбраковка — повод.

    Пустой список ответов исключается отдельно: переспрашивать некого, а не
    «нечего». Разница видна в отчёте — во втором случае там появилась бы строка
    про переспрос на прогоне, где ответов не было вовсе.
    """
    if not answers or cap <= 0:
        return False
    return bool(personas_to_ask(flagged))


def limit_to_cap(
    targets: set[tuple[str, int]], cap: int = DEFAULT_CAP
) -> set[tuple[str, int]]:
    """
    Первые `cap` целей в устойчивом порядке.

    Именно сортировка, а не произвольная выборка из множества: два прогона на
    одних данных обязаны переспросить одних и тех же. Порядок обхода множества в
    Python зависит от хэшей, и расхождение двух отчётов на одном материале
    объяснить было бы нечем.
    """
    return set(sorted(targets)[: max(0, cap)])


def cap_exhausted(targets: set[tuple[str, int]], cap: int = DEFAULT_CAP) -> bool:
    """Осталась ли отбраковка, до которой переспрос не дошёл."""
    return len(targets) > max(0, cap)
