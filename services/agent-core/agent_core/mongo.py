"""
Единственная точка подключения воркера к MongoDB.

До этой задачи её не было: `frames/analyze.py` принимал готовую коллекцию
аргументом, а конструировать её было некому. Отдельный модуль нужен по той же
причине, по которой он есть в вебе (`apps/web/lib/server/mongo.ts`): строка
подключения и режим соединения должны быть описаны один раз, иначе второй
вызывающий заведёт свой клиент со своими настройками, и разойдутся они молча.

─── directConnection ─────────────────────────────────────────────────────────
Managed MongoDB (TimeWeb) не отдаёт наружу внутренние hostnames реплики
(192.168.x.x). Без `directConnection` драйвер пытается достучаться до них и
вешает запрос — выглядит это как медленная база, а не как ошибка конфигурации.
Параметр дописывается только если его нет в строке: на настоящей реплике
прямое соединение молча выключило бы обнаружение узлов и failover.

Логика повторяет `mongoUri()` в вебе дословно. Дублирование здесь неизбежно —
это два разных рантайма, — но поведение обязано совпадать, иначе воркер и веб
будут ходить в базу по-разному.
"""

from __future__ import annotations

import os
import re
from typing import Any

_CLIENT: Any = None
#: pid процесса, в котором создан _CLIENT. См. mongo_db() — это защита от fork.
_CLIENT_PID: int | None = None

_DIRECT_ALREADY_SET = re.compile(r"[?&]directConnection=", re.IGNORECASE)


def mongo_uri() -> str:
    url = os.environ.get("MONGODB_URL")
    if not url:
        from .config import ConfigError

        raise ConfigError(
            "MONGODB_URL не задан: отчёт сохранять некуда, и веб его не прочитает"
        )
    if _DIRECT_ALREADY_SET.search(url):
        return url
    if os.environ.get("MONGO_DIRECT_CONNECTION") == "0":
        return url
    return f"{url}{'&' if '?' in url else '?'}directConnection=true"


def mongo_db() -> Any:
    """
    База воркера. Клиент один на процесс: pymongo держит пул сам.

    Новый клиент на каждый вызов означал бы новый пул соединений на каждую
    задачу Celery — и упёрлись бы мы в лимит соединений managed-инстанса, а
    выглядело бы это как отказ базы под нагрузкой.

    ─── Почему клиент привязан к pid ─────────────────────────────────────────
    Celery работает пулом prefork: родитель форкает рабочие процессы. MongoClient
    через fork не переносится — у потомка остаются дескрипторы сокетов родителя
    и фоновые потоки мониторинга, которых после fork не существует. Проявляется
    это не исключением, а зависанием запроса до таймаута, то есть выглядит как
    медленная база.

    Сегодня клиент создаётся лениво и только из узла analytics, то есть уже в
    потомке, и проблемы нет. Но это свойство держится на том, что никто не
    позовёт mongo_db() при импорте модуля или из родителя — а такой вызов
    добавляется одной строкой и ничего не ломает заметно.

    Поэтому клиент помнит свой pid и пересоздаётся, если процесс сменился.
    Проверка стоит копейки (один вызов getpid) и снимает целый класс отказов,
    диагностируемых часами.
    """
    global _CLIENT, _CLIENT_PID
    pid = os.getpid()
    if _CLIENT is None or _CLIENT_PID != pid:
        from pymongo import MongoClient

        _CLIENT = MongoClient(mongo_uri())
        _CLIENT_PID = pid
    return _CLIENT[os.environ.get("MONGO_DB") or "agora"]
