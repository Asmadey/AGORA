def submit_in_context(pool: Any, fn: Any, /, *args: Any, **kwargs: Any) -> Any:
    """
    То же, что `pool.submit(fn, ...)`, но с контекстом вызывающего потока.

    ─── Зачем ────────────────────────────────────────────────────────────────
    Контекст OpenTelemetry — а значит и текущий спан — живёт в `contextvars`.
    `ThreadPoolExecutor` исполняет функцию в чужом потоке, где этих contextvars
    нет: родителя не находится, и SDK заводит НОВЫЙ корень трассы.

    В прогоне 0051 так получилось двадцать семь отдельных трасс `answer-survey`
    — без арендатора, без прогона, без родителя. Самое ценное, ради чего
    трассировка и ставилась (что ответила персона и за что её забраковал
    судья), оказалось не связано с прогоном ничем, кроме времени.

    ─── Почему копия, а не общий контекст ────────────────────────────────────
    `copy_context()` снимает снимок в потоке-отправителе, и он у каждой задачи
    свой. Общий контекст на пул означал бы, что установленное одной персоной
    видит соседняя, — а изоляция персон друг от друга здесь и есть смысл
    конструкции (см. докстринг `respondent/run.py`).

    Контекст снимается на КАЖДЫЙ вызов: `Context.run` нельзя войти повторно,
    пока он исполняется, а пачка отправляется целиком до первого `result()`.
    """
    import contextvars

    ctx = contextvars.copy_context()
    return pool.submit(ctx.run, functools.partial(fn, *args, **kwargs))


