"""
Метрика `values_grounding`: следует ли назначение ценностей таблице ВЦИОМ по возрасту.

─── Почему её не было ───────────────────────────────────────────────────────
`persona_grounding` называется «заземлением персоны», а сверяет возраст, гео,
пол и средние баллы. Ценности в ней не участвуют.

При этом `persona/enrich.py` утверждал обратное:

    #: Поля, которые модель не видит и не может изменить. Список не для красоты:
    #: по ним считается persona_grounding …
    GROUNDED_FIELDS = (…, "values_and_beliefs", …)

Для `values_and_beliefs` это неправда. Каждый, кто открывал файл, видел
«ценности заземлены» и шёл дальше — и три дефекта прожили из-за этой строки
месяцы: три ценности вместо пяти, одинаковый топ-2 у всех персон и значения из
топ-15 корпуса вместо канонического перечня.

─── Чем метрика НЕ является ─────────────────────────────────────────────────
Защитой. Защита приехала 16.09.2026 тестами `test_persona_values.py`, и они
блокируют слияние, чего метрика не делает (`required: false` — решение
владельца).

Метрика добавляет ровно две вещи, которых у тестов нет: ПОРЯДОК всех
семнадцати вместо двух крайностей (`test_частые_в_корпусе_остаются_частыми`
сравнивает «Крепкую семью» с «Коллективизмом» и молчит о пятнадцати между
ними) и ЧИСЛО, которое человек сравнит с прошлым прогоном.

─── Почему не сравниваются абсолютные доли ──────────────────────────────────
Прямое соответствие разорвано сознательно: пять ценностей на персону против
1.45 у реального респондента и сглаживание `+1`, дающее вес значениям с нулевой
поддержкой. Проверка вида `|gen − real| ≤ 0.10` краснела бы ВСЕГДА — то есть
стала бы шумом, который перестают читать.

Сравнивается порядок: ранговая корреляция Спирмена.
"""
from __future__ import annotations

from agent_core.persona.values_grounding import (
    COVERAGE_SAMPLE,
    MIN_RANK_CORRELATION,
    spearman,
    values_grounding,
)

# ─── Ранговая корреляция ────────────────────────────────────────────────────


def test_совпадающий_порядок_даёт_единицу():
    assert spearman([1, 2, 3, 4], [1, 2, 3, 4]) == 1.0


def test_обратный_порядок_даёт_минус_единицу():
    assert spearman([1, 2, 3, 4], [4, 3, 2, 1]) == -1.0


def test_связки_не_ломают_счёт():
    """Ценности с равной частотой — обычное дело: в корпусе их несколько пар."""
    r = spearman([1, 2, 2, 3], [1, 2, 2, 3])
    assert 0.99 <= r <= 1.0


def test_вырожденный_вход_не_делит_на_ноль():
    # Все частоты равны — разброса нет, корреляция неопределена. Ноль, а не NaN:
    # NaN просочился бы в отчёт и сравнился бы с порогом непредсказуемо.
    assert spearman([1, 1, 1], [5, 5, 5]) == 0.0


# ─── Сам замер ──────────────────────────────────────────────────────────────


def test_замер_возвращает_три_числа():
    m = values_grounding(size=200, seed=20260916)
    assert set(m) >= {
        "rank_correlation",
        "coverage",
        "max_share",
        "personas",
        "source",
        "expected_counts",
    }
    assert m["personas"] == 200


def test_ожидание_берется_из_таблицы_вциом_по_возрасту():
    m = values_grounding(size=200, seed=20260916)
    assert m["source"] == "values_by_age_vciom.json"
    assert m["expected_counts"]["Крепкая семья"] > m["expected_counts"]["Коллективизм"]


def test_порядок_следует_корпусу():
    m = values_grounding(size=200, seed=20260916)
    assert m["rank_correlation"] >= MIN_RANK_CORRELATION, m


def test_все_семнадцать_достижимы():
    """
    Пять ценностей не имели шанса выпасть до 16.09.2026: их не было в
    `VCIOM_TO_DNA`. Проверка на достаточной выборке это ловит.
    """
    m = values_grounding(size=COVERAGE_SAMPLE, seed=20260916)
    assert m["coverage"] == 17, m.get("missing")


def test_ни_одна_ценность_не_у_всех():
    """
    Прежде «Крепкая семья» и «Справедливость» стояли у 100 % персон: их брал
    жёсткий `values_pool[:2]`. Доля ровно 1.0 — не распределение, а константа.
    """
    m = values_grounding(size=200, seed=20260916)
    assert m["max_share"] < 1.0, m


def test_замер_воспроизводим():
    a = values_grounding(size=100, seed=7)
    b = values_grounding(size=100, seed=7)
    assert a == b


# ─── Порог ──────────────────────────────────────────────────────────────────


def test_порог_корреляции_осмыслен():
    # Ниже 0.5 корреляция перестаёт отличать «следует корпусу» от «случайно
    # совпало»; единица недостижима из-за сглаживания и выборки без повторов.
    assert 0.5 <= MIN_RANK_CORRELATION < 1.0


def test_выборка_для_покрытия_достаточна():
    """
    «Созидательный труд» имеет вес 0.44 % — на сотне персон он может не выпасть
    ни разу, и проверка покрытия краснела бы случайно. Выборка обязана быть
    настолько большой, чтобы отказ означал дефект, а не невезение.
    """
    assert COVERAGE_SAMPLE >= 400
