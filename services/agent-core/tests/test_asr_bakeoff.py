"""
Чем меряется качество расшифровки, когда эталона нет.

─── Зачем ────────────────────────────────────────────────────────────────────
Владелец второй раз спрашивает, что делать с GigaAM. Ответить по README нельзя:
там WER на чужих наборах, а у нас пятидесятиминутный фильм с музыкой, шумом и
несколькими голосами. Своего эталонного текста к нему нет и не будет — вручную
расшифровать пятьдесят минут дороже, чем весь этот разбор.

Эталон при этом и не нужен, чтобы поймать тот дефект, который уже случился.
Прогон 0051 дал 43 реплики на 3033 секунды: parakeet молчал там, где на дорожке
есть голос. Такое ловится сравнением с детектором речи — он уже работает в
конвейере узлом `detect_speech` и ничего не знает о словах.

Отсюда три величины, которые считаются без эталона и по которым модели можно
сравнить между собой:

* **покрытие** — какая доля речи, найденной VAD, попала хоть в какую-то реплику;
* **доля кириллицы** — parakeet на русском фильме выдавал «I come so she showed
  me», и это видно арифметикой, а не чтением;
* **плотность слов** — слов на минуту речи; схлопывание длинного куска в одну
  фразу роняет её вдвое.

Ни одна из трёх не заменяет WER. Все три ловят отказ, а не разницу в качестве:
модель, которая слышит всё и путает окончания, по ним неотличима от идеальной.
Это осознанная граница — и она названа здесь, чтобы результат замера не выдали
за измерение точности.
"""

from __future__ import annotations

from agent_core.asr.bakeoff import (
    coverage,
    cyrillic_share,
    overlap_seconds,
    speech_seconds,
    words_per_minute,
)


def test_speech_seconds_sums_the_detector():
    assert speech_seconds([(0.0, 10.0), (20.0, 25.0)]) == 15.0


def test_overlap_counts_each_second_once():
    """
    Две реплики на одном участке речи — это не двойное покрытие.

    Считать иначе значит поощрять модель, которая дублирует куски: у parakeet
    на стыках чанков это ровно тот случай.
    """
    speech = [(0.0, 10.0)]
    assert overlap_seconds([(0.0, 6.0), (4.0, 8.0)], speech) == 8.0


def test_overlap_ignores_words_outside_speech():
    """Реплика в тишине покрытием не считается — она галлюцинация, а не находка."""
    assert overlap_seconds([(50.0, 60.0)], [(0.0, 10.0)]) == 0.0


def test_coverage_of_run_0051_would_have_been_red():
    """
    Числа прогона 0051: речь по VAD 1800 с, расшифровано 1062 с. Проверка
    существует ради этого случая, поэтому он записан числами.
    """
    assert coverage([(0.0, 1062.0)], [(0.0, 1800.0)]) == 0.59


def test_coverage_without_speech_is_undefined_not_zero():
    """Немой ролик — законный случай, и ноль здесь означал бы отказ модели."""
    assert coverage([], []) is None


def test_cyrillic_share_catches_the_wrong_language():
    assert cyrillic_share("I come so she showed me") == 0.0
    assert cyrillic_share("Приветствую вас") == 1.0
    # Цифры и знаки не считаются ни за кого: «в 1917 году» — русская фраза.
    assert cyrillic_share("в 1917 году!") == 1.0


def test_cyrillic_share_of_silence_is_undefined():
    assert cyrillic_share("") is None


def test_words_per_minute_is_measured_against_speech_not_wall_clock():
    """
    Знаменатель — секунды речи, а не длина файла. Иначе фильм с получасом
    музыки выглядел бы вдвое хуже разговорного ролика при той же расшифровке.
    """
    assert words_per_minute("раз два три четыре", speech_sec=120.0) == 2.0


