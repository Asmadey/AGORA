"""
Планировщик кусков для GigaAM: ни одна секунда речи не должна пропасть.

─── Откуда взялась проверка ──────────────────────────────────────────────────
Первый замер GigaAM (20.08.2026) дал покрытие речи 62 % — и виноват был не
движок, а моя нарезка. Она выглядела так:

    if cur and end - cur[0] <= LIMIT:
        cur = (cur[0], end)
    else:
        chunks.append(cur)
        cur = (start, min(end, start + LIMIT))    # ← хвост длинного участка терялся

Участок речи длиннее потолка обрезался, а не делился: всё, что за потолком,
не попадало ни в один кусок и до модели не доезжало. Симптом — «модель молчит»,
причина — арифметика в планировщике.

Ровно этот же класс дефекта дал 59 % на прогоне 0051. Поэтому планировщик
проверяется отдельно от модели: он чистая функция, ему не нужны ни веса, ни
дорожка, и краснеть он обязан на машине без GPU и без интернета.

─── Что именно требуется ─────────────────────────────────────────────────────
Три свойства, и все три проверяются числами:

1. **Полнота.** Объединение кусков покрывает каждый участок речи целиком.
2. **Потолок.** Ни один кусок не длиннее того, что модель принимает за раз.
3. **Экономность.** Тишина между участками не оплачивается сверх необходимого:
   куски не сливаются через паузу длиннее порога.
"""

from __future__ import annotations

from agent_core.asr.bakeoff import coverage
from agent_core.asr.gigaam import CHUNK_LIMIT_SEC, plan_chunks


def test_short_neighbours_are_merged():
    """Двадцать участков по секунде — это не двадцать вызовов модели."""
    speech = [(float(i) * 2, float(i) * 2 + 1) for i in range(10)]
    chunks = plan_chunks(speech)
    assert len(chunks) < len(speech)


def test_no_chunk_exceeds_the_limit():
    speech = [(0.0, 600.0)]
    for start, end in plan_chunks(speech):
        assert end - start <= CHUNK_LIMIT_SEC + 1e-6


def test_a_long_span_is_split_not_truncated():
    """
    Тот самый дефект: участок длиннее потолка терял хвост.

    Проверяется покрытием, а не числом кусков: важно, что до модели доедет вся
    речь, а не то, на сколько частей она поделена.
    """
    speech = [(0.0, 600.0)]
    assert coverage(plan_chunks(speech), speech) == 1.0


def test_every_span_is_covered_completely():
    speech = [(0.0, 12.0), (13.5, 61.0), (200.0, 203.0), (203.4, 260.0)]
    assert coverage(plan_chunks(speech), speech) == 1.0


def test_a_long_silence_is_not_paid_for():
    """
    Участки по разные стороны минутной паузы не сливаются в один кусок.

    Иначе модель получает минуту тишины внутри куска: это и оплаченное время, и
    приглашение галлюцинировать на пустом месте.
    """
    speech = [(0.0, 2.0), (120.0, 122.0)]
    chunks = plan_chunks(speech)
    assert chunks == [(0.0, 2.0), (120.0, 122.0)], (
        "участки слились через паузу — в модель уедет тишина"
    )


def test_empty_speech_gives_no_chunks():
    """Немой ролик — законный случай, и куска «на всякий случай» тут быть не должно."""
    assert plan_chunks([]) == []


def test_chunks_go_in_order_and_do_not_overlap():
    """
    Порядок и отсутствие наложений — условие того, что таймкоды монотонны.

    Наложение дало бы одну и ту же реплику дважды с разным временем, и ссылка
    персоны на момент перестала бы проверяться.
    """
    speech = [(0.0, 45.0), (46.0, 300.0)]
    chunks = plan_chunks(speech)
    for (a_start, a_end), (b_start, _) in zip(chunks, chunks[1:], strict=False):
        assert a_start < a_end <= b_start
