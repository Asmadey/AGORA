"""
Список моделей транскрипции совпадает с тем, что лежит в образе.

─── Как это нашлось ──────────────────────────────────────────────────────────
Настройки предлагали `large-v3` и `large-v3-turbo`, а в кэше воркера лежит одна:
`models--Systran--faster-whisper-large-v3`. Выбор второй уводил прогон качать
полтора гигабайта весов ПОСРЕДИ работы — уже после того, как ролик залит и
оплачен разбор.

Проявляется это не как «модель не найдена», а как необъяснимо долгая
транскрипция в первый раз и нормальная во второй. Худший вид дефекта: он чинит
сам себя после первого попадания и потому не воспроизводится, когда за него
берутся.

─── Почему список один на два языка ──────────────────────────────────────────
Перечень живёт в двух местах — `agent_core/config.py` и `apps/web/lib/settings.ts`
— и разъехаться они могут независимо. Здесь сверяются оба и оба сверяются с
образом: не «список непустой», а «предлагаем ровно то, что можем выполнить».
"""

from __future__ import annotations

import re
from pathlib import Path

from agent_core.config import WHISPER_MODELS

REPO = Path(__file__).resolve().parents[3]
SETTINGS_TS = REPO / "apps" / "web" / "lib" / "settings.ts"

#: Что действительно предзагружено в образ воркера.
#:
#: Порядок значим: первый элемент — значение по умолчанию. GigaAM стоит первым
#: по замеру 20.08.2026 на пяти минутах диалога из прогона 0051: 64,8 слов на
#: минуту речи против 40,3 у parakeet, 21 секунда против 67, 1694 МБ против
#: 3285 (docs/ASR_BAKEOFF_2026-08-20.md).
#:
#: Веса whisper лежат в кэше HuggingFace на томе, веса GigaAM — в /opt/models/gigaam
#: внутри образа. Добавлять сюда строку можно только вместе с доливкой весов:
#: модель, которой в образе нет, уводит прогон качать её посреди работы, и
#: выглядит это случайно долгой транскрипцией, а не нехваткой модели.
IN_IMAGE = ("gigaam-v3-e2e-rnnt", "large-v3")


def test_worker_offers_only_what_the_image_has():
    assert tuple(WHISPER_MODELS) == IN_IMAGE, (
        "воркер принимает модель, которой нет в образе: прогон уйдёт качать веса "
        "посреди работы, и выглядеть это будет как случайное замедление"
    )


def test_web_offers_the_same_list():
    src = SETTINGS_TS.read_text("utf-8")
    match = re.search(r"WHISPER_MODELS\s*=\s*\[([^\]]*)\]", src)
    assert match, "в apps/web/lib/settings.ts не найден WHISPER_MODELS"

    offered = tuple(re.findall(r'"([^"]+)"', match.group(1)))
    assert offered == IN_IMAGE, (
        f"интерфейс предлагает {offered}, а в образе {IN_IMAGE}: выбор лишней "
        f"модели уводит прогон качать веса уже после заливки ролика"
    )


# ─── Третий список: ограничение в схеме ──────────────────────────────────────
#
# Тест выше сверял два перечня — питоновский и веб-овский — и был зелёным, пока
# сохранение настроек отвечало «внутренняя ошибка». Список моделей лежит ещё и
# третьим местом: `CHECK (whisper_model IN (…))` в таблице `settings`. Он остался
# от whisper и parakeet не знает, поэтому запись падает на 23514, а роут отдаёт
# пятисотку — то есть выбор в интерфейсе есть, а сохранить его нельзя.
#
# Проверяется ПОСЛЕДНЕЕ определение по номеру миграции: ограничение можно только
# пересоздать следующим файлом (CLAUDE.md §5), и смотреть на исходное значит
# читать состояние, которого в базе уже нет.
INIT = REPO / "infra" / "postgres" / "init"

_CHECK = re.compile(
    r"whisper_model\s+IN\s*\(([^)]*)\)", re.IGNORECASE | re.DOTALL
)


#: Строчный комментарий SQL. Снимается перед разбором: первая же версия теста
#: нашла ограничение внутри комментария, где процитирована ПРЕДЫДУЩАЯ редакция,
#: и объявила миграцию несделанной. Парсер, читающий комментарии как код, врёт
#: тем убедительнее, чем подробнее написана миграция.
_COMMENT = re.compile(r"--[^\n]*")


def _effective_check() -> tuple[str, ...]:
    """Список моделей из самой поздней миграции, которая его задаёт."""
    for path in sorted(INIT.glob("*.sql"), reverse=True):
        match = _CHECK.search(_COMMENT.sub("", path.read_text("utf-8")))
        if match:
            return tuple(re.findall(r"'([^']+)'", match.group(1)))
    raise AssertionError("ограничение whisper_model не найдено ни в одной миграции")


def test_schema_accepts_every_offered_model():
    allowed = _effective_check()
    missing = [m for m in IN_IMAGE if m not in allowed]
    assert not missing, (
        f"схема не принимает {missing}: интерфейс предлагает модель, а запись "
        f"настроек падает на CHECK и отдаёт «внутреннюю ошибку». Ограничение "
        f"пересоздаётся следующей миграцией, старая не редактируется"
    )


# ─── Четвёртый список: запасное умолчание в compose ──────────────────────────
#
# `WHISPER_MODEL` в окружении воркера действует для задач БЕЗ снимка настроек —
# тех, что поставлены до появления настроек. На сервере оно осталось `large-v3`
# после того, как каталог переехал на GigaAM, и `_asr` с пустым снимком уходил в
# whisper.
#
# Само по себе это не отказ: прогон идёт, текст появляется. Отличить его от
# правильного можно только по расшифровке — то есть никак, если не знать
# заранее, что искать. Ровно так же выглядел дефект, из-за которого turbo,
# выбранный в интерфейсе, считался моделью large-v3.

COMPOSE = REPO / "infra" / "docker-compose.yml"


def test_compose_fallback_matches_the_default_model():
    src = COMPOSE.read_text("utf-8")
    match = re.search(r"WHISPER_MODEL:\s*\$\{WHISPER_MODEL:-([^}]+)\}", src)
    assert match, "в infra/docker-compose.yml не найдено умолчание WHISPER_MODEL"

    assert match.group(1) == WHISPER_MODELS[0], (
        f"запасное умолчание {match.group(1)!r} не совпадает с моделью по "
        f"умолчанию {WHISPER_MODELS[0]!r}: задача без снимка настроек пойдёт "
        f"другой моделью, чем показывает интерфейс"
    )
