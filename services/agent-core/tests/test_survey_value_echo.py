"""
Персона не должна видеть свой список ценностей, отвечая на вопрос о ценностях.

─── Замер, с которого всё началось ──────────────────────────────────────────
Прогон 0093, вопрос 8 анкеты заказчика («какие ценности стремились донести
создатели»): «Крепкая семья» — 100 %, все 19 персон. При этом на экране ролика
нет ни семьи, ни детей, ни дома: женщина в машине, люди в камуфляже, поцелуй
через окно. «Служение Отечеству» — люди в форме занимают весь ролик — набрало
21 %. Ответ перевёрнут относительно материала.

Замер эха: из 45 названных ценностей 40 — СОБСТВЕННЫЕ ценности персоны.
89 % при случайном уровне 29 % (пять своих из семнадцати вариантов).

─── Почему так выходило ─────────────────────────────────────────────────────
Персона видела свой список ценностей дважды, и оба раза в том же окне, где её
просят назвать ценности материала:

1. `{{persona_dna}}` — вся DNA целиком, включая `values_and_beliefs.
   important_values`;
2. портрет — 17 из 20 портретов набора 170c318c перечисляют ценности персоны
   прозой («…где на первом месте стоят крепкая семья, справедливость и служение
   Отечеству»). Портрет лежит в DNA и, кроме того, подставлялся отдельно в
   `{{verbatim_examples}}`.

А системный промпт прямо велит: «Твои оценки и эмоции должны следовать из
ТВОЕГО профиля: ценностей…». Варианты ответа на вопрос 8 — тот же список
семнадцати ценностей Указа 809, из которого персону и собирали. Совпадение было
гарантировано конструкцией.

Решение владельца 18.09.2026: убрать из контекста опроса всё, что называет
персоне её ценности, а `{{verbatim_examples}}` заполнить тем, что там и обещано
промптом — настоящими репликами корпуса. Сейчас под заголовком «Так ты обычно
говоришь и рассуждаешь (образцы живой речи людей твоего типа)» подставляется
биография от третьего лица, то есть плейсхолдер и так заполнен не тем.

Ценности персоны никуда не деваются: они остаются в DNA, в реестре аудитории и
в подборе к корпусу. Их перестают показывать ей во время опроса.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from agent_core.respondent.run import build_slice  # noqa: E402

PERSONA = {
    "id": "p1",
    "name": "Наталья",
    "dna": {
        "demographics": {"age": 41, "gender": "жен", "city": "Санкт-Петербург",
                         "age_group": "35-44", "geo": "столицы"},
        "values_and_beliefs": {
            "important_values": ["Крепкая семья", "Справедливость", "Патриотизм"],
            "worldview": "консервативная",
            "political_orientation": "умеренно-консервативный",
            "religious_attitude": "атеист",
        },
        "communication_style": {"directness": "окольный"},
        "big_five": {"openness": 4},
        "lifestyle_and_interests": {"hobbies": ["рукоделие"], "work_status": "работает"},
        "narrative": (
            "Анна, 41-летняя жительница Санкт-Петербурга, ставит на первое место "
            "крепкую семью и справедливость, а материальное — на второе."
        ),
        "seed": 1,
    },
}

SYSTEM = (
    "# Кто ты\n{{persona_dna}}\n\nСегмент: {{segment}}\n\n"
    "Так ты обычно говоришь:\n{{verbatim_examples}}\n\nОриентиры: {{score_priors}}\n"
)
USER = "Ты посмотрел(а) «{{content_title}}».\n{{video_understanding}}\n{{survey_questions}}\n"

PACK = {"title": "ролик", "timeline": []}
SURVEY = {"questions": [{"id": "q08-values", "number": 8, "type": "multi_choice",
                         "label": "Какие ценности донесли создатели?",
                         "options": [{"id": "v-8", "label": "Крепкая семья"}]}]}

VERBATIMS = [
    "Я вообще такое не смотрю, если честно.",
    "Ну вот тут прям зацепило, да.",
]


def _slice(**kwargs) -> tuple[str, str]:
    return build_slice(
        PERSONA, PACK, SURVEY,
        system_template=SYSTEM, user_template=USER, **kwargs,
    )


def test_own_values_are_not_shown_to_the_persona() -> None:
    system, _ = _slice(verbatims=VERBATIMS)
    assert "important_values" not in system, (
        "список ценностей персоны в окне вопроса о ценностях — это и есть эхо 89 %"
    )
    assert "Крепкая семья" not in system


def test_portrait_does_not_smuggle_the_values_back() -> None:
    """
    Портрет — второй канал того же эха и потому тоже уходит из опроса.

    17 из 20 портретов набора перечисляют ценности персоны прозой. Убрать
    `important_values`, оставив портрет, значило бы закрыть меньший из двух
    каналов и решить, что готово.
    """
    system, _ = _slice(verbatims=VERBATIMS)
    assert "Справедливость" not in system
    assert "Анна" not in system, (
        "заодно уходит чужое имя: портрет персоны «Наталья» звал её Анной"
    )


def test_persona_keeps_everything_that_is_not_a_value_list() -> None:
    """Персона остаётся собой: демография, характер, мировоззрение на месте."""
    system, _ = _slice(verbatims=VERBATIMS)
    for kept in ("Санкт-Петербург", "окольный", "консервативная", "рукоделие"):
        assert kept in system, f"из промпта пропало то, что должно было остаться: {kept}"


def test_verbatims_fill_the_placeholder_meant_for_them() -> None:
    system, _ = _slice(verbatims=VERBATIMS)
    for line in VERBATIMS:
        assert line in system
    assert "{{verbatim_examples}}" not in system


def test_without_verbatims_the_section_is_not_faked() -> None:
    """
    Пула нет — подставлять биографию обратно нельзя.

    Именно так плейсхолдер и был заполнен не тем: под заголовком «образцы живой
    речи» стояло описание человека от третьего лица.
    """
    system, _ = _slice()
    assert "Анна" not in system
    assert "Крепкая семья" not in system
