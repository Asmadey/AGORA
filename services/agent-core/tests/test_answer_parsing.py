"""
Разбор ответа персоны по типу вопроса — в одном месте и с проверкой.

─── Почему форма ответа осталась прежней ────────────────────────────────────
План этапа 1 предполагал новую структуру `{question_id, option_ids[], value,
text}`. Замер 17.09.2026 показал, что она не нужна: модель уже возвращает
карту «поле → ответ» с правильными идентификаторами вариантов —

    {"q01-plot": 5, "q07-emotions": "e-3, e-7, e-5", "t1-1": "m-1", ...}

— и `respondent/run.py` (`_answers_to_map`) приводит к ней обе законные формы.
Порядок в мультивыборе сохраняется строкой через запятую, а он значим: в
выгрузке заказчика каждый выбранный вариант занимает свою колонку по порядку.

Менять то, что работает, ради красоты контракта — это лишняя правка промпта,
лишний риск и лишний прогон. Поэтому добавляется РАЗБОР этой карты, а не новая
её форма.

─── Что здесь проверяется ───────────────────────────────────────────────────
Что «5» и 5 — один балл; что «e-3, e-7» — два идентификатора в порядке
называния; что чужой идентификатор, превышение потолка и служебный вариант
рядом с содержательным названы поимённо, а не молча проглочены.

Проглатывание здесь опаснее отказа: неразобранный вариант не попадёт ни в одну
долю, доли сойдутся к 100 % по оставшимся, и на графике это будет выглядеть
как мнение аудитории.
"""
from __future__ import annotations

import json
import pathlib

from agent_core.survey import parse_field_answer

REPO = pathlib.Path(__file__).resolve().parents[3]
SURVEY = json.loads((REPO / "data" / "survey" / "customer_2026.json").read_text("utf-8"))


def _q(number: int) -> dict:
    return [q for q in SURVEY["questions"] if q["number"] == number][0]


# ─── Шкала ───────────────────────────────────────────────────────────────────


def test_балл_приходит_числом_и_строкой_одинаково():
    scale = _q(1)
    assert parse_field_answer(scale, 5).value == 5
    assert parse_field_answer(scale, "5").value == 5
    assert parse_field_answer(scale, " 5 ").value == 5


def test_балл_вне_шкалы_назван_ошибкой():
    scale = _q(1)
    out = parse_field_answer(scale, 15)
    assert out.value is None
    assert "шкал" in out.error


def test_ноль_законный_балл():
    """Шкала заказчика 0–10. Ноль — настоящая оценка, а не «не ответил»."""
    out = parse_field_answer(_q(1), 0)
    assert out.value == 0
    assert not out.error


# ─── Выбор нескольких ────────────────────────────────────────────────────────


def test_мультивыбор_разбирается_в_порядке_называния():
    out = parse_field_answer(_q(7), "e-3, e-7, e-5")
    assert out.option_ids == ["e-3", "e-7", "e-5"], "порядок значим: он едет в колонки выгрузки"
    assert not out.error


def test_мультивыбор_принимает_список():
    out = parse_field_answer(_q(7), ["e-1", "e-2"])
    assert out.option_ids == ["e-1", "e-2"]


def test_чужой_идентификатор_назван_поимённо():
    out = parse_field_answer(_q(7), "e-3, e-99")
    assert "e-99" in out.error
    assert out.option_ids == ["e-3"], "разобранное сохраняется, непонятое называется"


def test_превышение_потолка_названо():
    out = parse_field_answer(_q(7), "e-1, e-2, e-3, e-4")
    assert "не более 3" in out.error or "потолок" in out.error


def test_служебный_вариант_рядом_с_содержательным_назван():
    """
    «Не испытал никаких эмоций» вместе с «Гордостью» — противоречие. Молча
    посчитать оба значило бы прибавить единицу и к эмоции, и к «эмоций не было».
    """
    out = parse_field_answer(_q(7), "e-3, e-s1")
    assert "одиночку" in out.error or "сам по себе" in out.error


def test_служебный_вариант_в_одиночку_законен():
    out = parse_field_answer(_q(7), "e-s1")
    assert out.option_ids == ["e-s1"]
    assert not out.error


# ─── Выбор одного и матрица ──────────────────────────────────────────────────


def test_одиночный_выбор_берёт_один_идентификатор():
    out = parse_field_answer(_q(10), "i-1")
    assert out.option_ids == ["i-1"]
    assert not out.error


def test_два_ответа_на_одиночный_вопрос_названы():
    out = parse_field_answer(_q(10), "i-1, i-2")
    assert out.error


def test_строка_матрицы_разбирается_по_вариантам_вопроса():
    """У матрицы варианты общие на все строки, а ответ даётся по строке."""
    out = parse_field_answer(_q(9), "m-2")
    assert out.option_ids == ["m-2"]
    assert not out.error


def test_подпись_варианта_вместо_идентификатора_принимается():
    """
    Модель иногда называет вариант словами. Отвергать такой ответ значило бы
    терять оплаченный ответ из-за формы; подпись однозначна, и сопоставить её
    можно здесь — один раз, а не в четырёх местах ниже по течению.
    """
    out = parse_field_answer(_q(10), "Скорее важные")
    assert out.option_ids == ["i-1"]
    assert not out.error


# ─── Открытый ────────────────────────────────────────────────────────────────


def test_открытый_ответ_остаётся_текстом():
    q = {"id": "c-1", "label": "Что запомнилось", "type": "open"}
    out = parse_field_answer(q, "  финальная сцена  ")
    assert out.text == "финальная сцена"
    assert not out.error


def test_пустой_ответ_это_пропуск_а_не_ошибка_формы():
    out = parse_field_answer(_q(1), None)
    assert out.missing is True
    assert out.value is None


# ─── Подпись, в которой есть запятая ─────────────────────────────────────────
#
# Шесть из тринадцати эмоций анкеты заказчика названы парой через запятую:
# «Восхищение, восторг», «Тревога, страх». Промпт при этом велит перечислять
# выбранное через запятую — то есть разделитель ответа совпадает с символом
# внутри подписи варианта.
#
# Наивное разбиение по запятой такой ответ теряет целиком и называет обе
# половины «вариантами не из списка». Персона выполнила инструкцию буквально, а
# ответ выброшен — ровно тот случай, ради которого подпись вообще принимается
# наравне с идентификатором.


def test_подпись_с_запятой_не_разрезается_разделителем():
    out = parse_field_answer(_q(7), "Восхищение, восторг")
    assert out.option_ids == ["e-1"], "парная подпись — один вариант, а не две ошибки"
    assert not out.error


def test_парная_подпись_рядом_с_одиночной():
    out = parse_field_answer(_q(7), "Восхищение, восторг, Гордость")
    assert out.option_ids == ["e-1", "e-3"]
    assert not out.error


def test_одиночные_подписи_через_запятую_остаются_разными_вариантами():
    """
    Обратная сторона: жадность не должна склеивать то, что склеивать нельзя.
    «Гордость, Надежда» — два варианта, и такой пары в списке нет.
    """
    out = parse_field_answer(_q(7), "Гордость, Надежда")
    assert out.option_ids == ["e-3", "e-5"]
    assert not out.error


def test_чужая_подпись_с_запятой_всё_ещё_ошибка():
    out = parse_field_answer(_q(7), "Восхищение, восторг, Умиление, нежность")
    assert "e-1" in out.option_ids
    assert out.error, "выдуманный вариант обязан быть назван, а не проглочен"


# ─── Вложенная матрица ───────────────────────────────────────────────────────
#
# Замер 17.09.2026, двадцать персон без грамматики: ТРИНАДЦАТЬ ответили на
# матрицу вложенным объектом —
#
#     "q09-themes": {"t1-1": "m-1", "t1-2": "m-2", ...}
#
# — вместо сорока трёх полей рядом. Промпт такой формы не запрещает: он просит
# «ответь по каждой строке», а как их сгруппировать, не говорит.
#
# Читатель знал только плоскую форму, и все сорок три ответа считались
# пропусками. Замер показывал «закрыто 31.9 поля из 67» — и это было
# ЧЕТВЁРТОЕ подряд число, оказавшееся дефектом чтения, а не свойством модели.
#
# Цена прямая: правило покрытия забраковало бы такие ответы, они выбыли бы из
# агрегата по правилу, и отчёт встал бы на семи персонах из двадцати.


def test_вложенная_матрица_разворачивается_в_поля():
    from agent_core.respondent.run import _answers_to_map

    out = _answers_to_map({
        "q01-plot": 8,
        "q09-themes": {"t1-1": "m-1", "t1-2": "m-2"},
    })
    assert out["t1-1"] == "m-1"
    assert out["t1-2"] == "m-2"
    assert out["q01-plot"] == 8


def test_вложенная_матрица_в_списке_пар():
    """Обе законные формы верхнего уровня несут одну и ту же вложенность."""
    from agent_core.respondent.run import _answers_to_map

    out = _answers_to_map([
        {"question": "q09-themes", "answer": {"t1-1": "m-1"}},
    ])
    assert out["t1-1"] == "m-1"


def test_плоская_форма_не_ломается():
    from agent_core.respondent.run import _answers_to_map

    out = _answers_to_map({"t1-1": "m-1", "q01-plot": 8})
    assert out == {"t1-1": "m-1", "q01-plot": 8}
