"""
Сцены строятся по склейкам, а описание получает свои начало и конец.

─── Дефект, ради которого это переписывается ────────────────────────────────
Было так: `keyframe_timestamps` брал середину каждой сцены, кадры собирались в
панель 2×2 по четыре подряд, панель уходила в модель ОДНОЙ картинкой, модель
возвращала ОДНО описание, а `_stamp` ставил ему таймкод ПЕРВОГО кадра панели.
Времена остальных трёх терялись.

На ролике 2:42 это дало 6 описаний вместо двух десятков: сцены, разнесённые на
полминуты, слились в одно описание с одним временем. Персона, сославшаяся на
момент внутри панели, получала описание от её начала — и судья справедливо
видел несовпадение, прямо это называя: «в таймкоде 0:00-0:25 (согласно
таймлайну это 0:00-2:00)». Отсюда 40–60% отбраковок по grounding и непроходимый
golden-сет.

─── Что теперь ──────────────────────────────────────────────────────────────
Один вызов — одна сцена — один интервал времени. Панель из четырёх кадров
остаётся, но кадры берутся ВНУТРИ одной сцены: модель по-прежнему видит
движение (поле `actions` без этого вырождается в «стоит»), а описание относится
к отрезку, границы которого известны нам, а не модели.

Сетку задаёт монтаж, а не таймер:

· склейки ищет детектор (порог 0.3 по содержимому кадра);
· склейка ближе 2 секунд к предыдущей границе — не граница, а дребезг:
  кусочек приклеивается к предыдущей сцене;
· сцена длиннее 30 секунд режется на РАВНЫЕ блоки: говорящая голова на одном
  слайде три минуты иначе стала бы одним описанием на три минуты — то есть
  ровно тем дефектом, от которого уходим.

Рассинхрон при такой схеме невозможен структурно, а не по договорённости: у
описания нет способа получить чужое время, потому что время у него своё.
"""

from __future__ import annotations

import pytest

from agent_core.frames.scenes import (
    MAX_SCENE_SEC,
    MIN_SCENE_SEC,
    Scene,
    build_scenes,
    sample_times,
)


def _spans(scenes: list[Scene]) -> list[tuple[float, float]]:
    return [(round(s.start_sec, 3), round(s.end_sec, 3)) for s in scenes]


# ─── Покрытие без дыр ────────────────────────────────────────────────────────


def test_scenes_cover_the_whole_video():
    """
    Сцены идут встык от нуля до конца: ни дыр, ни перекрытий.

    Дыра — это кусок ролика, которого нет ни в одном описании: персона его не
    видела, а отчёт об этом не сообщает. Перекрытие — момент, у которого два
    разных описания, и какое из них покажет экран, зависит от порядка.
    """
    scenes = build_scenes(cuts=[7.0, 19.0, 41.0], duration_sec=60.0)

    assert scenes[0].start_sec == 0.0
    assert scenes[-1].end_sec == pytest.approx(60.0)
    for previous, following in zip(scenes, scenes[1:], strict=False):
        assert following.start_sec == pytest.approx(previous.end_sec), _spans(scenes)


# ─── Дребезг ─────────────────────────────────────────────────────────────────


def test_cut_closer_than_min_glues_to_the_previous_scene():
    """
    Склейка через полсекунды после предыдущей — не сцена.

    Быстрый монтаж даёт десятки границ подряд. Каждая из них стала бы отдельным
    вызовом модели за описание, которое читается как «то же самое, но на полкадра
    позже».
    """
    scenes = build_scenes(cuts=[10.0, 10.4, 10.9, 30.0], duration_sec=45.0)

    assert _spans(scenes) == [(0.0, 10.0), (10.0, 30.0), (30.0, 45.0)]
    assert all(s.duration_sec >= MIN_SCENE_SEC for s in scenes), _spans(scenes)


def test_short_tail_glues_to_the_previous_scene():
    """
    Полсекунды в хвосте не становятся сценой.

    Иначе последним, что видит персона, оказывается отдельное описание одного
    кадра, а анкета спрашивает именно про финал: «досмотрели бы до конца».
    """
    scenes = build_scenes(cuts=[20.0], duration_sec=20.4)

    assert _spans(scenes) == [(0.0, 20.4)]


def test_video_shorter_than_the_minimum_is_still_one_scene():
    """Полуторасекундный ролик — законный вход, а не повод для пустого списка."""
    scenes = build_scenes(cuts=[], duration_sec=1.5)

    assert _spans(scenes) == [(0.0, 1.5)]


# ─── Длинная сцена ───────────────────────────────────────────────────────────


def test_long_scene_is_split_into_equal_blocks():
    """
    Три минуты одного слайда — не одно описание.

    Блоки равные, а не «тридцать, тридцать, остаток»: хвост в две секунды
    получил бы собственное описание наравне с полноценным куском, и на таймлайне
    это выглядело бы как событие там, где ничего не произошло.
    """
    scenes = build_scenes(cuts=[], duration_sec=100.0)

    assert len(scenes) == 4, _spans(scenes)
    assert _spans(scenes) == [(0.0, 25.0), (25.0, 50.0), (50.0, 75.0), (75.0, 100.0)]
    assert all(s.duration_sec <= MAX_SCENE_SEC for s in scenes)


def test_split_blocks_are_not_marked_as_cuts():
    """
    Граница от монтажа и граница от нарезки — разные вещи.

    По первой на таймлайне рисуется смена сцены, по второй — продолжение той же.
    Смешать их значит показать в отчёте монтаж, которого в материале нет.
    """
    scenes = build_scenes(cuts=[40.0], duration_sec=80.0)

    assert [s.is_cut for s in scenes] == [True, False, True, False], _spans(scenes)
    # Первая сцена начинается в нуле — это не склейка, но и не продолжение:
    # начало материала считается границей, иначе таймлайн начинается «внутри».
    assert scenes[0].start_sec == 0.0


def test_scene_index_is_its_place_in_the_result():
    """Индекс — место в итоговом списке, а не в списке границ до склейки коротких."""
    scenes = build_scenes(cuts=[3.0, 3.5, 20.0], duration_sec=40.0)

    assert [s.index for s in scenes] == list(range(len(scenes)))


# ─── Кадры берутся внутри сцены ──────────────────────────────────────────────


def test_frames_are_sampled_inside_the_scene_not_at_its_edges():
    """
    Первый кадр сцены часто застаёт незавершённый переход — затемнение, шторку,
    полукадр наплыва. Последний — начало следующего перехода. Поэтому выборка
    идёт по серединам равных долей, а не по границам.
    """
    times = sample_times(Scene(index=0, start_sec=10.0, end_sec=30.0, is_cut=True), count=4)

    assert times == [12.5, 17.5, 22.5, 27.5]
    assert times[0] > 10.0 and times[-1] < 30.0


def test_sampling_a_two_second_scene_still_gives_four_distinct_moments():
    """
    Минимальная сцена — две секунды. Четыре кадра в ней обязаны различаться по
    времени, иначе панель показывает модели одно и то же четырежды.
    """
    times = sample_times(Scene(index=0, start_sec=0.0, end_sec=2.0, is_cut=True), count=4)

    assert len(set(times)) == 4, times
    assert all(0.0 < t < 2.0 for t in times)
