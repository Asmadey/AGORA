"""
Закрытый вопрос доезжает до персоны вместе со своими вариантами.

─── Почему это отдельная проверка ───────────────────────────────────────────
До сих пор анкета рендерилась строкой `- [id] (тип) формулировка`, и этого
хватало: все типы были либо шкалой, либо свободным текстом. У анкеты заказчика
девять вопросов из пятнадцати — выбор из закрытого списка, и список обязан
оказаться в промпте. Вопрос «какие эмоции вы испытали» без тринадцати вариантов
— это открытый вопрос, и ответ на него в закрытую диаграмму не ложится.

Дефект такого рода не виден ни в одном логе: прогон проходит целиком, стоит
полную цену и возвращает правдоподобные эмоции, которых нет в списке
заказчика. Ровно так уже случилось с `verbatim_pool`, который судья получал
пустым, и с `question_label`, который воркер читал из несуществующего поля.

─── Что проверяется ─────────────────────────────────────────────────────────
Не формат строки, а наличие содержимого: каждая подпись варианта, каждая
строка матрицы, объявленный потолок выбора и правило одиночного выбора для
служебных вариантов. Формат меняется, содержимое — нет.

Счётчик полей проверяется отдельно, потому что от него зависит решение о
разбиении опроса: при всех десяти темах персона отвечает примерно на семь
десятков полей в одном вызове, и это главный измеряемый риск этапа 0.
"""
from __future__ import annotations

import json
import pathlib

from agent_core.survey import answerable_fields, render_questions

REPO = pathlib.Path(__file__).resolve().parents[3]
SURVEY = json.loads((REPO / "data" / "survey" / "customer_2026.json").read_text("utf-8"))


def _all_themes() -> list[dict]:
    """Анкета при максимуме: выбраны все десять тем вопроса 9."""
    return SURVEY["questions"]


def _q(number: int) -> dict:
    return [q for q in SURVEY["questions"] if q["number"] == number][0]


def test_каждый_вариант_закрытого_вопроса_попадает_в_промпт():
    text = render_questions(_all_themes())
    for q in SURVEY["questions"]:
        for option in q.get("options", []):
            assert option["label"] in text, (
                f"вопрос №{q['number']}: вариант {option['label']!r} не доехал до промпта"
            )


def test_каждая_строка_матрицы_попадает_в_промпт():
    text = render_questions(_all_themes())
    for q in SURVEY["questions"]:
        for row in q.get("rows", []):
            assert row["label"] in text, (
                f"вопрос №{q['number']}: строка {row['label']!r} не доехала до промпта"
            )


def test_названия_тем_попадают_в_промпт():
    """Матрица из сорока трёх строк без заголовков тем читается как свалка."""
    text = render_questions(_all_themes())
    for theme in _q(9)["themes"]:
        assert theme["label"] in text, f"тема {theme['label']!r} не доехала до промпта"


def test_потолок_выбора_назван_в_промпте():
    text = render_questions(_all_themes())
    assert "не более 3" in text, (
        "потолок «до трёх ответов» не назван — модель выберет сколько захочет"
    )


def test_служебный_вариант_объявлен_одиночным():
    text = render_questions(_all_themes())
    assert "только сам по себе" in text or "в одиночку" in text, (
        "правило «не испытал никаких эмоций выбирается один» не названо"
    )


def test_формулировка_каждого_вопроса_на_месте():
    """`_asked_questions` сверяет промпт с анкетой по формулировке и отказывает, если её нет."""
    text = render_questions(_all_themes())
    for q in SURVEY["questions"]:
        assert q["label"] in text, f"вопрос №{q['number']}: формулировка не доехала"


# ─── Счётчик полей ───────────────────────────────────────────────────────────


def test_поля_считаются_по_строкам_матрицы_а_не_по_вопросам():
    fields = answerable_fields(_all_themes())
    ids = [f for f in fields]
    assert len(set(ids)) == len(ids), "адреса полей повторяются"
    # 13 нематричных вопросов + 43 подтемы вопроса 9 + 11 подвопросов вопроса 11
    assert len(fields) == 13 + 43 + 11, (
        f"полей {len(fields)}, ожидалось 67 = 13 обычных вопросов + 43 подтемы + 11 подвопросов"
    )


def test_матричное_поле_адресуется_вопросом_и_строкой():
    fields = set(answerable_fields(_all_themes()))
    assert "q09-themes/t1-1" in fields, "подтема адресуется парой «вопрос/строка»"
    assert "q09-themes" not in fields, "матрица целиком полем не является — отвечают построчно"
    assert "q01-plot" in fields, "обычный вопрос адресуется своим идентификатором"
