"""
Разбор анкеты: все формы, которые до него доезжают.

─── Почему именно этот модуль ────────────────────────────────────────────────
Он трижды за одну сессию оказывался источником дефекта, и ни разу — падением на
месте. Анкета приезжает в очередь СПИСКОМ, а читалась как словарь; падало это
не в разборе, а на 344-й секунде прогона в `respondent/run.py`, потом, после
починки первого места, на 690-й в `qa/checks.py`. Затем оказалось, что
формулировка вопроса берётся из поля `text`, которого в контракте нет, — и это
хуже отказа: прогон проходит целиком, стоит полную цену и даёт ответы на
вопросы, которых персона не видела.

Ни одна из трёх поломок не была видна на глаз. Отсюда набор случаев ниже: не
«работает ли разбор», а «что он делает с тем, что до него реально доезжает».
"""

from __future__ import annotations

import pytest

from agent_core.survey import question_label, survey_questions

# ─── Формы анкеты ────────────────────────────────────────────────────────────

def test_list_is_the_canonical_shape():
    """Именно список кладёт в очередь POST /api/tasks."""
    survey = [{"id": "q1", "label": "Как вам ролик?"}]
    assert survey_questions(survey) == survey


def test_dict_with_questions_is_accepted():
    """Форма из фикстур CDD и ручных прогонов."""
    assert survey_questions({"questions": [{"id": "q1"}]}) == [{"id": "q1"}]


@pytest.mark.parametrize("survey", [None, "", 0, [], {}, {"questions": None}, "текст"])
def test_no_survey_is_legal_and_gives_empty_list(survey):
    """
    Прогон без анкеты законен — он идёт по пяти базовым критериям. Исключение
    здесь остановило бы законный сценарий, а пустой список ведёт себя как
    отсутствие вопросов везде ниже по течению.
    """
    assert survey_questions(survey) == []


def test_non_dict_entries_are_dropped_not_crashed():
    """
    В списке может оказаться строка — так выглядит анкета, собранная в обход
    конструктора. Уронить на ней прогон значит потерять уже оплаченные
    расшифровку и разбор кадров ради одной битой строки.
    """
    assert survey_questions([{"id": "q1"}, "мусор", None, 42, {"id": "q2"}]) == [
        {"id": "q1"},
        {"id": "q2"},
    ]


def test_dict_shape_also_drops_non_dict_entries():
    assert survey_questions({"questions": [{"id": "q1"}, ["ерунда"]]}) == [{"id": "q1"}]


# ─── Формулировка вопроса ────────────────────────────────────────────────────

def test_label_is_the_contract_field():
    assert question_label({"label": "Как вам ролик?"}) == "Как вам ролик?"


def test_text_is_only_a_fallback():
    """
    `text` оставлен ради старых записей, но контракт — `label`. Если стоят оба,
    выигрывает контракт: иначе старое поле, забытое в базе, тихо переопределяло
    бы то, что человек напечатал в конструкторе.
    """
    assert question_label({"label": "новое", "text": "старое"}) == "новое"
    assert question_label({"text": "старое"}) == "старое"


def test_question_without_label_gives_empty_string_not_none():
    """
    Пустая строка, а не None: ниже по течению формулировка склеивается в промпт,
    и None превратился бы в подстроку «None» в тексте, который увидит персона.
    """
    assert question_label({"id": "q1"}) == ""
    assert question_label({}) == ""


def test_label_is_trimmed():
    # Пробелы приезжают из конструктора и из вставки из документа. Без обрезки
    # ключ ответа не совпадёт с ключом вопроса — это ровно тот дефект, который
    # чинился в qa/checks.py.
    assert question_label({"label": "  Как вам ролик?\n"}) == "Как вам ролик?"


def test_label_of_non_string_value_does_not_crash():
    """Число в поле формулировки — не повод ронять прогон."""
    assert question_label({"label": 42}) == "42"
