"""
Персона видит таймкод готовым, а не собирает его из чисел.

─── Как это нашлось ─────────────────────────────────────────────────────────
Первый чистый прогон на сценной сетке: QA забраковал 8 ответов из 12, все по
`grounding`, из них три — правилом, с одинаковой причиной:

    grounding_refs: таймкод 44:48 за пределами ролика (02:42)
    grounding_refs: таймкод 50:58 за пределами ролика (02:42)
    grounding_refs: таймкод 58:22 за пределами ролика (02:42)

44:48 — это не сорок четыре минуты. Это ячейка таймлайна «с 44-й по 48-ю
секунду»: персона получала `{"start": 44.0, "end": 48.0}` — голые числа — и
склеивала их через двоеточие, потому что промпт просит «таймкод». Правило
читало результат как MM:SS и справедливо видело выход за длительность.

То есть ответ был ВЕРНЫМ — персона сослалась на реальный момент, — а
забраковали его из-за формы, которую мы же ей и подсказали.

─── Почему чинится в пакете, а не в разборе ссылок ──────────────────────────
Соблазн — научить правило угадывать: «если MM:SS не помещается в ролик, читай
как диапазон секунд». Это лечит симптом и добавляет догадку туда, где сейчас
однозначность. Персона по-прежнему писала бы вольную форму, а правило
угадывало бы — и однажды угадало бы неверно на ролике длиннее часа.

Источник проблемы в том, что мы показываем время машинным форматом и просим
человеческий. Поэтому ячейка получает готовую строку `0:44–0:48`, а числа
остаются рядом для арифметики.
"""

from __future__ import annotations

from agent_core.content.pack import build_pack, format_timecode


def _scene(index: int, start: float, end: float) -> dict:
    return {
        "panel_index": index,
        "timestamp_sec": start,
        "end_sec": end,
        "is_cut": True,
        "scene_description": f"сцена {index}",
    }


def test_timecode_is_minutes_and_seconds():
    """M:SS, а не голые секунды: именно в этой форме о видео говорят люди."""
    assert format_timecode(0) == "0:00"
    assert format_timecode(44) == "0:44"
    assert format_timecode(65.4) == "1:05"
    assert format_timecode(162) == "2:42"


def test_hours_appear_only_when_they_exist():
    """
    Часы в подписи трёхминутного ролика — лишний разряд, который персона
    перепишет в ответ и который потом придётся разбирать.
    """
    assert format_timecode(3599) == "59:59"
    assert format_timecode(3600) == "1:00:00"


def test_cell_carries_a_ready_made_timecode():
    """
    Ячейка отдаёт готовую строку. Собирать её из start и end персона не должна:
    именно самостоятельная сборка и дала «44:48» вместо «0:44–0:48».
    """
    pack = build_pack(
        transcript=[], speakers=[],
        scenes=[_scene(0, 44.0, 48.0), _scene(1, 65.4, 73.6)],
        duration_sec=162.0, mode="short", title="t",
    )
    cells = pack.full()["timeline"]

    assert cells[0]["time"] == "0:44–0:48"
    # 73.6 округляется до 74: округление, а не отбрасывание дробной части —
    # подпись ближе к настоящей границе, а промах в полсекунды не меняет,
    # куда попадёт перемотка.
    assert cells[1]["time"] == "1:05–1:14"
    # Числа остаются рядом: по ним считает код, строку читает персона.
    assert cells[0]["start"] == 44.0
    assert cells[0]["end"] == 48.0


def test_compact_form_keeps_the_timecode():
    """
    Компактная форма — та, что уходит в массовый прогон. Потерять в ней
    таймкод значит вернуть персону к сборке из чисел ровно там, где отвечает
    большинство аудитории.
    """
    pack = build_pack(
        transcript=[{"start": 45.0, "end": 47.0, "text": "достаточно длинная реплика"}],
        speakers=[],
        scenes=[_scene(0, 44.0, 48.0)],
        duration_sec=162.0, mode="short", title="t",
    )
    compact = pack.compact()["timeline"]

    assert compact, "ячейка с репликой обязана пережить сжатие"
    assert compact[0]["time"] == "0:44–0:48"
