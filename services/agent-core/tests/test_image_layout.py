"""
Корень раскладки не вычисляется арифметикой по `Path(__file__).parents[N]`.

─── Что случилось 18.09.2026 ─────────────────────────────────────────────────
`portraits/distill.py` считал корень как `Path(__file__).resolve().parents[4]`.
Это верно ровно для одной раскладки — репозитория, где модуль лежит по пути
services/agent-core/agent_core/portraits/distill.py. В образе воркера пакет
кладётся в корень: /app/agent_core/portraits/distill.py, и ЧЕТВЁРТОГО ПРЕДКА У
ТАКОГО ПУТИ НЕТ — выше /app только «/».

Обращение к несуществующему предку бросает IndexError, и бросает его ПРИ
ИМПОРТЕ. Это роняет не одно чтение файла, а весь процесс: celery не смог
загрузить модуль задач, и воркер на боевом ушёл в цикл перезапуска. Пока
`distill` звали только из веба и из CLI, дефект молчал; детонировал его первый
же импорт из `persona/tasks.py`.

Ни один прежний тест этого не видел и не мог: все они запускаются из
репозитория, где глубина «правильная». Воспроизвести короткий путь в тесте
тоже нельзя — для этого надо класть пакет на уровень ниже корня файловой
системы. Поэтому проверка статическая: она запрещает сам приём.

─── Почему запрет, а не поиск IndexError ─────────────────────────────────────
Вторая, более тихая половина того же дефекта — промах МИМО каталога без всякой
ошибки: `parents[4] / "data"` в образе разворачивается в `/data`, то есть в
корень файловой системы, где ничего нет. Это уже случалось с корпусом
заземления. Так что дело не в исключении, а в допущении о глубине.

Правильный приём один и живёт в `agent_core/paths.py`: `find_repo_file` и
`find_data_file` перебирают известные раскладки. В шапке того модуля прямо
сказано, что приём уже дважды написан по месту и потому должен жить один раз.
"""
from __future__ import annotations

import re
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1] / "agent_core"

#: Только ВЕРХНИЙ УРОВЕНЬ модуля: строка, у которой код начинается с колонки 0.
#:
#: Такой индекс роняет весь процесс при импорте, и это та поломка, которая уже
#: случилась. Тот же приём внутри функции — тоже мина, но срабатывает она на
#: одном вызове и не мешает воркеру подняться. Четыре такие остались в
#: persona/enrich.py, persona/validate.py, qa/judge.py и respondent/run.py: это
#: четыре копии одного помощника, которому по шапке paths.py положено жить в
#: одном месте. Снимаются отдельной задачей, не срочной правкой боевого.
FIXED_DEPTH = re.compile(r"^[A-Za-z_].*\.parents\[\d+\]")

#: `paths.py` сам объясняет приём и в примерах цитирует `parents[4]` — он и
#: есть лекарство, а не болезнь. Тест — тоже: он цитирует дефект в описании.
ALLOWED = {"paths.py", "test_image_layout.py"}


def test_глубина_пути_не_зашита_числом() -> None:
    offenders: list[str] = []
    for path in sorted(PACKAGE.rglob("*.py")):
        if path.name in ALLOWED:
            continue
        for number, line in enumerate(path.read_text("utf-8").splitlines(), 1):
            code = line.split("#", 1)[0]
            if FIXED_DEPTH.search(code):
                offenders.append(f"{path.relative_to(PACKAGE.parent)}:{number}: {line.strip()}")

    assert not offenders, (
        "корень раскладки вычислен арифметикой по parents[N] — в образе воркера "
        "путь короче, и это либо IndexError при импорте (процесс падает), либо "
        "молчаливый промах в /data. Возьмите find_repo_file / find_data_file из "
        "agent_core/paths.py:\n  " + "\n  ".join(offenders)
    )
