"""
Анкета заказчика как ДАННЫЕ, а не как текст в промпте.

─── Зачем файл, а не константы в коде ───────────────────────────────────────
Пятнадцать обязательных вопросов, тринадцать эмоций, семнадцать ценностей,
десять тем с сорока тремя подтемами и одиннадцать вопросов воздействия — это
внешний документ заказчика, у которого есть происхождение и версия. Ровно по
этой причине в `data/values/traditional_values.json` уже лежит перечень Указа
809: у списка есть источник вне репозитория, и он обязан приехать вместе с
ним, а не быть переписанным в код.

Второй копии семнадцати ценностей здесь НЕ заводится. Два списка с одним
смыслом расходятся молча — это тот же дефект, что `START_HERE.md` со
скопированным статусом: заметить расхождение по тексту невозможно, а стоит оно
прохода.

─── Что этот тест держит ────────────────────────────────────────────────────
Форму анкеты, и только её. Он ничего не говорит о том, хорошо ли персоны на неё
отвечают — это вопрос замера, а не проверки структуры. Он говорит, что состав
вопросов и вариантов совпадает с присланным документом: числа 15, 13, 17, 43 и
11 взяты из него и проверяются поимённо, потому что ошибиться в них легко и
незаметно. В переписке владельца уже дважды прозвучало «пятнадцать эмоций» и
«девятнадцать вариантов в вопросе 7» — оба раза мимо, и оба раза это изменило
бы и диаграмму, и схему ответа.
"""
from __future__ import annotations

import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[3]
SURVEY_PATH = REPO / "data" / "survey" / "customer_2026.json"
VALUES_PATH = REPO / "data" / "values" / "traditional_values.json"


def _doc() -> dict:
    assert SURVEY_PATH.exists(), (
        f"нет {SURVEY_PATH.relative_to(REPO)} — анкета заказчика не заведена как данные"
    )
    return json.loads(SURVEY_PATH.read_text("utf-8"))


def _questions() -> list[dict]:
    return _doc()["questions"]


def _by_number(n: int) -> dict:
    found = [q for q in _questions() if q.get("number") == n]
    assert len(found) == 1, f"вопрос №{n}: найдено {len(found)} штук вместо одного"
    return found[0]


# ─── Общая форма ─────────────────────────────────────────────────────────────


def test_анкета_лежит_в_данных_а_не_в_коде():
    doc = _doc()
    assert doc.get("source"), "у анкеты нет поля source — откуда взялся перечень"
    assert doc.get("version"), (
        "у анкеты нет версии: без неё отчёт не скажет, по какой редакции посчитан"
    )


def test_ровно_пятнадцать_обязательных_вопросов():
    qs = _questions()
    assert len(qs) == 15, f"обязательных вопросов {len(qs)}, а в Приложении 1 их пятнадцать"
    assert [q["number"] for q in qs] == list(range(1, 16)), "нумерация вопросов не 1..15 подряд"


def test_идентификаторы_уникальны():
    ids = [q["id"] for q in _questions()]
    assert len(set(ids)) == len(ids), "идентификаторы вопросов повторяются"


def test_каждый_вопрос_принадлежит_одному_из_шести_блоков():
    blocks = _doc()["blocks"]
    assert len(blocks) == 6, f"блоков {len(blocks)}, договаривались о шести"
    known = {b["id"] for b in blocks}
    for q in _questions():
        assert q.get("block") in known, (
            f"вопрос №{q['number']}: блок {q.get('block')!r} не объявлен"
        )


def test_варианты_внутри_вопроса_не_повторяются():
    for q in _questions():
        ids = [o["id"] for o in q.get("options", [])]
        assert len(set(ids)) == len(ids), (
            f"вопрос №{q['number']}: идентификаторы вариантов повторяются"
        )
        labels = [o["label"] for o in q.get("options", [])]
        assert len(set(labels)) == len(labels), (
            f"вопрос №{q['number']}: подписи вариантов повторяются"
        )


# ─── Шкалы ───────────────────────────────────────────────────────────────────


def test_все_шкалы_от_нуля_до_десяти():
    """
    Ноль доступен. В полевых анкетах заказчика шкала подписана «от 1 до 10», в
    требованиях — «от 0 до 10»; расходятся два его документа, и владелец выбрал
    требования (17.09.2026). Из-за этого средние наших прогонов нельзя
    сравнивать со средними его волн напрямую — сравнимы доли 8–10 и NPS.
    """
    scales = [q for q in _questions() if q["type"] == "scale"]
    assert [q["number"] for q in scales] == [1, 2, 3, 4, 5, 6, 15], (
        f"шкальными должны быть вопросы 1-6 и 15, а не {[q['number'] for q in scales]}"
    )
    for q in scales:
        assert q["scaleMin"] == 0, (
            f"вопрос №{q['number']}: нижняя граница {q['scaleMin']}, а не 0"
        )
        assert q["scaleMax"] == 10, (
            f"вопрос №{q['number']}: верхняя граница {q['scaleMax']}, а не 10"
        )


# ─── Вопрос 7: эмоции ────────────────────────────────────────────────────────


def test_в_вопросе_семь_тринадцать_эмоций_и_два_служебных_варианта():
    """
    Пятнадцать столбцов на диаграмме, а не семнадцать и не девятнадцать.
    Шесть эмоций записаны парой слов через запятую («Восхищение, восторг»), и
    посчитать их за две — самая лёгкая ошибка в этом списке.
    """
    q = _by_number(7)
    assert q["type"] == "multi_choice"
    options = q["options"]
    assert len(options) == 15, f"вариантов {len(options)}, ожидалось 15 = 13 эмоций + 2 служебных"
    service = [o for o in options if o.get("service")]
    assert len(service) == 2, f"служебных вариантов {len(service)}, ожидалось два"
    assert [o["label"] for o in service] == [
        "Не испытал никаких эмоций",
        "Затрудняюсь ответить",
    ]


def test_в_вопросе_семь_до_трёх_ответов():
    assert _by_number(7)["maxChoices"] == 3


def test_служебные_варианты_выбираются_в_одиночку():
    for n in (7, 8):
        q = _by_number(n)
        exclusive = set(q["exclusiveOptionIds"])
        service = {o["id"] for o in q["options"] if o.get("service")}
        assert exclusive == service, (
            f"вопрос №{n}: взаимоисключающими объявлены {exclusive}, а служебные — {service}"
        )


# ─── Вопрос 8: ценности ──────────────────────────────────────────────────────


def test_в_вопросе_восемь_девятнадцать_вариантов():
    q = _by_number(8)
    assert q["type"] == "multi_choice"
    assert len(q["options"]) == 19, (
        f"вариантов {len(q['options'])}, ожидалось 19 = 17 ценностей + 2 служебных"
    )
    assert q["maxChoices"] == 3


def test_ценности_берутся_из_существующего_справочника_а_не_переписаны():
    """
    Ровно те же семнадцать строк и в том же порядке, что в
    `data/values/traditional_values.json`. Второй список с тем же смыслом
    разошёлся бы с первым молча.
    """
    canon = json.loads(VALUES_PATH.read_text("utf-8"))["values"]
    q = _by_number(8)
    got = [o["label"] for o in q["options"] if not o.get("service")]
    assert got == canon, "перечень ценностей вопроса 8 разошёлся со справочником Указа 809"


# ─── Вопрос 9: темы ──────────────────────────────────────────────────────────


def test_в_вопросе_девять_десять_тем_и_сорок_три_подтемы():
    q = _by_number(9)
    assert q["type"] == "matrix_single"
    themes = q["themes"]
    assert len(themes) == 10, f"тем {len(themes)}, в документе десять"
    rows = q["rows"]
    assert len(rows) == 43, f"подтем {len(rows)}, в документе сорок три"
    known = {t["id"] for t in themes}
    for row in rows:
        assert row["themeId"] in known, f"подтема {row['id']}: тема {row['themeId']!r} не объявлена"
    counts = {t["id"]: 0 for t in themes}
    for row in rows:
        counts[row["themeId"]] += 1
    assert list(counts.values()) == [6, 4, 5, 4, 4, 4, 4, 5, 3, 4], (
        f"подтемы разложены по темам как {list(counts.values())}, а в документе 6-4-5-4-4-4-4-5-3-4"
    )


def test_у_вопроса_девять_три_варианта_ответа():
    q = _by_number(9)
    assert [o["label"] for o in q["options"]] == [
        "Скорее эта тема поднималась",
        "Скорее эта тема не поднималась",
        "Затрудняюсь ответить / Не могу оценить",
    ]


# ─── Вопрос 11: воздействие ──────────────────────────────────────────────────


def test_в_вопросе_одиннадцать_одиннадцать_подвопросов_по_десяти_темам():
    """
    Не десять: у темы 4 «Национальное единство и культурное многообразие» в
    таблице заказчика две строки.
    """
    q = _by_number(11)
    rows = q["rows"]
    assert len(rows) == 11, f"подвопросов {len(rows)}, в таблице заказчика одиннадцать"
    themes = [r["themeId"] for r in rows]
    assert len(set(themes)) == 10, "подвопросы покрывают не все десять тем"
    doubled = [t for t in set(themes) if themes.count(t) == 2]
    assert len(doubled) == 1, "ровно у одной темы должно быть два подвопроса"


def test_в_вопросе_одиннадцать_только_да_и_нет():
    """Владелец решил 17.09.2026: «затрудняюсь ответить» здесь нет."""
    q = _by_number(11)
    assert [o["label"] for o in q["options"]] == ["Да", "Нет"]


def test_вопрос_одиннадцать_привязан_к_выбору_тем_вопроса_девять():
    q = _by_number(11)
    assert q.get("dependsOnQuestion") == _by_number(9)["id"], (
        "вопрос 11 должен добавляться по выбранным темам вопроса 9, иначе его "
        "подвопросы попадут в анкету целиком независимо от выбора оператора"
    )


# ─── Одиночный выбор ─────────────────────────────────────────────────────────


def test_вопросы_с_одним_ответом_имеют_объявленное_число_вариантов():
    expected = {10: 3, 12: 6, 13: 3, 14: 3}
    for number, size in expected.items():
        q = _by_number(number)
        assert q["type"] == "single_choice", f"вопрос №{number}: тип {q['type']}"
