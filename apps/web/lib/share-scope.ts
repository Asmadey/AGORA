/**
 * Что показывает публичная ссылка в каждой из двух областей.
 *
 * ─── Что здесь чинится ────────────────────────────────────────────────────
 * Диалог «Поделиться» предлагает выбор: весь отчёт или только сводка. Выбор
 * доезжал до базы честно — колонка `report_shares.scope` заполнялась, — но на
 * публичной странице от него зависела ОДНА секция из двенадцати: «Темы».
 * Всё остальное совпадало. То есть «весь отчёт» и «только сводка» давали почти
 * одинаковую страницу, и обе показывали сводку.
 *
 * Причина глубже переключателя. Публичная страница была второй, написанной от
 * руки реализацией отчёта: пять секций против двенадцати у внутренней. Две
 * реализации одного экрана расходятся молча — сравнить их можно только открыв
 * рядом, а рядом их никто не держит.
 *
 * Поэтому список секций живёт здесь один, а рисует их общий `ReportBody`.
 * Функция чистая и проверяется тестом: «что видно по ссылке» — это то, что
 * уходит наружу, и утверждать это надо, а не предполагать.
 */

export type ReportScope = "full" | "aggregate";

/**
 * Секции отчёта в порядке чтения.
 *
 * Имена совпадают с заголовками на экране, чтобы расхождение между тестом и
 * страницей было видно глазами, а не только в диффе.
 */
export const REPORT_SECTIONS = [
  "degraded",
  "material",
  "metrics",
  "narrative",
  "criteria",
  "emotions",
  "riskPoints",
  "segments",
  "synthesis",
  "qa",
  "asked",
  "personas",
] as const;

export type ReportSection = (typeof REPORT_SECTIONS)[number];

/**
 * Сводка — это числа и выводы, без того, из чего они собраны.
 *
 * Граница проведена по одному признаку: **сводка не содержит сырья**. Ответы
 * персон, их вербатим, цитаты синтеза, точки риска с таймкодами и сам материал
 * — это то, что персона сказала и что она смотрела. Тот, кому дали ссылку на
 * сводку, получает результат исследования, а не его первичные данные.
 *
 * «Проверка ответов» тоже не входит: доля отбраковок QA — внутренняя кухня
 * прогона, и по ней читают качество работы, а не качество ролика.
 *
 * `degraded` входит в обе области намеренно. Это предупреждение о том, что
 * отчёт собран не полностью; скрыть его в сводке значило бы отдать наружу
 * неполный отчёт, выглядящий полным.
 */
const AGGREGATE_SECTIONS: readonly ReportSection[] = [
  "degraded",
  "metrics",
  "narrative",
  "criteria",
  "emotions",
];

export function sectionsFor(scope: ReportScope): ReportSection[] {
  return scope === "full"
    ? [...REPORT_SECTIONS]
    : REPORT_SECTIONS.filter((s) => AGGREGATE_SECTIONS.includes(s));
}

export function showsSection(scope: ReportScope, section: ReportSection): boolean {
  return scope === "full" || AGGREGATE_SECTIONS.includes(section);
}

/**
 * Область из строки в базе.
 *
 * Неизвестное значение сводится к `aggregate`, а не к `full`: колонка
 * текстовая, и опечатка при записи не должна оборачиваться показом большего,
 * чем выбрал выпускающий ссылку. Ошибаться здесь надо в сторону меньшего.
 */
export function parseScope(raw: unknown): ReportScope {
  return raw === "full" ? "full" : "aggregate";
}
