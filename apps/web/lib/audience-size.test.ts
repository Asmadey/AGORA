import assert from "node:assert/strict";
import { test } from "node:test";

import {
  AUDIENCE_SIZE_BOUNDS,
  DEFAULT_AUDIENCE_SIZE,
  parseAudienceChoice,
} from "./audience.ts";

/**
 * Размер аудитории: нижняя граница выбрана по арифметике, а не по ощущению.
 *
 * ─── Откуда числа ──────────────────────────────────────────────────────────
 * Заказчик требует колонку «14–35 лет» у КАЖДОГО показателя. Доля этой группы
 * в корпусе — 74 записи из 165, то есть 44.8 %, и генератор сэмплирует
 * возрастные группы по корпусным долям. Значит в срез попадает примерно
 * 0.45 от размера набора:
 *
 *     набор 20  → в срезе  9, один человек 11 п.п.,  погрешность ±16.7 п.п.
 *     набор 40  → в срезе 18, один человек 5.6 п.п., погрешность ±11.8 п.п.
 *     набор 100 → в срезе 45, один человек 2.2 п.п., погрешность ±7.5 п.п.
 *     набор 200 → в срезе 90, один человек 1.1 п.п., погрешность ±5.3 п.п.
 *
 * Собственные полевые волны заказчика — от 28 до 117 человек.
 *
 * Решение владельца 17.09.2026: минимум 40, потолок 200. Прежний минимум был
 * единица, а подпись рекомендовала 20 — при таком наборе один человек в срезе
 * весит одиннадцать процентных пунктов, и колонка «14–35» выглядит такой же
 * точной, как у заказчика, будучи втрое грубее.
 *
 * ─── Что этот тест держит ──────────────────────────────────────────────────
 * Границы и то, что они действительно проверяются. Число в константе, которое
 * никто не сверяет, — это подпись, а не граница.
 */

test("нижняя граница — 40 персон", () => {
  assert.equal(AUDIENCE_SIZE_BOUNDS.min, 40);
});

test("потолок — 200 персон", () => {
  assert.equal(AUDIENCE_SIZE_BOUNDS.max, 200);
});

test("умолчание попадает в границы и хватает на срез 14–35", () => {
  assert.ok(DEFAULT_AUDIENCE_SIZE >= AUDIENCE_SIZE_BOUNDS.min);
  assert.ok(DEFAULT_AUDIENCE_SIZE <= AUDIENCE_SIZE_BOUNDS.max);
  assert.ok(
    DEFAULT_AUDIENCE_SIZE >= 100,
    "ниже сотни в срезе 14–35 меньше сорока пяти человек, и доли в нём шагают крупнее двух пунктов",
  );
});

const criteria = (size: number) => ({
  size,
  ageGroups: ["25-34"],
  geos: ["столицы"],
  genders: ["жен"],
  education: [],
});

test("набор меньше минимума отвергается, а не подправляется молча", () => {
  const r = parseAudienceChoice(criteria(20));
  assert.equal(r.ok, false);
  assert.match(r.ok === false ? r.errors.join("; ") : "", /40/);
});

test("набор больше потолка отвергается", () => {
  const r = parseAudienceChoice(criteria(300));
  assert.equal(r.ok, false);
});

test("набор в границах принимается", () => {
  const r = parseAudienceChoice(criteria(100));
  assert.equal(r.ok, true, r.ok === false ? r.errors.join("; ") : "");
});
