/**
 * Контракт шаблона промпта: какие переменные он обязан использовать.
 *
 * ─── Зачем ────────────────────────────────────────────────────────────────
 * Переопределение `analytics.report` у арендатора с 03.08.2026 выглядело так —
 * целиком:
 *
 *     test {{content}}
 *
 * Промпт-студия его приняла: PUT извлекал переменные ИЗ САМОГО шаблона и
 * сверял шаблон с ними же. Такая проверка не может не пройти.
 *
 * Дальше это работало полгода и молча. Стадия отчёта подставляет шесть своих
 * переменных, ни одна из которых в шаблоне не названа, — значит модель не
 * получает ни агрегата, ни ответов персон. `{{content}}` не подставляет никто —
 * значит он уезжает в модель фигурными скобками. Прогон 0051 отправил так 64
 * токена и получил обратно `{"content": "test {{content}}"}`. В отчёте после
 * этого пусты нарратив, темы, сильные и слабые стороны — а числовая часть
 * посчитана полностью и выглядит убедительно.
 *
 * ─── Что считается контрактом ─────────────────────────────────────────────
 * Переменные ДЕФОЛТНОГО шаблона того же ключа. Это ровно то, что стадия кладёт
 * в подстановку: дефолт seed-ится миграцией из того же места, откуда воркер
 * берёт запасной файл.
 *
 * Отсюда два отказа:
 *
 * * `missing` — переменная дефолта в шаблоне не названа. Данные, которые стадия
 *   собрала и оплатила, до модели не доедут.
 * * `unknown` — в шаблоне есть переменная, которой стадия не даёт. Она уедет в
 *   модель как есть, вместе со скобками.
 *
 * ─── Почему не «предупреждение» ───────────────────────────────────────────
 * Предупреждение здесь бесполезно: оно показывается один раз тому, кто и так
 * жмёт «сохранить», а последствие наступает через час прогона и выглядит как
 * скупой отчёт. Владелец может вернуть переменную в текст в любом месте — цена
 * отказа одна строка, цена пропуска — прогон.
 */

/** Извлекает {{имена}} без повторов. Та же логика, что в prompt-registry.ts. */
export function placeholderNames(text: string): string[] {
  const found = (text ?? "").matchAll(/\{\{\s*([a-zA-Z0-9_.]+)\s*\}\}/g);
  return [...new Set([...found].map((m) => m[1]))];
}

export interface ContractViolation {
  /** Переменные дефолта, которых нет в новом шаблоне. */
  missing: string[];
  /** Переменные нового шаблона, которых нет у стадии. */
  unknown: string[];
}

/**
 * Сверяет шаблон с дефолтом того же ключа.
 *
 * `null` — нарушений нет. Дефолт без переменных (или отсутствующий) означает,
 * что сверять не с чем: тогда проверка не срабатывает, вместо того чтобы
 * запретить всё подряд.
 */
export function checkTemplateContract(
  template: string,
  defaultTemplate: string | null | undefined,
): ContractViolation | null {
  const required = placeholderNames(defaultTemplate ?? "");
  if (required.length === 0) return null;

  const used = new Set(placeholderNames(template));
  const requiredSet = new Set(required);

  const missing = required.filter((name) => !used.has(name));
  const unknown = [...used].filter((name) => !requiredSet.has(name));

  if (missing.length === 0 && unknown.length === 0) return null;
  return { missing, unknown };
}

/** Человеческая формулировка отказа — она уезжает прямо в интерфейс. */
export function describeViolation(key: string, v: ContractViolation): string {
  const parts: string[] = [];
  if (v.missing.length > 0) {
    parts.push(
      `не использованы переменные стадии: ${v.missing.map((n) => `{{${n}}}`).join(", ")}` +
        " — эти данные до модели не доедут",
    );
  }
  if (v.unknown.length > 0) {
    parts.push(
      `стадия не даёт переменных: ${v.unknown.map((n) => `{{${n}}}`).join(", ")}` +
        " — они уедут в модель вместе со скобками",
    );
  }
  return `шаблон ${key} не соответствует контракту стадии: ${parts.join("; ")}`;
}
