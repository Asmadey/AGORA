/**
 * Ширина колонок таймлайна — из содержимого пакета, а не из числа на глаз.
 *
 * ─── Зачем ────────────────────────────────────────────────────────────────
 * Прежде стояло `grid-cols-[minmax(0,7fr)_minmax(0,9fr)]`. Замерено на боевом
 * (прогон 0091, 16.09.2026):
 *
 *     колонка «Сцена» ......... 227.5 px (под текст 135)
 *     колонка «Речь» .......... 292.5 px
 *     знаков в строке описания . 15
 *     описание 139 знаков ...... 10 строк
 *     высота ячейки ............ 236 px (медиана)
 *
 * А в самом пакете:
 *
 *     описания сцен ... 77 % текста, есть в 322 из 322 ячеек, медиана 139
 *     речь ............ 23 % текста, ОТСУТСТВУЕТ в 186 из 322 ячеек
 *
 * Более широкая колонка несла меньше четверти текста и пустовала в 58 % строк;
 * колонка с тремя четвертями текста была сжата до пятнадцати знаков в строку.
 * На 322 ячейках это около 76 000 px прокрутки в окне высотой 600.
 *
 * ─── Почему не «доля текста» ──────────────────────────────────────────────
 * Отдать 77/23 — та же ошибка, только в другую сторону. Высоту строки задаёт
 * ТА ИЗ ДВУХ колонок, что выше. 186 ячеек без речи в долю текста попадают и
 * тянут её к описаниям, но на высоту тех строк ширина колонки речи не влияет
 * вовсе. Зато в ячейке, где речь есть, сжатая колонка вырастет выше описания —
 * и строка станет выше прежней.
 *
 * Поэтому считается не доля текста, а СУММАРНАЯ ВЫСОТА ленты: перебор долей и
 * выбор той, при которой лента короче всего. Это ровно та величина, ради
 * которой всё затевалось, и она сама разбирается с обоими перекосами.
 */

/** Превью кадра в ячейке сцены. Ширина класса `w-20`. */
const PREVIEW_PX = 80;

/** Просвет между превью и описанием (`gap-3`) и между колонками. */
const GAP_PX = 12;

/**
 * Сколько знаков помещается в пиксель ширины при здешнем шрифте.
 *
 * Замер, а не прикидка: на боевом 15 знаков укладывались в 135 px при шрифте
 * 10 px. Величина приблизительная по природе — ширина знака зависит от самого
 * знака, — но нужна она только чтобы СРАВНИТЬ два варианта деления между
 * собой, а не чтобы предсказать высоту в пикселях.
 */
const CHARS_PER_PX = 15 / 135;

/**
 * Ширина области под обе колонки, в пикселях.
 *
 * Умолчание — замер боевого: панель 572 px минус её собственные отступы
 * `p-3` (24) минус просвет между колонками (12). Точность здесь не критична:
 * от неё зависит только положение оптимума, и то слабо.
 */
const DEFAULT_AREA_PX = 536;

/**
 * Границы, за которые пропорция не выходит.
 *
 * Пакет вообще без речи дал бы колонке речи нулевую ширину, и заголовок
 * «РЕЧЬ» повис бы над пустотой. Пустая колонка — это не «речи нет», это
 * сломанная разметка: читатель видит заголовок и не понимает, почему под ним
 * ничего.
 */
export const MIN_SHARE = 0.35;
export const MAX_SHARE = 0.75;

/**
 * Сколько знаков в строке — нижняя граница читаемости колонки С СОДЕРЖИМЫМ.
 *
 * Перебор минимизирует суммарную высоту и ради этого охотно сожмёт соседнюю
 * колонку до ленты в два слова. На составе 0091 без этого порога он выбирал
 * 0.72: лента короче на 36 %, но речи оставалось 150 px, то есть 16 знаков в
 * строку — ровно то, за что забракована прежняя вёрстка. Выигрыш в прокрутке
 * за счёт нечитаемости соседа — это не выигрыш, а перенос дефекта.
 *
 * 18 знаков — примерно три слова: та ширина, на которой строка ещё читается
 * как строка, а не как столбик. Порог намеренно низкий: он ограждает от
 * вырождения, а не диктует пропорцию.
 */
const MIN_READABLE_CHARS = 18;

/** Шаг перебора. Мельче незаметно глазу, крупнее теряет оптимум. */
const STEP = 0.01;

interface Cell {
  scene: string | null;
  lines: { text: string }[];
}

/** Во сколько строк развернётся `chars` знаков в колонке шириной `px`. */
function lines(chars: number, px: number): number {
  if (chars <= 0) return 0;
  const perLine = Math.max(1, px * CHARS_PER_PX);
  return Math.ceil(chars / perLine);
}

/**
 * Доля ширины под колонку «Сцена». Остаток достаётся «Речи».
 *
 * Перебирает доли и возвращает ту, при которой суммарная высота ленты
 * наименьшая. При равенстве берётся меньшая доля: тогда колонка речи шире, а
 * она содержит цитаты, которые читают целиком.
 */
export function sceneColumnShare(cells: Cell[], areaPx: number = DEFAULT_AREA_PX): number {
  // Считаем по СОСТАВУ, а не по числу ячеек: удвоение ленты не должно менять
  // вёрстку, иначе длинный ролик и короткий с тем же материалом разойдутся
  // без всякой причины.
  const rows = cells.map((c) => ({
    desc: (c.scene ?? "").length,
    speech: (c.lines ?? []).reduce((n, l) => n + (l?.text ?? "").length, 0),
  }));

  if (rows.every((r) => r.desc === 0 && r.speech === 0)) {
    return (MIN_SHARE + MAX_SHARE) / 2;
  }

  // Колонка «имеет содержимое», если оно есть хоть в одной ячейке. Порог
  // читаемости к пустой колонке не применяется: там нечего читать.
  const hasDesc = rows.some((r) => r.desc > 0);
  const hasSpeech = rows.some((r) => r.speech > 0);
  const readablePx = MIN_READABLE_CHARS / CHARS_PER_PX;

  let best: number | null = null;
  let bestHeight = Infinity;
  let fallback = MIN_SHARE;
  let fallbackHeight = Infinity;

  for (let share = MIN_SHARE; share <= MAX_SHARE + 1e-9; share += STEP) {
    // Описание делит свою колонку с превью; речь занимает свою целиком.
    const descPx = Math.max(1, share * areaPx - PREVIEW_PX - GAP_PX);
    const speechPx = Math.max(1, (1 - share) * areaPx);

    let height = 0;
    for (const r of rows) {
      height += Math.max(lines(r.desc, descPx), lines(r.speech, speechPx));
    }

    // Запасной вариант считается всегда: если читаемыми обе колонки сделать
    // нельзя (панель слишком узкая), лучше вернуть наименьшую высоту, чем
    // ничего. Молча отдать MIN_SHARE было бы хуже: это выглядело бы как
    // осознанный выбор.
    if (height < fallbackHeight) {
      fallbackHeight = height;
      fallback = share;
    }

    if (hasDesc && descPx < readablePx) continue;
    if (hasSpeech && speechPx < readablePx) continue;

    // Строгое «меньше»: при равенстве остаётся доля поменьше, найденная раньше.
    if (height < bestHeight) {
      bestHeight = height;
      best = share;
    }
  }

  // Перебор накапливает погрешность сложения — округляем до шага.
  return Math.round((best ?? fallback) / STEP) * STEP;
}
