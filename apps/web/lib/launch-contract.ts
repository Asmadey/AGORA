/**
 * Что обязано быть верным, чтобы прогон вообще мог состояться.
 *
 * ─── Зачем модуль ─────────────────────────────────────────────────────────
 * `POST /api/tasks` принимал `videoRef` как «строка либо отсутствует» и на
 * этом останавливался. Отсутствующий и заведомо негодный ключ проходили
 * дальше: задача создавалась, вставала в очередь, воркер её забирал и падал —
 * `ValueError: video_ref пуст` или `FileNotFoundError`. Пользователь при этом
 * видел появившееся исследование, которое через полминуты становилось FAILED.
 *
 * Отказ здесь знаем в момент запроса. Ровно это рассуждение уже применено в
 * том же маршруте к пустому набору персон: «проверка стоит один COUNT и
 * превращает поздний дорогой отказ в немедленный 400 с названной причиной».
 * К материалу его просто не применили.
 *
 * ─── Почему это ещё и про изоляцию ────────────────────────────────────────
 * RLS не распространяется на S3. Ключ приходит телом запроса, и без проверки
 * префикса арендатора можно было запустить прогон на чужом залитом файле:
 * строка `tasks` создастся в своём арендаторе, а воркер скачает объект
 * соседнего. `POST /api/upload/complete` префикс проверяет — запуск не
 * проверял, хотя это та же граница.
 *
 * ─── Про дублирование формата ключа ───────────────────────────────────────
 * Тот же формат объявлен в `lib/server/s3.ts` (там он создаётся) и в
 * `agent_core/storage.py` (там читается). Третья копия здесь заведена
 * сознательно и закреплена тестом: проверка обязана отличать ключ от мусора
 * ДО постановки в очередь, а тянуть ради этого серверный модуль в разбор тела
 * запроса значит тащить `@aws-sdk` в маршрут, которому он не нужен.
 */

/** Ключ объекта: `tenants/<uuid>/uploads/<имя>`. Совпадает с `_S3_KEY` воркера. */
const S3_KEY = /^tenants\/[0-9a-f-]{36}\/uploads\/[^/]+$/;

export function looksLikeObjectKey(value: string): boolean {
  return S3_KEY.test(value);
}

/**
 * Претензия к материалу запуска — либо `null`, если претензий нет.
 *
 * Текст претензии называет, что не так и как выглядит правильное значение:
 * маршрут открыт не только визарду, и «videoRef: некорректен» отправляет
 * читающего в исходники вместо исправления запроса.
 */
export function checkVideoRef(value: unknown, tenantId: string): string | null {
  if (value === undefined || value === null || value === "") {
    return (
      "videoRef: обязателен — прогон без материала не может состояться. " +
      "Загрузите файл через /api/upload/presign и /api/upload/complete, " +
      "оттуда придёт ключ вида tenants/<uuid>/uploads/<имя>"
    );
  }
  if (typeof value !== "string") return "videoRef: строка";

  const ref = value.trim();
  if (!looksLikeObjectKey(ref)) {
    return (
      `videoRef: «${ref}» не похож на ключ объекта. ` +
      "Ожидается tenants/<uuid>/uploads/<имя> — то, что возвращает " +
      "/api/upload/complete. Локальные пути и адреса s3:// воркер не примет"
    );
  }
  // Префикс сверяется с арендатором сессии, а не просто с формой ключа:
  // форма у чужого ключа ровно та же.
  if (!ref.startsWith(`tenants/${tenantId}/uploads/`)) {
    return "videoRef: ключ принадлежит другому арендатору";
  }
  return null;
}
