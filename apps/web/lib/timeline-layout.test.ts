import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

/**
 * Ширину колонок задаёт разметка, а не размер ролика.
 *
 * ─── Что было ─────────────────────────────────────────────────────────────
 * 16.09.2026 на боевом, прогон 0091: плеер занимал 1306 пикселей, панель сцен —
 * 84. Заголовки «СЦЕНА» и «РЕЧЬ» налезали друг на друга, таймкоды переносились
 * по одной цифре.
 *
 * Владелец связал это с нажатием «play», и это объяснимо, но причина не в нём.
 * Сетка была объявлена так:
 *
 *     lg:grid-cols-[auto_minmax(0,1fr)]
 *
 * Трек `auto` — это `minmax(min-content, max-content)`. Пока браузер не знает
 * собственных размеров ролика, max-content мал, и колонки выглядят нормально.
 * Как только метаданные доехали (`readyState 4`, `videoWidth 1280`), max-content
 * становится шириной ролика, и трек разрастается до неё. «Play» лишь торопит
 * загрузку метаданных — то же самое случится само, если подождать.
 *
 * Панель сцен при этом не защищена ничем: у `minmax(0,1fr)` минимум равен нулю,
 * то есть она обязана отдать всё, что потребует сосед.
 *
 * `max-w-full` на самом ролике не спасал: его содержащий блок объявлен `w-fit`,
 * то есть тоже считается по содержимому. Процент от ширины, которая сама
 * считается от этого процента, разрешается в исходный размер ролика.
 *
 * ─── Что проверяется ──────────────────────────────────────────────────────
 * Не имена классов, а смысл треков: колонка плеера не считается по содержимому,
 * у колонки сцен есть ненулевой минимум, и обёртка плеера не `w-fit`.
 *
 * Проверка именно такая потому, что сегодня же тест, написанный на первое
 * вхождение строки, покраснел на верном коде: маркер был выбран вместо
 * свойства.
 */

const WEB = new URL("..", import.meta.url).pathname;

function read(rel: string): string {
  const p = join(WEB, rel);
  return existsSync(p) ? readFileSync(p, "utf8") : "";
}

/**
 * Без комментариев: разбор обязан идти по коду, а не по его объяснению.
 *
 * Первая редакция этого теста читала `lg:grid-cols-[…]` вместе с комментарием,
 * где та же строка приведена как ОПИСАНИЕ ошибки, — и краснела на исправленном
 * коде. То есть попалась ровно в ту ловушку, о которой предупреждает сама.
 */
function code(text: string): string {
  return text
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

const src = code(read("components/agora/Timeline.tsx"));

/** Разбирает `lg:grid-cols-[A_B]` на два трека. */
function tracks(): [string, string] {
  const m = /lg:grid-cols-\[([^\]]+)\]/.exec(src);
  assert.ok(m, "у сетки таймлайна объявлены колонки для широкого экрана");
  // Подчёркивание в Tailwind — разделитель треков, но внутри minmax(...) его
  // нет, поэтому делить можно по нему, не разбирая скобки.
  const parts = m[1].split("_");
  assert.equal(parts.length, 2, `ожидались два трека, получено: ${m[1]}`);
  return [parts[0], parts[1]];
}

test("колонка плеера не считается по размеру ролика", () => {
  const [player] = tracks();

  assert.notEqual(
    player,
    "auto",
    "`auto` — это minmax(min-content, max-content): трек вырастет до исходной ширины ролика",
  );
  assert.ok(
    !/max-content|fit-content/.test(player),
    `колонка плеера не должна зависеть от содержимого, объявлено: ${player}`,
  );

  // 16.09.2026 раскладка перевёрнута: плеер больше не берёт остаток, а
  // занимает ровно свою ширину — остаток уходит разбору сцен. Требование при
  // этом ТО ЖЕ: верхняя граница не должна зависеть от того, что внутри.
  // Годятся и доля свободного места (`fr`), и заданная длина — лишь бы не
  // содержимое. Ширина плеера считается от потолка высоты и пропорций ролика,
  // то есть из чисел, известных до вёрстки.
  const max = /^minmax\([^,]+,\s*(.+)\)$/.exec(player)?.[1] ?? player;
  assert.ok(
    /fr$/.test(max.trim()) || /^(calc\(|var\(|\d)/.test(max.trim()),
    `верхняя граница колонки плеера — доля места или заданная длина, а не содержимое: ${player}`,
  );
});

test("у панели сцен есть ненулевой минимум", () => {
  const [, scenes] = tracks();

  const m = /^minmax\(\s*([^,]+),/.exec(scenes);
  assert.ok(m, `колонка сцен объявлена через minmax, чтобы у неё был пол: ${scenes}`);

  const min = m[1].trim();
  assert.notEqual(min, "0", "минимум 0 означает «отдать всё соседу» — с этого и началось");
  assert.ok(
    /^\d+(\.\d+)?(rem|px|ch)$/.test(min),
    `минимум колонки сцен задан длиной, а не ${min}`,
  );

  const rem = min.endsWith("rem") ? parseFloat(min) : parseFloat(min) / 16;
  assert.ok(
    rem >= 18,
    `под две подколонки с текстом и превью нужно не меньше 18rem, задано ${min}`,
  );
});

test("обёртка плеера не считается по содержимому", () => {
  // `w-fit` внутри гибкого трека возвращает ту же круговую зависимость:
  // процентный потолок ролика считается от ширины, которая считается от ролика.
  const wrapper = /<div className="([^"]*)"[^>]*>\s*\{data\.video \?/.exec(src)?.[1];
  assert.ok(wrapper, "обёртка плеера найдена");
  assert.ok(
    !/\bw-fit\b/.test(wrapper),
    `обёртка плеера не должна быть w-fit, объявлено: ${wrapper}`,
  );
  assert.ok(
    /\bw-full\b/.test(wrapper),
    "обёртка занимает колонку целиком — тогда max-w-full у ролика считается от неё",
  );
});

test("ролик по-прежнему держит пропорции обеих ориентаций", () => {
  // Правка колонок не должна отменить то, ради чего писался прежний комментарий:
  // вертикальный ролик упирается в потолок высоты, горизонтальный — в ширину.
  //
  // 16.09.2026 механизм заменён. Прежде пропорции держал сам элемент:
  // `w-auto max-h-[600px] max-w-full`, то есть ширина считалась от СОБСТВЕННОГО
  // размера содержимого. Это и давало скачок при нажатии «play»: до него
  // содержимым был постер (512×214), после — ролик.
  //
  // Теперь пропорции задаёт обёртка (`aspectRatio`), а ролик в неё вписывается
  // (`object-contain`). Требование прежнее, и проверяется оно по-прежнему:
  // потолок высоты ради вертикальных роликов и запрет расти по содержимому.
  assert.ok(
    /maxHeight: PLAYER_MAX_HEIGHT|max-h-\[600px\]/.test(src),
    "потолок высоты на месте — без него ролик 9:16 уезжает на три экрана",
  );
  assert.ok(/aspectRatio/.test(src), "пропорции задаёт коробка");
  assert.ok(/object-contain/.test(src), "ролик вписывается в коробку, а не задаёт её");
  const video = /<video[\s\S]*?className="([^"]*)"/.exec(src)?.[1] ?? "";
  assert.ok(
    !/\bw-auto\b/.test(video),
    `ширина по содержимому запрещена: ${video}`,
  );
});
