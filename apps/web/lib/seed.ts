/**
 * Seed набора персон.
 *
 * ─── Почему отдельный модуль ради семи строк ───────────────────────────────
 * Потому что прежние семь строк лежали внутри маршрута и были неверны, а
 * проверить их можно было только подняв HTTP-сервер. Число 42 стояло в трёх
 * местах подряд — умолчание `GenerationConfig`, умолчание маршрута и
 * отсутствие поля в теле запроса из визарда, — и каждое по отдельности
 * выглядело разумным.
 *
 * Проверено на боевой базе: 134 персоны с seed 42, три набора по 12 персон с
 * ОДИНАКОВЫМ списком имён и два набора по 20 — тоже. Владелец создавал одну и
 * ту же аудиторию заново, не зная об этом; различались только тексты
 * `narrative`, которые пишет модель при температуре 0.9.
 *
 * ─── Почему seed не выброшен совсем ────────────────────────────────────────
 * Он записывается в `persona_sets.seed`. Случайный, но сохранённый — это не то
 * же самое, что отсутствующий: набор можно воспроизвести, если понадобится
 * объяснить, откуда взялась конкретная персона. Явно переданный seed
 * по-прежнему исполняется как есть.
 */

/**
 * Потолок значения. int32 — не свойство генератора, а граница, за которой
 * начинается зависимость от разрядности на другом конце: значение уезжает в
 * JSON и приходит в `random.Random` питона.
 */
export const MAX_SEED = 2 ** 31 - 1;

/**
 * Seed из тела запроса либо случайный.
 *
 * Непригодное значение приравнивается к отсутствующему НАМЕРЕННО: прежняя
 * редакция подставляла на него 42, и отличить «не передали» от «передали
 * ерунду» по результату было нельзя. Случайный seed в обоих случаях честнее —
 * он не притворяется осмысленным выбором.
 */
export function resolveSeed(raw: unknown): number {
  if (typeof raw === "number" && Number.isInteger(raw) && raw >= 0 && raw <= MAX_SEED) {
    return raw;
  }
  return Math.floor(Math.random() * (MAX_SEED + 1));
}
