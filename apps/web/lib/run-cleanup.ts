/**
 * Какие объекты хранилища принадлежат прогону.
 *
 * ─── Что чинится ──────────────────────────────────────────────────────────
 * Удаление исследования убирало строку в Postgres, документы `reports` и
 * `report_personas` в Mongo и исходный ролик. Оставались:
 *
 *   * `content_packs` — таймлайн, сцены и расшифровка. На боевой базе 36 из 41
 *     пакета уже осиротели: прогонов, которым они принадлежали, нет;
 *   * кадры сцен в S3 — по файлу на сцену, сотни на прогон;
 *   * `playback_ref` — вторая копия ролика, перекодированная для плеера.
 *
 * Заметить это неоткуда: исследование пропадает из списка, экран чист, а место
 * занято. Счёт за хранилище приходит раз в месяц и не объясняет, чем.
 *
 * ─── Почему кадры берутся из пакета, а не по префиксу ─────────────────────
 * Ключи кадров лежат в самом пакете — по ним таймлайн и рисуется. Это точный
 * список: удаляется ровно то, что прогон создал. Удаление по префиксу
 * `tenants/<t>/runs/<task>/` было бы полнее, но требует постраничного листинга
 * с разбором XML, а главное — стирает всё, что окажется под префиксом, включая
 * то, чего этот прогон не создавал.
 *
 * Цена точности названа: если пакет уже удалён, кадры останутся. Вызывающий
 * обязан сказать об этом вслух, а не молча оставить мусор.
 */

export interface RunObjects {
  /** Исходный ролик, как его загрузил пользователь. */
  videoRef?: string | null;
  /** Перекодированная копия для плеера. */
  playbackRef?: string | null;
  /** Заставка в списке исследований — обычно первый кадр. */
  posterRef?: string | null;
  /** Пакет материала из Mongo; из него берутся кадры сцен. */
  pack?: { scenes?: unknown } | null;
}

/**
 * Ключи объектов прогона без повторов и без пустых значений.
 *
 * Пустая строка, отправленная в S3 ключом, удаляет не то, что задумано, либо
 * отвечает ошибкой — и то и другое хуже пропуска.
 */
export function objectKeysOf(run: RunObjects): string[] {
  const keys: string[] = [];
  const push = (value: unknown) => {
    if (typeof value === "string" && value.trim()) keys.push(value);
  };

  push(run.videoRef);
  push(run.playbackRef);
  push(run.posterRef);

  const scenes = run.pack?.scenes;
  if (Array.isArray(scenes)) {
    for (const scene of scenes) {
      push((scene as { screenshot?: unknown } | null)?.screenshot);
    }
  }

  return [...new Set(keys)];
}
