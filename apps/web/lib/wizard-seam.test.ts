import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

/**
 * Шов между визардом и запуском: доезжает ли до прогона то, что собрано на
 * экранах.
 *
 * ─── Зачем отдельный файл ─────────────────────────────────────────────────
 * Тесты этого проекта устроены по задачам: у #10 «Шаг Опрос» свой, у #11 «Шаг
 * Резюме и запуск» свой, и оба зелёные. Вопрос «доезжает ли анкета от первого
 * до второго» не принадлежит ни одному из них — рёбра графа задач тестами не
 * покрыты вовсе.
 *
 * Дефект, ради которого файл заведён, прожил в продукте всё время его
 * существования: тело `POST /api/tasks` из визарда не содержало ни `surveyId`,
 * ни `questions`. Маршрут читает вопросы по `surveyId`, не получал его и
 * отправлял воркеру `survey: null`. Воркер на `null` идёт по пяти базовым
 * критериям — законный и описанный запасной путь. Поэтому ни один вопрос,
 * добавленный в конструкторе, никогда не был задан ни одной персоне, а прогон
 * при этом выглядел совершенно обычным.
 *
 * ─── Почему разбор исходника, а не вызов ──────────────────────────────────
 * Проверить это вызовом значит поднять браузер, пройти семь шагов визарда и
 * посмотреть, что ушло в сеть. Такая проверка не идёт в CI и не срабатывает в
 * момент внесения регрессии. Здесь читается тот самый литерал тела запроса —
 * то есть ровно то место, где поле пропало.
 *
 * Проверка намеренно грубая: она требует присутствия имени поля, а не
 * правильности значения. Значение проверяется поведенчески, на прогоне; имя
 * поля — единственное, что можно утверждать статически, и его отсутствие как
 * раз и было дефектом.
 */

const WIZARD = join(
  new URL("..", import.meta.url).pathname,
  "app",
  "studies",
  "new",
  "page.tsx",
);

const source = readFileSync(WIZARD, "utf8");

/**
 * Тело запроса на запуск — от `fetch("/api/tasks"` до конца объекта.
 *
 * Границы ищутся по скобкам, а не регуляркой на весь файл: в визарде четыре
 * вызова `fetch`, и совпадение с любым другим сделало бы тест зелёным по
 * ошибке.
 */
function launchBody(): string {
  const call = source.indexOf('fetch("/api/tasks"');
  assert.notEqual(call, -1, "в визарде нет вызова POST /api/tasks");
  const start = source.indexOf("JSON.stringify({", call);
  assert.notEqual(start, -1, "у вызова запуска нет тела JSON.stringify({…})");

  let depth = 0;
  for (let i = source.indexOf("{", start); i < source.length; i++) {
    if (source[i] === "{") depth++;
    else if (source[i] === "}") {
      depth--;
      if (depth === 0) return source.slice(start, i + 1);
    }
  }
  throw new Error("тело запроса не закрыто — разбор не удался");
}

test("визард отправляет анкету на запуск", async (t) => {
  const body = launchBody();

  await t.test("в теле запуска есть surveyId", () => {
    assert.match(
      body,
      /\bsurveyId\b/,
      "тело POST /api/tasks не содержит surveyId — маршрут читает вопросы " +
        "именно по нему, и без него воркер получает survey: null и молча идёт " +
        "по пяти базовым критериям",
    );
  });

  await t.test("поля, которые уже доезжали, не потерялись", () => {
    // Регрессия в обратную сторону: правка тела запроса ради анкеты не должна
    // выронить соседнее поле. Каждое из перечисленных однажды отсутствовало
    // и каждое отсутствовало молча.
    for (const field of [
      "mode",
      "videoRef",
      "personaSetId",
      "replicationCount",
      "audienceContext",
      "seed",
    ]) {
      assert.match(body, new RegExp(`\\b${field}\\b`), `тело запуска потеряло ${field}`);
    }
  });
});

test("маршрут запуска умеет принять surveyId", () => {
  // Вторая половина шва. Поле в теле запроса бессмысленно, если маршрут его не
  // читает; читающий маршрут бессмыслен, если поле не шлют. Разошлись бы они
  // так же молча, как разошлись в первый раз.
  const route = readFileSync(
    join(new URL("..", import.meta.url).pathname, "app", "api", "tasks", "route.ts"),
    "utf8",
  );
  assert.match(route, /\bsurveyId\b/, "POST /api/tasks не разбирает surveyId");
  assert.match(
    route,
    /FROM surveys/,
    "POST /api/tasks не читает вопросы из таблицы surveys",
  );
});
