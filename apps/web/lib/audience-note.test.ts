import assert from "node:assert/strict";
import { test } from "node:test";

import { audienceNote } from "./audience-note.ts";

/**
 * Подпись под составом аудитории.
 *
 * ─── Откуда взялась ────────────────────────────────────────────────────────
 * Владелец открыл отчёт, увидел три персоны там, где запускал двенадцать, и
 * решил, что прогон ненастоящий. Девять ответов забраковал QA — и это законная
 * работа проверки, — но на экране об этом не было ни слова: отчёт показывал
 * выживших и молчал, что показывает остаток.
 *
 * Число исключённых лежало в `qa_summary` и выводилось в подписи шапки мелким
 * шрифтом, далеко от самого списка. Там, где его ищут, его не было.
 */

test("без отбраковки лишнего не пишем", () => {
  const note = audienceNote({ shown: 12, surviving: 12, excludedByQa: 0 });
  assert.equal(note, null, `на пустом месте появилась подпись: ${note}`);
});

test("отбраковка названа числом и долей от запуска", () => {
  const note = audienceNote({ shown: 3, surviving: 3, excludedByQa: 9 });
  assert.ok(note, "подписи нет там, где исключены три четверти ответов");
  // Читатель должен увидеть все три числа: сколько было, сколько осталось,
  // сколько выброшено. Любое одно из них по отдельности вводит в заблуждение.
  assert.match(note!, /12/, `не сказано, сколько было всего: ${note}`);
  assert.match(note!, /3/, `не сказано, сколько осталось: ${note}`);
  assert.match(note!, /9/, `не сказано, сколько исключено: ${note}`);
});

test("подпись говорит, что это остаток, а не выборка", () => {
  const note = audienceNote({ shown: 3, surviving: 3, excludedByQa: 9 })!;
  assert.match(
    note,
    /исключ|отбрак|не прошл/i,
    `по тексту нельзя понять, что ответы выброшены проверкой: ${note}`,
  );
});

test("постраничный показ и отбраковка — разные вещи и не путаются", () => {
  // Двадцать выживших, показаны первые пять, восемь исключены. Три числа с
  // разным смыслом; слипшись, они дают «показаны 5 из 20» — и читатель решает,
  // что остальные пятнадцать просто ниже по странице.
  const note = audienceNote({ shown: 5, surviving: 20, excludedByQa: 8 })!;
  assert.match(note, /5/);
  assert.match(note, /20/);
  assert.match(note, /8/);
  assert.match(note, /28/, `не назван исходный размер запуска: ${note}`);
});

test("исключено всё — это отдельный случай, а не ноль в подписи", () => {
  // Пустой отчёт с подписью «показано 0 из 0» выглядит поломкой продукта.
  // Сказать надо прямо: проверку не прошёл ни один ответ.
  const note = audienceNote({ shown: 0, surviving: 0, excludedByQa: 12 })!;
  assert.match(note, /ни один|все 12|полностью/i, `невнятно на полном отказе: ${note}`);
});
