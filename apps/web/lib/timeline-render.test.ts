import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

/**
 * Список сцен рисуется весь сразу, хотя видно из него три ячейки.
 *
 * ─── Что замерено ─────────────────────────────────────────────────────────
 * 16.09.2026, боевой прогон 0091 (48 минут, 322 сцены), измерено в браузере:
 *
 *   ячеек в DOM            328
 *   ячеек видно              3
 *   картинок                322
 *   из них loading="lazy"     0
 *   последний кадр докачан  21.4 с
 *   узлов в списке         3711
 *
 * То есть браузер выкачивает 322 кадра, чтобы показать три. Остальные 319 —
 * это ~23 МБ трафика (замер по бакету: 864 кадра занимали 61.6 МБ) и 322
 * параллельных запроса к S3, которые душат сам ролик: после нажатия «play»
 * `readyState` держался в нуле, `currentTime` не сдвинулся за десять секунд.
 *
 * Пользователь при этом видит «Загружаем разбор материала…» — маршрут
 * `/api/tasks/{id}/timeline` отвечает за 877 мс, а ждать приходится десятки
 * секунд. Подпись не врёт про причину, она про неё просто молчит.
 *
 * ─── Три отдельные причины ────────────────────────────────────────────────
 * 1. Кадры запрашиваются жадно. Лечится `loading="lazy"` и явными размерами:
 *    без них браузер не знает, куда картинка ляжет, и не может отложить.
 * 2. Все 322 ячейки размечаются и красятся. Лечится `content-visibility`:
 *    браузер пропускает то, что за пределами прокрутки.
 * 3. `onTimeUpdate` меняет `currentSec` четыре раза в секунду, и каждая
 *    перерисовка проходит по всем 322 ячейкам заново — потому что `Cell` не
 *    мемоизирован, а `onSeek` создаётся заново на каждой ячейке каждый раз.
 *
 * Третья причина — самая коварная: она не видна на неподвижной странице и
 * появляется ровно тогда, когда человек нажимает «play», то есть выглядит
 * как дефект плеера.
 */

const WEB = new URL("..", import.meta.url).pathname;

function read(rel: string): string {
  const p = join(WEB, rel);
  return existsSync(p) ? readFileSync(p, "utf8") : "";
}

/** Без комментариев: разбор идёт по коду, а не по его объяснению. */
function code(text: string): string {
  return text
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

const src = code(read("components/agora/Timeline.tsx"));

// ─── Кадры грузятся по мере надобности ──────────────────────────────────────

test("кадр сцены грузится лениво и знает свой размер", () => {
  const img = /<img[\s\S]*?\/>/.exec(src)?.[0];
  assert.ok(img, "кадр сцены рисуется тегом img");

  assert.ok(
    /loading="lazy"/.test(img),
    "без loading=\"lazy\" браузер выкачивает все 322 кадра, чтобы показать три",
  );
  assert.ok(
    /width=\{?\d+\}?/.test(img) && /height=\{?\d+\}?/.test(img),
    "явные размеры обязательны: без них браузер не знает, куда ляжет картинка, и отложить её не может",
  );
});

// ─── Невидимые ячейки не размечаются ────────────────────────────────────────

test("ячейка вне прокрутки не размечается и не красится", () => {
  assert.ok(
    /content-visibility:\s*auto/.test(src),
    "content-visibility:auto даёт браузеру пропустить то, что за пределами прокрутки",
  );
  assert.ok(
    /contain-intrinsic-size:/.test(src),
    "без предполагаемой высоты полоса прокрутки прыгает при каждом измерении",
  );
});

// ─── Ход воспроизведения не перерисовывает весь список ──────────────────────

test("ячейка мемоизирована", () => {
  assert.ok(
    /\bmemo\(/.test(src),
    "без memo каждое движение ползунка перерисовывает все 322 ячейки",
  );
  assert.ok(
    /from "react"/.test(src) && /\bmemo\b/.test(src.split("\n").slice(0, 10).join("\n")),
    "memo импортирован из react",
  );
});

test("обработчик клика не создаётся заново на каждой ячейке", () => {
  // Встроенная стрелка в map возвращает новую функцию при каждой перерисовке,
  // и memo перестаёт что-либо значить: props всегда разные.
  const list = /<Cell[\s\S]*?\/>/.exec(src)?.[0] ?? "";
  assert.ok(list, "ячейки раздаются компонентом Cell");
  assert.ok(
    !/=\{\s*\(\)\s*=>/.test(list),
    `в props ячейки не должно быть встроенных стрелок: ${list.replace(/\s+/g, " ").slice(0, 160)}`,
  );

  assert.ok(
    /useCallback/.test(src),
    "перемотка передаётся стабильной ссылкой — иначе memo не работает",
  );
});

test("положение ползунка обновляется не чаще раза в секунду", () => {
  const handler = /onTimeUpdate=\{([\s\S]*?)\}\n/.exec(src)?.[1] ?? "";
  assert.ok(handler, "обработчик onTimeUpdate на месте");
  assert.ok(
    /Math\.floor|\|\s*0|Math\.trunc/.test(handler),
    `дробные секунды дают четыре перерисовки в секунду вместо одной: ${handler.replace(/\s+/g, " ")}`,
  );
});

test("подсветка ячейки считается по целым секундам", () => {
  // Если `active` считать по дробному времени, округление в обработчике не
  // поможет: значение всё равно будет меняться четырежды в секунду.
  assert.ok(
    /currentSec/.test(src),
    "текущая секунда хранится в состоянии",
  );
  const setter = /setCurrentSec\(([^)]*)\)/.exec(src)?.[1] ?? "";
  assert.ok(
    /Math\.floor|Math\.trunc/.test(setter),
    `в состояние кладётся целая секунда, а не дробная: setCurrentSec(${setter})`,
  );
});
