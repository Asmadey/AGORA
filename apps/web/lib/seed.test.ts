import assert from "node:assert/strict";
import { test } from "node:test";

import { MAX_SEED, resolveSeed } from "./seed.ts";

/**
 * Seed набора персон.
 *
 * ─── Что здесь чинится ────────────────────────────────────────────────────
 * Число 42 было зашито в трёх местах подряд: умолчание `GenerationConfig`,
 * умолчание маршрута `/api/audience` и отсутствие поля в теле запроса из
 * визарда. Следствие проверено на боевой базе: 134 персоны с seed 42, и три
 * набора по 12 персон с ОДИНАКОВЫМ списком имён. Владелец создавал одну и ту же
 * аудиторию заново, не зная об этом.
 *
 * ─── Почему seed всё-таки остаётся ────────────────────────────────────────
 * Он записывается в `persona_sets.seed`. Случайный по умолчанию, но
 * сохранённый — это не то же самое, что отсутствующий: набор можно
 * воспроизвести, если однажды понадобится объяснить, откуда взялась персона.
 * Явно переданный seed по-прежнему исполняется как есть — на этом держится
 * эталонный прогон.
 */

test("явный seed исполняется как передан", () => {
  assert.equal(resolveSeed(12345), 12345);
  assert.equal(resolveSeed(0), 0);
});

test("без seed берётся случайный, а не 42", () => {
  // Двадцать попыток: вероятность двадцати совпадений подряд у настоящего
  // генератора исчезающе мала, а зашитая константа провалит проверку сразу.
  const drawn = new Set<number>();
  for (let i = 0; i < 20; i += 1) drawn.add(resolveSeed(undefined));
  assert.ok(drawn.size > 1, `все двадцать попыток дали одно значение: ${[...drawn]}`);
  assert.ok(!(drawn.size === 1 && drawn.has(42)), "вернулось зашитое 42");
});

test("мусор вместо seed — тоже случайный, а не молча 42", () => {
  // Прежняя редакция подставляла 42 на любое непонятное значение. Отличить
  // «не передали» от «передали ерунду» по результату было нельзя.
  for (const bad of [-1, 1.5, "42", null, Number.NaN, {}]) {
    const value = resolveSeed(bad);
    assert.ok(Number.isInteger(value) && value >= 0, `для ${JSON.stringify(bad)} вернулось ${value}`);
  }
});

test("seed помещается в диапазон, который принимает генератор", () => {
  // GenerationConfig.validate() требует неотрицательное целое; на стороне
  // Python значение уедет в random.Random, а по дороге — через JSON. Держим
  // его в пределах int32, чтобы не зависеть от разрядности на другом конце.
  for (let i = 0; i < 200; i += 1) {
    const value = resolveSeed(undefined);
    assert.ok(value >= 0 && value <= MAX_SEED, `вне диапазона: ${value}`);
    assert.ok(Number.isInteger(value), `не целое: ${value}`);
  }
});
