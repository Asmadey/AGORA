import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

/**
 * Перестановка атрибутов на экране исследования (запрос владельца 16.09.2026).
 *
 * Пункты списка и что каждый значит:
 *
 * 1. «Время обработки» уезжает из панели показателей в полосу под плеером,
 *    рядом с «Длительностью». Это свойство ПРОГОНА, а не аудитории: в одном
 *    ряду с NPS оно читалось как показатель, который что-то говорит о людях.
 *    Полоса под плеером ровно для таких свойств и заведена.
 * 3. Плитка «Ценности ВЦИОМ» теряет подвал с пояснениями — владелец просил
 *    компактную плитку в высоту соседних.
 * 5. «Досмотрят до конца» и «Досмотрено» сводятся в одну карточку.
 * 7. Секция «Заданные вопросы» уходит с экрана: те же вопросы уже видны в
 *    развёрнутой карточке персоны, где рядом стоит ответ. (Пункт 6 — убрать
 *    подпись типа «scale» — этим и закрывается: подпись жила только здесь.)
 */

const WEB = new URL("..", import.meta.url).pathname;

function read(rel: string): string {
  const p = join(WEB, rel);
  return existsSync(p) ? readFileSync(p, "utf8") : "";
}

/** Без комментариев: разбор идёт по коду, а не по его объяснению. */
function code(text: string): string {
  return text
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

const body = code(read("components/agora/ReportBody.tsx"));
const timeline = code(read("components/agora/Timeline.tsx"));
const values = code(read("components/agora/ValuesChart.tsx"));
const runPage = code(read("app/runs/[id]/page.tsx"));
const sharePage = code(read("app/share/[token]/page.tsx"));

// ─── 1. Время обработки ─────────────────────────────────────────────────────

test("«Время обработки» больше не карточка панели показателей", () => {
  assert.ok(
    !/label="Время обработки"/.test(body),
    "плитки в сетке показателей нет",
  );
});

test("«Время обработки» стоит в полосе под плеером рядом с «Длительностью»", () => {
  assert.ok(
    /Время обработки/.test(timeline),
    "подпись переехала в Timeline",
  );
  const strip = /\[\s*\["Сцен"[\s\S]*?\]\s*\.map/.exec(timeline)?.[0] ?? "";
  assert.ok(strip, "полоса свойств материала собирается списком пар");
  assert.ok(
    strip.indexOf("Длительность") < strip.indexOf("Время обработки"),
    "«Время обработки» стоит ПРАВЕЕ «Длительности», как просил владелец",
  );
});

test("время приезжает в Timeline снаружи, а не считается внутри", () => {
  // Замер живёт в Postgres и читается на сервере. Второй запрос из клиента
  // ради той же величины разошёлся бы с шапкой при первом же расхождении.
  assert.ok(
    /processingSec/.test(timeline),
    "Timeline принимает замер отдельным props",
  );
  assert.ok(
    /processingSec=\{/.test(runPage),
    "страница прогона передаёт замер",
  );
});

test("на публичной странице времени по-прежнему нет", () => {
  // Публичная ссылка намеренно не показывает, сколько считался прогон: это
  // сведения о нашей кухне, а не о материале. Прежде это обеспечивалось тем,
  // что `timing` туда не передавали, — и обеспечиваться должно так же.
  const call = /<Timeline[\s\S]{0,200}?\/>/.exec(sharePage)?.[0] ?? "";
  assert.ok(call, "публичная страница рисует Timeline");
  assert.ok(
    !/processingSec/.test(call),
    `замер наружу не уходит: ${call.replace(/\s+/g, " ")}`,
  );
});

// ─── 3. Плитка ценностей ────────────────────────────────────────────────────

test("плитка ценностей лишилась подвала и разделителя", () => {
  assert.ok(!/Ещё \{outside\}/.test(values), "строки «Ещё N назначений» нет");
  assert.ok(
    !/несущих ценность/.test(values),
    "подписи «персон аудитории, несущих ценность · в перечне 17» нет",
  );
  assert.ok(
    !/border-t/.test(values),
    "разделителя над подвалом нет",
  );
});

// ─── 5. Просмотр одной карточкой ────────────────────────────────────────────

test("«Досмотрят до конца» и «Досмотрено» — один блок", () => {
  assert.ok(
    /Досмотрят до конца/.test(body) && /Досмотрено/.test(body),
    "обе величины остались: они разные, и одна другую не заменяет. " +
      "Первая считается по retention_intent, который категориален; вторая — " +
      "по шкальному вопросу анкеты. Свести их в одно число значило бы выдумать данные",
  );

  // Обе лежат внутри одного блока «Просмотр», а не в двух рамках рядом.
  const block = /Просмотр<\/p>[\s\S]*?<\/div>\s*<\/div>/.exec(body)?.[0] ?? "";
  assert.ok(block, "блок «Просмотр» есть");
  assert.ok(
    /Досмотрят до конца/.test(block) && /Досмотрено/.test(block),
    "обе величины внутри него",
  );
});

test("показатели больше не карточки каждый в своей рамке", () => {
  // Четыре величины отвечают на один вопрос — «как приняли материал». Каждая
  // в своей рамке читалась как отдельный сюжет.
  assert.ok(!/<StatCard\b/.test(body), "StatCard в сводке не используется");
  const group = /<Metric\b/g;
  assert.ok((body.match(group) ?? []).length >= 6, "величины рисуются примитивом Metric");
});

test("у каждого показателя есть попап «откуда число»", () => {
  assert.ok(/MetricInfo/.test(body), "попап подключён");
  const infoCalls = body.match(/info=\{info\(/g) ?? [];
  assert.ok(
    infoCalls.length >= 6,
    `пояснение заведено у всех показателей, а их ${infoCalls.length}`,
  );
});

test("попап не съедает последний шаг цепочки", () => {
  // У прежнего раскрытия было записанное обоснование: нажатие на таймкод
  // перематывает плеер, а плеер стоит выше на этой же странице. Диалог
  // перекрывает его собой — значит, должен уйти, когда таймкод нажали.
  const popup = code(read("components/agora/MetricInfo.tsx"));
  assert.ok(popup, "components/agora/MetricInfo.tsx существует");
  assert.ok(
    /#t=/.test(popup),
    "попап замечает нажатие на ссылку-таймкод",
  );
  assert.ok(
    /setOpen\(false\)/.test(popup),
    "и закрывается, чтобы перемотка была видна",
  );
});

// ─── 6 и 7. Заданные вопросы ────────────────────────────────────────────────

test("секции «Заданные вопросы» на экране нет", () => {
  assert.ok(
    !/Заданные вопросы/.test(body),
    "секция убрана: те же вопросы стоят в карточке персоны рядом с ответом",
  );
  assert.ok(
    !/\{q\.type\}/.test(body),
    "подпись типа вопроса («scale») ушла вместе с секцией",
  );
});

test("список заданных вопросов по-прежнему доезжает до карточек персон", () => {
  // Секция ушла, а данные нужны: `asked` задаёт ПОРЯДОК анкеты, и без него
  // карточка персоны не смогла бы показать вопрос, на который нет ответа.
  assert.ok(
    /asked=\{/.test(body),
    "PersonaAccordion по-прежнему получает asked",
  );
  assert.ok(
    /view\.asked/.test(body),
    "источник прежний — снимок survey_asked из отчёта",
  );
});
