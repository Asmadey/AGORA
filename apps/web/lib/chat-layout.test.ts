import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

/**
 * Чат выглядит и ведёт себя как чат (пункты 8 и 9 списка владельца).
 *
 * ─── Почему строка ввода уезжала вниз ─────────────────────────────────────
 * `ChatView` объявлен `flex h-full flex-col`, лента — `flex-1 overflow-y-auto`.
 * Разметка верная, но высоты у неё не было: страница чата оборачивала её в
 * `<div className="p-8">` без собственной высоты, а `<main>` — не флексбокс.
 * `h-full` при неопределённой высоте предка разрешается в `auto`, `flex-1`
 * тогда не ограничивает ничего, и лента растёт вместе с перепиской, унося
 * строку ввода вниз страницы. Внутренней прокрутки по той же причине не было:
 * `overflow-y-auto` на блоке, который сам под себя растёт, не срабатывает
 * никогда.
 *
 * Цепочка высот есть, просто она прерывалась на странице: `<main>` — это
 * растянутый элемент внутри `h-screen overflow-hidden`, то есть высота у него
 * определённая. Нужно лишь не терять её на пути к ленте.
 */

const WEB = new URL("..", import.meta.url).pathname;

function read(rel: string): string {
  const p = join(WEB, rel);
  return existsSync(p) ? readFileSync(p, "utf8") : "";
}

/** Без комментариев: разбор идёт по коду, а не по его объяснению. */
function code(text: string): string {
  return text
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

const view = code(read("components/agora/ChatView.tsx"));
const page = code(read("app/runs/[id]/chat/page.tsx"));
const typing = code(read("components/ui/typing-animation.tsx"));

// ─── 8. Строка ввода прижата к низу ─────────────────────────────────────────

test("страница чата отдаёт ленте определённую высоту", () => {
  assert.ok(
    /h-full/.test(page),
    "обёртка страницы берёт высоту <main>, а она определённая",
  );
  assert.ok(
    /min-h-0/.test(page),
    "min-h-0 обязателен: без него флекс-элемент не сжимается ниже содержимого, " +
      "и внутренняя прокрутка не включается — дефект возвращается молча",
  );
});

test("лента сжимается, а не держит пол в 24rem", () => {
  // `min-h-[24rem]` — это пол, и на невысоком экране он больше доступной
  // высоты. Тогда лента вылезает за низ, и строка ввода снова уезжает.
  assert.ok(
    !/min-h-\[24rem\]/.test(view),
    "жёсткого пола у ленты нет",
  );
  assert.ok(
    /min-h-0/.test(view) && /flex-1/.test(view),
    "лента занимает остаток и умеет сжиматься",
  );
});

test("кнопка «Спросить» выровнена по центру поля ввода", () => {
  const bar = /<div className="flex[^"]*gap-2"/.exec(view)?.[0] ?? "";
  assert.ok(bar, "строка ввода найдена");
  assert.ok(
    /items-center/.test(bar),
    `кнопка по центру, а не по нижнему краю: ${bar}`,
  );
});

// ─── 9. Внутренняя прокрутка и ожидание ────────────────────────────────────

test("прокручивается лента, а не страница", () => {
  assert.ok(
    /overflow-y-auto/.test(view),
    "у ленты своя полоса прокрутки",
  );
});

test("пока модель думает, в пузыре печатается «Думаю»", () => {
  assert.ok(typing, "components/ui/typing-animation.tsx существует");
  assert.ok(
    /TypingAnimation/.test(view),
    "пузырь ожидания использует печатающуюся строку",
  );
  assert.ok(
    /Думаю/.test(view),
    "по умолчанию написано «Думаю»",
  );
});

test("шаг конвейера не потерян ради красоты", () => {
  // Пока запрос идёт, сервер присылает шаг («ищу сцены» и подобное). Он
  // информативнее слова «Думаю», и заменять его целиком нельзя: это был бы
  // обмен сведений на анимацию.
  assert.ok(
    /step \?\? "Думаю"|step \?\?\s*\n?\s*"Думаю"/.test(view),
    "шаг показывается, когда известен, и «Думаю» — когда нет",
  );
});

test("индикатор печатает по кругу, а не замирает допечатав", () => {
  // Образец из запроса печатает один раз и останавливается. Остановившийся
  // индикатор не отличается от зависшего запроса — то есть возвращает ровно ту
  // неопределённость, ради которой заводился.
  assert.ok(
    /%/.test(typing),
    "счётчик букв идёт по кругу",
  );
  assert.ok(
    /setInterval/.test(typing) && /clearInterval/.test(typing),
    "таймер снимается при размонтировании",
  );
});

test("ширина пузыря не пляшет на каждой букве", () => {
  assert.ok(
    /invisible/.test(typing),
    "место держит невидимая копия полного текста, иначе дёргается вся лента",
  );
});
