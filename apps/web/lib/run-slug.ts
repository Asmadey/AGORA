/**
 * Адрес прогона: номер вместо UUID.
 *
 * ─── Что просил владелец ──────────────────────────────────────────────────
 * «Сейчас по сути есть два идентификатора: длинный id и номер в заголовке
 * (№ 0050). Я хочу, чтобы был 1 порядковый номер, и это — № 0050.
 * Соответственно, в слаг должен быть номер 0050.»
 *
 * ─── Почему UUID продолжает приниматься ───────────────────────────────────
 * Ссылки вида /runs/e0dd6c3a-… уже разошлись по переписке и лежат в истории
 * браузера. Перестав их понимать, продукт сломал бы то, что человек считал
 * сохранённым. Маршрут принимает оба вида и на UUID отвечает постоянным
 * перенаправлением на номер: адрес приходит в порядок сам, без просьб
 * «обновите закладку».
 *
 * ─── Почему разбор отдельно от обращения к базе ───────────────────────────
 * Строка приходит из адреса, то есть от кого угодно. Отсеять непригодное надо
 * ДО запроса: «сначала спросим, потом проверим» — это лишний повод ошибиться в
 * месте, где ошибка стоит утечки между арендаторами.
 */

/** До скольких знаков дополняется номер. Столько же в заголовке: «№ 0050». */
export const RUN_SLUG_PAD = 4;

/** Разумный потолок разрядности. Двадцать девяток теряют точность в number. */
const MAX_DIGITS = 9;

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const NUMBER = /^\d+$/;

export type RunRef =
  | { kind: "uuid"; id: string }
  | { kind: "number"; seqNo: number };

/**
 * Что перед нами — номер, идентификатор или мусор.
 *
 * `null` означает «ни то, ни другое»: вызывающий обязан ответить 404, не
 * обращаясь к базе.
 */
export function parseRunSlug(slug: string): RunRef | null {
  const text = String(slug ?? "").trim();

  if (UUID.test(text)) {
    // Регистр приводится к нижнему: адрес мог быть скопирован из письма, где
    // почтовик поднял регистр, а в базе UUID хранится в нижнем.
    return { kind: "uuid", id: text.toLowerCase() };
  }

  if (NUMBER.test(text) && text.length <= MAX_DIGITS) {
    const seqNo = Number(text);
    // Ноль не номер: нумерация начинается с единицы, и «/runs/0» — это либо
    // опечатка, либо попытка нащупать границы.
    if (seqNo >= 1) return { kind: "number", seqNo };
  }

  return null;
}

/**
 * Номер в виде, пригодном для адреса.
 *
 * Дополнение нулями — украшение ради узнаваемости: в заголовке «№ 0050», и в
 * адресе должно быть 0050, иначе человек не свяжет одно с другим. Обрезки нет:
 * у команды с десятью тысячами прогонов адрес обязан остаться правильным.
 */
export function runSlug(seqNo: number): string {
  return String(seqNo).padStart(RUN_SLUG_PAD, "0");
}
