import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

/**
 * Плеер не меняет размер при нажатии «play», а плашка не торчит из-под него.
 *
 * ─── Что замерено на боевом 16.09.2026 (прогон 0091) ──────────────────────
 * До нажатия «play»:
 *
 *     readyState .............. 0     (HAVE_NOTHING)
 *     videoWidth × videoHeight  0 × 0
 *     постер .................. 512 × 214
 *     коробка <video> ......... 514 × 216   ← постер плюс рамка
 *     коробка плашки .......... 744 × 600
 *
 * `preload="metadata"` стоит, а метаданных нет: при заданном `poster` Chrome
 * их не грузит — постера ему достаточно, чтобы что-то показать. Поэтому
 * элемент берёт СОБСТВЕННЫЙ размер ПОСТЕРА, а не ролика.
 *
 * Нажатие «play» наконец загружает метаданные, `videoWidth/videoHeight`
 * становятся настоящими, и под `max-h-[600px] w-auto max-w-full` элемент
 * пересчитывается по пропорциям РОЛИКА. Отсюда скачок, который видел владелец.
 *
 * Отсюда же и вторая половина жалобы: плашка 744 px вокруг ролика 514 px.
 * Причина одна — коробку никто не задал, и она следует за тем, что сейчас
 * оказалось внутри: сначала постер, потом ролик.
 *
 * ─── Чем чиним ────────────────────────────────────────────────────────────
 * Коробке задаются ПРОПОРЦИИ, а ролик внутри — `object-contain`. Тогда постер
 * вписывается в готовую коробку вместо того, чтобы её задавать, и загрузка
 * метаданных ничего не двигает. Пропорции берутся из постера (он кадр того же
 * ролика) и уточняются по метаданным, когда те придут.
 */

const WEB = new URL("..", import.meta.url).pathname;

function read(rel: string): string {
  const p = join(WEB, rel);
  return existsSync(p) ? readFileSync(p, "utf8") : "";
}

/** Без комментариев: разбор идёт по коду, а не по его объяснению. */
function code(text: string): string {
  return text
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

const src = code(read("components/agora/Timeline.tsx"));

test("коробка плеера задана пропорциями, а не содержимым", () => {
  assert.ok(
    /aspectRatio/.test(src),
    "у обёртки ролика есть заданное соотношение сторон",
  );
  assert.ok(
    /object-contain/.test(src),
    "ролик и постер вписываются в коробку, а не задают её",
  );
});

test("размер не зависит от того, загрузились ли метаданные", () => {
  // Ровно тот дефект, который видел владелец: до «play» размер один, после —
  // другой. Пропорции обязаны быть известны ДО загрузки метаданных.
  assert.ok(
    /onLoadedMetadata/.test(src),
    "метаданные уточняют пропорции, когда приходят",
  );
  assert.ok(
    /videoWidth/.test(src) && /videoHeight/.test(src),
    "уточнение берётся из собственного размера ролика",
  );
  assert.ok(
    !/\bw-auto\b/.test(src),
    "`w-auto` убран: именно он давал ширину по содержимому",
  );
});

test("постер задаёт первую догадку о пропорциях", () => {
  // Постер — кадр этого же ролика, значит его пропорции и есть пропорции
  // ролика. Умолчание 16:9 до загрузки постера оставило бы скачок на роликах
  // другого формата — а вертикальные у нас бывают.
  assert.ok(
    /naturalWidth/.test(src),
    "пропорции постера замеряются",
  );
});

test("колонка плеера поджата по его ширине", () => {
  const grid = /grid gap-4 lg:grid-cols-\[[^\]]+\]/.exec(src)?.[0] ?? "";
  assert.ok(grid === "" || !/minmax\(0,1fr\)_minmax\(22rem,40rem\)/.test(grid),
    `прежняя раскладка заменена: ${grid}`);
  assert.ok(
    /--player/.test(src),
    "ширина колонки считается от плеера, а не назначается на глаз",
  );
});

test("плеер не съедает всю ширину, даже если просит", () => {
  // Замерено на боевом 16.09.2026: у ролика прогона 0091 пропорции 2.393, и при
  // 600 px высоты он просит 1436 px — больше всей области содержимого. Без
  // потолка по ДОЛЕ ширины разбор сцен получал свой минимум в 22rem вместо
  // «оставшегося пространства», которое владелец и просил ему отдать.
  //
  // Потолка высоты для этого мало: он ограничивает высоту, а ширина при широких
  // пропорциях уходит за экран сама.
  assert.ok(
    /PLAYER_WIDTH_SHARE/.test(src),
    "доля ширины задана именованной постоянной",
  );
  assert.ok(
    /min\(/.test(src),
    "ширина колонки — меньшее из собственной ширины плеера и доли",
  );
});

test("остаток ширины достаётся разбору сцен", () => {
  // Владелец просил отдать освободившееся место списку сцен: там описания и
  // реплики, и им ширина нужна, а плееру сверх его пропорций — нет.
  const grid = /lg:grid-cols-\[([^\]]+)\]/.exec(src)?.[1] ?? "";
  assert.ok(grid, "раскладка в две колонки на широком экране");
  const [left, right] = grid.split("_");
  assert.ok(/--player/.test(left), `левая колонка считается от плеера: ${left}`);
  assert.ok(/1fr/.test(right), `правая берёт остаток: ${right}`);
});

test("вертикальный ролик по-прежнему не уезжает на три экрана", () => {
  // Охранная проверка: потолок высоты стоял ради роликов 9:16, и потерять его
  // при перестановке легко — а заметно это станет только на вертикальном
  // материале, которого под рукой может не оказаться.
  assert.ok(
    /max-h-\[600px\]|maxHeight/.test(src),
    "потолок высоты сохранён",
  );
});
