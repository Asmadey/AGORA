/**
 * Выгрузка ответов прогона в Excel — адрес, имя файла и заголовки.
 *
 * ─── Почему отдельный модуль, а не строки по месту ─────────────────────────
 * Имя файла и тип содержимого назначаются в двух местах: маршрут ставит их в
 * заголовки ответа, меню — в ссылку. Разойдясь, они дают книгу, которую
 * браузер показывает текстом вместо того, чтобы сохранить, — и выглядит это
 * как испорченный файл, а не как разошедшиеся строки.
 *
 * Сюда же вынесено то, что вообще можно проверить тестом: `npm test` собирает
 * только `lib/**`, и логика, оставленная в `.tsx` или в маршруте, не
 * проверяется ничем.
 *
 * ─── Книгу собирает воркер ─────────────────────────────────────────────────
 * §6 запрещает нативные npm-модули в `apps/web`. Здесь нет и не должно быть
 * сборщика xlsx: форма книги описана один раз, на Python
 * (`agent_core/analytics/excel_export.py`), и вторая её реализация разошлась
 * бы с первой молча.
 */

/** MIME-тип xlsx. Тот же, что у воркера (`analytics/excel_download.py`). */
export const EXCEL_MEDIA_TYPE =
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet";

/** Адрес выгрузки для меню скачивания. */
export function excelHref(runId: string): string {
  return `/api/tasks/${runId}/excel`;
}

/**
 * Имя файла в «Загрузках».
 *
 * Прогон назван в имени по той же причине, что у расшифровки и отчёта: два
 * исследования, скачанных подряд, иначе отличаются только временем файла.
 */
export function excelFileName(runId: string): string {
  return `answers-${runId}.xlsx`;
}

/** Заголовок, по которому браузер сохраняет файл, а не открывает его. */
export function excelDisposition(runId: string): string {
  return `attachment; filename="${excelFileName(runId)}"`;
}

/**
 * Отказ службы сборки — текстом, называющим, куда смотреть.
 *
 * «Ошибка 502» отправляет читающего в исходники веба, где ничего нет: книгу
 * собирает другой контейнер, и поднят ли он — первое, что надо проверить.
 */
export function excelUpstreamError(status: number, detail: string): string {
  const tail = detail.trim().slice(0, 200);
  return (
    `служба выгрузки ответила ${status}. ` +
    (tail ? `${tail}. ` : "") +
    "Проверьте, поднят ли контейнер agent-api."
  );
}
