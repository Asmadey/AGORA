/**
 * Заголовок исследования.
 *
 * ─── Почему три источника, а не один ────────────────────────────────────────
 * Название, данное человеком, отвечает на вопрос «зачем делали». Имя файла —
 * факт о загрузке. Ключ S3 — внутренность, которая попала на экран по
 * недосмотру: владелец увидел в списке исследований заголовок
 * `tenants/de15d1e3-…/uploads/f77c2e53-….mp4`.
 *
 * Хранятся они порознь намеренно. Переименовав исследование в «Ролик для ВК,
 * апрель», человек стёр бы единственную запись о том, какой файл залит, — а она
 * нужна ровно тогда, когда название дали общее.
 *
 * ─── Почему функцией, а не выражением на месте ─────────────────────────────
 * Порядок нужен в трёх местах: список, шапка прогона и заголовок вкладки.
 * Разъехавшись, они дали бы разные названия одному прогону на соседних экранах —
 * и увидеть это можно было бы, только открыв оба.
 */

export const MAX_TITLE = 200;

/** Когда неизвестно вообще ничего. Пустой заголовок выглядит как битый прогон. */
export const UNTITLED = "Прогон без материала";

export interface ResearchNaming {
  title?: string | null;
  sourceName?: string | null;
  videoRef?: string | null;
}

export function researchTitle(task: ResearchNaming): string {
  const own = (task.title ?? "").trim();
  if (own) return own;
  const file = (task.sourceName ?? "").trim();
  if (file) return file;
  const ref = (task.videoRef ?? "").trim();
  if (ref) return ref;
  return UNTITLED;
}

/**
 * Название из формы в пригодный для записи вид.
 *
 * `null` означает «названия нет» — законное состояние: человек мог стереть
 * поле, и тогда заголовок возвращается к имени файла.
 *
 * Слишком длинное ОТВЕРГАЕТСЯ, а не обрезается. Обрезка — это правка чужого
 * текста без ведома автора: человек видит на экране одно, а сохраняется другое,
 * и узнаёт он об этом при следующем открытии страницы.
 */
export function normalizeTitle(input: unknown): string | null {
  const text = String(input ?? "").trim();
  if (!text) return null;
  if (text.length > MAX_TITLE) {
    throw new Error(`Название длиннее ${MAX_TITLE} символов`);
  }
  return text;
}
