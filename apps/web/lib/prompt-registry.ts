/**
 * Реестр промптов (задача #26) — чтение seed-версий с диска.
 *
 * ЭТАП 1 из 2. Источником истины должна стать таблица prompts с версиями,
 * is_active и is_default (acceptance задачи #26), но сами тексты уже существуют
 * в prompts/*.md, и это настоящие файлы, а не макет. Поэтому просмотр промпта
 * работает сегодня и показывает то, что реально уйдёт в модель.
 *
 * Чего здесь ещё нет и не может быть до БД: редактирование, версии, переключение
 * активной версии, restore default, dry-run. Всё это операции над строками
 * таблицы, а не над файлами: править seed-файлы из интерфейса означало бы
 * менять дефолт для всех арендаторов сразу и терять возможность откатиться.
 */

export interface PromptMeta {
  key: string;
  stage: string;
  /** Одна строка для списка. */
  desc: string;
  /** Что промпт делает и почему так — для карточки. Абзацы. */
  about: string[];
  /** Что подставляется в шаблон. Имена совпадают с `{{...}}` в файле. */
  inputs: string;
  /** Что модель обязана вернуть. По этому формату разбирает воркер. */
  output: string;
  /** Кто вызывает: модуль воркера. Пусто — промпт ещё не подключён. */
  calledBy: string;
  /**
   * Почему промпт не вызывается никем.
   *
   * Отсутствие поля означает «вызывается». Заведено потому, что промпт в
   * реестре без вызова неотличим от рабочего: студия предлагает его править, а
   * непоявившийся эффект правки читается как её собственный дефект. Пустой
   * `calledBy` эту роль не выполнял — он одинаково выглядит и у забытого
   * промпта, и у намеренно неиспользуемого.
   */
  unused?: string;
}

