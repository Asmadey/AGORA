import { createHash, randomBytes } from "node:crypto";

/**
 * Выпуск и отпечаток токена публичной ссылки (#29).
 *
 * ─── Почему отдельно от lib/share.ts ──────────────────────────────────────
 * `node:crypto` нельзя тянуть в клиентский бандл: диалог «Поделиться» —
 * клиентский компонент, и импорт списка сроков жизни утаскивал бы за собой
 * весь модуль. Сборка на этом падает с UnhandledSchemeError — и это лучший из
 * возможных исходов: молча уехавший в браузер серверный код был бы хуже.
 *
 * ─── Почему токен выпускает сервер ────────────────────────────────────────
 * `Math.random` не криптографический: последовательность предсказуема по
 * нескольким выданным значениям. Для ссылки, открывающей отчёт БЕЗ входа в
 * систему, это то же самое, что открытый доступ. Прежний диалог собирал токен
 * именно так — четырьмя вызовами Math.random в браузере.
 *
 * ─── Почему в базу идёт хеш ───────────────────────────────────────────────
 * Так заведена схема: `report_shares.token_hash`, а политика читает
 * `app.current_share_token_hash()` — SHA-256 от `app.share_token` в hex.
 * Утечка дампа базы не даёт доступа к отчётам.
 */

/** Сколько байт энтропии в токене. 32 — как у ключа сессии. */
const TOKEN_BYTES = 32;

export function newToken(): string {
  return randomBytes(TOKEN_BYTES).toString("base64url");
}

/** SHA-256 в hex — ровно то, что считает `app.current_share_token_hash()`. */
export function hashToken(token: string): string {
  return createHash("sha256").update(token).digest("hex");
}
