import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

import { sceneColumnShare, MIN_SHARE, MAX_SHARE } from "./timeline-columns.ts";

/**
 * Ширина колонок таймлайна считается по содержимому пакета.
 *
 * ─── Что было ─────────────────────────────────────────────────────────────
 * `grid-cols-[minmax(0,7fr)_minmax(0,9fr)]` — число, выбранное однажды на глаз.
 * Замерено на боевом (прогон 0091, 16.09.2026):
 *
 *     колонка «Сцена» ......... 227.5 px (под текст 135)
 *     колонка «Речь» .......... 292.5 px
 *     знаков в строке описания . 15
 *     описание 139 знаков ...... 10 строк
 *     высота ячейки ............ 236 px (медиана)
 *
 * А в пакете:
 *
 *     описания сцен ... 77 % текста, есть в 322 из 322 ячеек, медиана 139
 *     речь ............ 23 % текста, ОТСУТСТВУЕТ в 186 из 322 ячеек
 *
 * То есть более широкая колонка несёт меньше четверти текста и пуста в 58 %
 * строк, а колонка с тремя четвертями текста сжата до пятнадцати знаков в
 * строку. На 322 ячейках это ≈ 76 000 px прокрутки в окне высотой 600.
 *
 * ─── Почему не просто «доля текста» ───────────────────────────────────────
 * Отдать колонкам 77/23 было бы такой же ошибкой, только в другую сторону.
 * Высоту СТРОКИ задаёт та из двух колонок, что выше, а 186 ячеек без речи в
 * долю текста попадают и тянут её к описаниям. В ячейке, где речь всё-таки
 * есть, узкая колонка речи вырастет выше описания, и строка станет выше, чем
 * была.
 *
 * Поэтому считается не доля текста, а суммарная высота: перебор долей и выбор
 * той, при которой лента короче всего. Это ровно та величина, ради которой всё
 * и затевалось.
 */

// ─── Поведение расчёта ──────────────────────────────────────────────────────

/** Ячейка: описание сцены и реплики. */
function cell(scene: string | null, ...lines: string[]) {
  return { scene, lines: lines.map((text) => ({ text })) };
}

const text = (n: number) => "ы".repeat(n);

test("перекос в сторону описаний отдаёт описаниям больше места", () => {
  // Слепок прогона 0091 по форме: длинные описания везде, речь в меньшинстве
  // ячеек.
  const cells = [
    ...Array.from({ length: 186 }, () => cell(text(139))),
    ...Array.from({ length: 136 }, () => cell(text(139), text(102))),
  ];
  const share = sceneColumnShare(cells);
  assert.ok(share > 0.5, `описаниям достаётся больше половины, получено ${share}`);
});

test("разговорный ролик двигает пропорцию в другую сторону", () => {
  // Обратный случай: короткие описания, много речи в каждой ячейке. Прибитое
  // число ошиблось бы здесь ровно так же, как сегодня ошибается на 0091.
  const cells = Array.from({ length: 200 }, () => cell(text(40), text(300)));
  const share = sceneColumnShare(cells);
  assert.ok(share < 0.5, `речи достаётся больше половины, получено ${share}`);
});

test("пропорция не выходит за границы, при которых колонка нечитаема", () => {
  // Пакет вообще без речи дал бы 100/0, и заголовок «РЕЧЬ» повис бы над
  // колонкой нулевой ширины. Пустая колонка — это не «речи нет», это сломанная
  // разметка.
  const немаяЛента = Array.from({ length: 50 }, () => cell(text(200)));
  const однаРечь = Array.from({ length: 50 }, () => cell(null, text(200)));
  for (const [имя, cells] of [["без речи", немаяЛента], ["без описаний", однаРечь]] as const) {
    const s = sceneColumnShare(cells);
    assert.ok(s >= MIN_SHARE && s <= MAX_SHARE, `${имя}: ${s} вне [${MIN_SHARE}, ${MAX_SHARE}]`);
  }
});

test("выигрыш в прокрутке не покупается нечитаемым соседом", () => {
  // Перебор минимизирует суммарную высоту и ради этого охотно сожмёт соседнюю
  // колонку до ленты в два слова. На составе 0091 без порога он выбирал 0.72:
  // лента короче на 36 %, но речи оставалось 150 px — 16 знаков в строку, то
  // есть ровно то, за что забракована прежняя вёрстка.
  const AREA = 536;
  const PREVIEW = 80;
  const GAP = 12;
  const CHARS_PER_PX = 15 / 135;
  const MIN_CHARS = 18;

  const cells = [
    ...Array.from({ length: 186 }, () => cell(text(139))),
    ...Array.from({ length: 136 }, () => cell(text(139), text(102))),
  ];
  const share = sceneColumnShare(cells, AREA);

  const speechPx = (1 - share) * AREA;
  const descPx = share * AREA - PREVIEW - GAP;
  assert.ok(
    speechPx * CHARS_PER_PX >= MIN_CHARS,
    `в колонке речи ${Math.round(speechPx * CHARS_PER_PX)} знаков в строке, нужно ${MIN_CHARS}`,
  );
  assert.ok(
    descPx * CHARS_PER_PX >= MIN_CHARS,
    `в колонке описания ${Math.round(descPx * CHARS_PER_PX)} знаков в строке, нужно ${MIN_CHARS}`,
  );
});

test("к пустой колонке порог читаемости не применяется", () => {
  // В колонке, где ни в одной ячейке ничего нет, читать нечего. Требовать от
  // неё ширины значило бы отнимать место у той, где текст есть.
  const немаяЛента = Array.from({ length: 50 }, () => cell(text(200)));
  assert.ok(
    sceneColumnShare(немаяЛента) > 0.6,
    "без речи описание забирает почти всё, упираясь только в MAX_SHARE",
  );
});

test("пустой пакет не роняет расчёт и не даёт NaN", () => {
  for (const cells of [[], [cell(null)], [cell("")]]) {
    const s = sceneColumnShare(cells);
    assert.ok(Number.isFinite(s), `получено ${s}`);
    assert.ok(s >= MIN_SHARE && s <= MAX_SHARE, `получено ${s}`);
  }
});

test("расчёт не зависит от числа ячеек, только от их состава", () => {
  // Удвоение ленты не меняет пропорцию: иначе длинный ролик и короткий с тем
  // же материалом верстались бы по-разному без всякой причины.
  const one = Array.from({ length: 30 }, () => cell(text(139), text(102)));
  assert.equal(sceneColumnShare(one), sceneColumnShare([...one, ...one]));
});

test("на настоящем составе 0091 описанию достаётся заметно больше прежнего", () => {
  // Прежнее деление — 7/16 = 0.4375. Ради чего всё и делается.
  const cells = [
    ...Array.from({ length: 186 }, () => cell(text(139))),
    ...Array.from({ length: 136 }, () => cell(text(139), text(102))),
  ];
  assert.ok(
    sceneColumnShare(cells) > 0.4375,
    "иначе правка не меняет ничего на том прогоне, с которого начали",
  );
});

// ─── Разметка ───────────────────────────────────────────────────────────────

const WEB = new URL("..", import.meta.url).pathname;

function read(rel: string): string {
  const p = join(WEB, rel);
  return existsSync(p) ? readFileSync(p, "utf8") : "";
}

/** Без комментариев: разбор идёт по коду, а не по его объяснению. */
function code(t: string): string {
  return t
    .replace(/\{\s*\/\*[\s\S]*?\*\/\s*\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "");
}

const src = code(read("components/agora/Timeline.tsx"));

test("прибитого 7fr/9fr в разметке больше нет", () => {
  assert.ok(
    !/7fr|9fr/.test(src),
    "пропорция больше не выбрана на глаз",
  );
  assert.ok(/sceneColumnShare/.test(src), "она считается по пакету");
});

test("доли приезжают в ячейку стабильной ссылкой", () => {
  // `Cell` мемоизирован. Объект стилей, пересобранный на каждом рисовании, —
  // это новые props: все 322 ячейки перерисовывались бы на каждой смене
  // текущей секунды. Ровно та же ловушка, что с `onSeek`, и отказ такой же
  // тихий — экран верный, просто тяжёлый.
  assert.ok(
    /const columns = useMemo\(/.test(src),
    "объект стилей запомнен, а не пересобран",
  );
  assert.ok(
    /columns=\{columns\}/.test(src),
    "и передан ячейке отдельным props",
  );
});

test("доли считаются до ранних возвратов", () => {
  // В компоненте три `return` на ошибку, загрузку и пустой таймлайн. Хук после
  // них вызывался бы не на каждом рисовании, и порядок хуков поехал бы. На
  // этом здесь уже споткнулись с `useCallback`.
  const share = src.indexOf("const share = useMemo");
  const firstReturn = src.search(/\n  if \([\s\S]{0,80}?\{\s*\n\s*return/);
  assert.ok(share > 0, "расчёт долей на месте");
  assert.ok(firstReturn > 0, "ранние возвраты на месте");
  assert.ok(share < firstReturn, "расчёт стоит ВЫШЕ первого раннего возврата");
});

test("шапка и ячейка делят ширину ОДНОЙ величиной", () => {
  // Два места с одинаковым числом — это два места, которые разойдутся. Тогда
  // заголовок «РЕЧЬ» встанет не над своей колонкой, и заметить это можно будет
  // только глазом.
  const defs = src.match(/gridTemplateColumns/g) ?? [];
  assert.equal(defs.length, 1, `доли объявлены В ОДНОМ месте, найдено ${defs.length}`);

  const uses = src.match(/style=\{columns\}/g) ?? [];
  assert.equal(uses.length, 2, `обе сетки берут их оттуда, найдено ${uses.length}`);

  const literals = src.match(/grid-cols-\[minmax\(0,\d+fr\)/g) ?? [];
  assert.equal(literals.length, 0, `постоянных долей не осталось: ${literals.join(", ")}`);
});
