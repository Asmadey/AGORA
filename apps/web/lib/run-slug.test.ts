import assert from "node:assert/strict";
import { test } from "node:test";

import { RUN_SLUG_PAD, parseRunSlug, runSlug } from "./run-slug.ts";

/**
 * Адрес прогона: номер вместо UUID.
 *
 * ─── Что просил владелец ──────────────────────────────────────────────────
 * «Сейчас по сути есть два идентификатора: длинный id
 * (e0dd6c3a-3355-4931-8cc1-8b17657f7d86) и номер в заголовке (№ 0050). Я хочу,
 * чтобы был 1 порядковый номер, и это — № 0050. Соответственно, в слаг должен
 * быть номер 0050 вместо e0dd6c3a-…»
 *
 * ─── Почему UUID всё-таки принимается ─────────────────────────────────────
 * Ссылки вида /runs/e0dd6c3a-… уже разошлись по переписке и лежат в истории
 * браузера. Перестав их понимать, продукт сломал бы то, что человек считал
 * сохранённым. Поэтому маршрут принимает оба вида, а на UUID отвечает
 * постоянным перенаправлением на номер — так адрес в строке приходит в порядок
 * сам, без просьб «обновите закладку».
 */

test("номер разбирается с ведущими нулями и без", () => {
  assert.deepEqual(parseRunSlug("0050"), { kind: "number", seqNo: 50 });
  assert.deepEqual(parseRunSlug("50"), { kind: "number", seqNo: 50 });
  assert.deepEqual(parseRunSlug("1"), { kind: "number", seqNo: 1 });
});

test("UUID разбирается как UUID, а не как мусор", () => {
  const id = "e0dd6c3a-3355-4931-8cc1-8b17657f7d86";
  assert.deepEqual(parseRunSlug(id), { kind: "uuid", id });
});

test("UUID в верхнем регистре тоже UUID", () => {
  // Адрес мог быть скопирован из письма, где почтовик поднял регистр.
  const id = "E0DD6C3A-3355-4931-8CC1-8B17657F7D86";
  assert.deepEqual(parseRunSlug(id), { kind: "uuid", id: id.toLowerCase() });
});

test("непохожее ни на то, ни на другое отвергается", () => {
  // Важно отвергнуть ДО обращения к базе: строка из адреса уедет в запрос, и
  // «сначала спросим, потом проверим» — это лишний повод для ошибки.
  for (const bad of ["", "0050a", "abc", "-1", "1.5", "№ 0050", "../../etc", "0x32"]) {
    assert.equal(parseRunSlug(bad), null, `принято непригодное: ${JSON.stringify(bad)}`);
  }
});

test("ноль не номер: нумерация начинается с единицы", () => {
  assert.equal(parseRunSlug("0"), null);
  assert.equal(parseRunSlug("0000"), null);
});

test("слишком длинное число отвергается, а не переполняется", () => {
  // Без границы строка из двадцати девяток превращается в число, теряющее
  // точность, и запрос уходит с уже неверным значением.
  assert.equal(parseRunSlug("9".repeat(20)), null);
});

test("runSlug даёт тот же вид, что и номер в заголовке", () => {
  // Заголовок показывает «№ 0050» — в адресе обязано быть 0050, иначе человек
  // не свяжет одно с другим.
  assert.equal(runSlug(50), "0050");
  assert.equal(runSlug(1), "0001");
  assert.equal(String(RUN_SLUG_PAD), "4");
});

test("номер длиннее четырёх знаков не обрезается", () => {
  // Дополнение нулями — украшение, а обрезка была бы потерей: у команды с
  // десятью тысячами прогонов адрес обязан остаться правильным.
  assert.equal(runSlug(12345), "12345");
});

test("разбор и сборка — обратны друг другу", () => {
  for (const n of [1, 7, 50, 999, 1000, 12345]) {
    assert.deepEqual(parseRunSlug(runSlug(n)), { kind: "number", seqNo: n });
  }
});
