/**
 * Подпись под составом аудитории: сколько ответов дошло до отчёта.
 *
 * ─── Зачем ────────────────────────────────────────────────────────────────
 * Владелец запустил двенадцать персон, открыл отчёт, увидел три и решил, что
 * прогон ненастоящий. Девять ответов забраковал QA — это законная работа
 * проверки, — но на экране об этом не было ни слова. Отчёт показывал выживших и
 * молчал, что показывает остаток.
 *
 * Число исключённых лежало в `qa_summary` и попадало мелким шрифтом в подпись
 * шапки. Там, где его ищут — рядом со списком персон, — его не было.
 *
 * ─── Почему три числа, а не одно ──────────────────────────────────────────
 * «Показано 3» — неполно. «Исключено 9» — тоже: непонятно, из скольких.
 * Читателю нужно сопоставить запуск с результатом, а для этого нужны оба конца
 * и разница между ними.
 *
 * Отдельно разводятся постраничный показ и отбраковка. Слипшись, они дают
 * «показаны 5 из 20», и читатель решает, что остальные пятнадцать просто ниже
 * по странице.
 */

export interface AudienceCounts {
  /** Сколько строк на экране прямо сейчас (первая страница). */
  shown: number;
  /** Сколько ответов дошло до отчёта. */
  surviving: number;
  /** Сколько забраковано проверкой. */
  excludedByQa: number;
}

/**
 * Текст подписи или `null`, когда говорить нечего.
 *
 * `null`, а не пустая строка: пустая строка отрисовалась бы пустым абзацем с
 * отступами, и под списком появился бы необъяснимый зазор.
 */
export function audienceNote({
  shown,
  surviving,
  excludedByQa,
}: AudienceCounts): string | null {
  // Без отбраковки подпись про неё не нужна вовсе: сообщение «исключено 0»
  // заставляет искать проблему там, где её нет.
  if (excludedByQa <= 0) return null;

  const launched = surviving + excludedByQa;

  // Полный отказ — отдельный случай. «Показано 0 из 0» читается как поломка
  // продукта, а произошло другое: проверка не пропустила ни одного ответа, и
  // это вывод о прогоне, а не об интерфейсе.
  if (surviving === 0) {
    return (
      `Проверку не прошёл ни один ответ: все ${launched} исключены QA. ` +
      `Отчёт собран без ответов персон — смотрите причины отбраковки в прогрессе прогона.`
    );
  }

  const head =
    shown < surviving
      ? `Показаны первые ${shown} из ${surviving} ответов, дошедших до отчёта`
      : `${surviving} ${plural(surviving, "ответ", "ответа", "ответов")} из ${launched} дошли до отчёта`;

  return (
    `${head}. ${excludedByQa} ` +
    `${plural(excludedByQa, "ответ", "ответа", "ответов")} из ${launched} ` +
    `исключены проверкой QA — это не потеря данных, а отбраковка: ` +
    `персона сослалась на то, чего в ролике нет.`
  );
}

/** Русское склонение после числа. Без него подпись читается как машинная. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  const mod10 = n % 10;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}
