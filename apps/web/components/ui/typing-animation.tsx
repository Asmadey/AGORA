"use client";

import { useEffect, useState } from "react";

import { cn } from "@/lib/utils";

/**
 * Текст, который печатается по буквам и начинает заново.
 *
 * ─── Зачем ────────────────────────────────────────────────────────────────
 * Пока модель думает, пузырь ответа стоял с одним символом «…». Неподвижная
 * точка не отличается от зависшего запроса: ждать её можно и минуту, не
 * понимая, идёт ли работа. Печатающаяся строка отвечает на этот вопрос сама.
 *
 * ─── Почему по кругу, а не один раз ───────────────────────────────────────
 * Образец из запроса печатает текст ОДИН раз и останавливается. Для заголовка
 * это верно, для индикатора ожидания — нет: допечатав, он снова становится
 * неподвижным, то есть возвращает ровно ту неопределённость, ради которой
 * заводился. Здесь строка стирается и печатается снова, пока её не уберут.
 *
 * ─── Почему прогресс живёт в эффекте, а не в состоянии ────────────────────
 * В образце счётчик букв лежит в `useState`, а эффект зависит от него — то
 * есть таймер пересоздаётся на каждую букву, и смена `text` не сбрасывает
 * счётчик. Здесь один интервал на всю жизнь строки: он и печатает, и
 * начинает заново.
 */
export function TypingAnimation({
  text,
  duration = 90,
  className,
}: {
  text: string;
  /** Пауза между буквами, мс. */
  duration?: number;
  className?: string;
}) {
  const [shown, setShown] = useState("");

  useEffect(() => {
    setShown("");
    let i = 0;
    const timer = setInterval(() => {
      // Пауза в конце строки: пройдя текст, счётчик идёт дальше по пустым
      // тактам и только потом начинает заново. Без неё строка мигает.
      i = (i + 1) % (text.length + 8);
      setShown(text.slice(0, Math.min(i, text.length)));
    }, duration);
    return () => clearInterval(timer);
  }, [text, duration]);

  return (
    <span className={cn("relative inline-block", className)} aria-live="polite">
      {/*
        Ширина держится невидимой копией полного текста: без неё пузырь
        менялся бы в ширине на каждой букве, и вместе с ним дёргалась бы вся
        лента сообщений.
      */}
      <span className="invisible" aria-hidden>
        {text}
      </span>
      <span className="absolute left-0">{shown}</span>
    </span>
  );
}
