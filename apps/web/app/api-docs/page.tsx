/**
 * Документация API: /api-docs
 *
 * ─── Почему не /api ────────────────────────────────────────────────────────
 * Страница жила по адресу `/api` и уводила на форму входа. Причина не в
 * настройке, а в том, что `/api` нельзя открыть, не открыв заодно всё
 * остальное: `isPublicPath` сравнивает точным равенством и по префиксу со
 * слэшем, поэтому запись "/api" в PUBLIC_PATHS сняла бы защиту со всего дерева
 * `/api/*` — со всеми маршрутами арендатора разом. Отдельный сегмент
 * `/api-docs` открывается целиком и ни с одним обработчиком не пересекается.
 *
 * ─── Что именно опубликовано ───────────────────────────────────────────────
 * Документ перечисляет параметры и коды ответов всех маршрутов, то есть карту
 * поверхности приложения. Данных арендатора в нём нет, и защита от него не
 * зависит: она держится на сессии и политиках RLS, а не на неизвестности
 * адресов. «Try it out» без входа отвечает 401 — это и есть верное поведение.
 *
 * Под `/api-docs` не должно появляться ничего, кроме этой страницы и самой
 * спецификации: сегмент публичен целиком. За этим следит проверка в
 * evals/tests/test_openapi_coverage.py.
 */

