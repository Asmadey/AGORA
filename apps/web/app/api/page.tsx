/**
 * Документация API: /api
 *
 * ─── Почему страница может жить внутри app/api ─────────────────────────────
 * В App Router обработчики занимают `app/api/<segment>/route.ts`, а сам сегмент
 * `/api` до сих пор не был занят ничем. `page.tsx` здесь не конфликтует ни с
 * одним обработчиком: конфликт возник бы только с `app/api/route.ts`, которого
 * нет и заводить который незачем.
 *
 * ─── Страница закрыта сессией ──────────────────────────────────────────────
 * Middleware пропускает без входа только /login, /api/auth и /api/health.
 * Документация в этот список НЕ добавлена намеренно: она перечисляет параметры
 * и коды ответов всех защищённых маршрутов, то есть готовую карту поверхности
 * атаки. Открывать её наружу — отдельное решение, а не побочный эффект
 * публикации; принимать его молча за пользователя нельзя.
 *
 * Чтобы сделать её публичной, добавьте "/api" в PUBLIC_PATHS
 * (apps/web/lib/server/auth.config.ts). Внимание: `isPublicPath` сравнивает
 * точным равенством и по префиксу со слэшем, поэтому "/api" откроет саму
 * страницу и одновременно ВСЁ дерево /api/*. Публиковать документацию так
 * нельзя — нужен отдельный публичный путь вида "/api-docs".
 */

