import spec from "../../../../../packages/shared/openapi/agora.openapi.json";

/**
 * Спецификация OpenAPI 3.1 в машинном виде.
 *
 * GET /api/openapi → application/json
 *
 * Отдаётся отдельным маршрутом, а не только через страницу /api: спецификация
 * нужна не одному Swagger UI. По этому адресу её забирают генераторы клиентов,
 * линтеры контрактов и внешние каталоги API — им нужен документ, а не страница.
 *
 * ─── Почему файл, а не сборка на лету ──────────────────────────────────────
 * Спецификация лежит в packages/shared и ревьюится как исходник. Сборка её из
 * маршрутов в рантайме дала бы документ, который всегда «совпадает» с кодом и
 * потому ничего не проверяет: разъехавшийся контракт нельзя было бы заметить,
 * потому что он переписывал бы сам себя. Расхождение ловит CDD-тест
 * evals/tests/test_openapi_coverage.py, сверяя пути и методы со спецификацией.
 */

export const runtime = "nodejs";

export async function GET() {
  return Response.json(spec, {
    headers: {
      // Документ меняется вместе с выкладкой, а не между запросами.
      "Cache-Control": "public, max-age=300",
      "Content-Type": "application/json; charset=utf-8",
    },
  });
}
