import { redirect } from "next/navigation";

/**
 * Корень уводит на список исследований.
 *
 * Раздел переехал на собственный адрес `/researches`: у всех остальных разделов
 * он есть, а «Исследования» жили на корне, и сослаться на них можно было только
 * доменом. Ссылка вида `https://…/` не говорит, куда ведёт, и в переписке
 * неотличима от ссылки на вход.
 *
 * Корень при этом остаётся рабочим адресом: на него ведут закладки, письма и
 * переход после входа. `redirect`, а не копия страницы, — иначе список пришлось
 * бы держать в двух местах, и они разошлись бы на первой же правке.
 */

export default function RootPage() {
  redirect("/researches");
}
